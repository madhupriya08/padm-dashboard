ALTER TABLE DM_PADM_CHANGE_EVENT
ADD COLUMN IF NOT EXISTS AFTER_VALUE VARIANT;

ALTER TABLE DM_PADM_CAMPAIGN_OFFER
ADD COLUMN IF NOT EXISTS PROGRAM_MATCH_STATUS VARCHAR;

ALTER TABLE DM_PADM_CAMPAIGN_OFFER
ADD COLUMN IF NOT EXISTS MATCHED_PROGRAM_VERSION_NUMBER NUMBER(10,0);

ALTER TABLE DM_PADM_CAMPAIGN_SOURCE_COMPONENT
ADD COLUMN IF NOT EXISTS SOURCE_CAMPAIGN_IDENTIFICATION_CODE VARCHAR;

SELECT
      TABLE_NAME
    , COLUMN_NAME
    , DATA_TYPE
    , IS_NULLABLE
FROM DB_RISK.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RISK_SBX'
  AND
  (
        (TABLE_NAME = 'DM_PADM_CHANGE_EVENT'
            AND COLUMN_NAME IN ('BEFORE_VALUE', 'AFTER_VALUE'))
     OR (TABLE_NAME = 'DM_PADM_CAMPAIGN_OFFER'
            AND COLUMN_NAME IN ('PROGRAM_MATCH_STATUS', 'MATCHED_PROGRAM_VERSION_NUMBER'))
     OR (TABLE_NAME = 'DM_PADM_CAMPAIGN_SOURCE_COMPONENT'
            AND COLUMN_NAME = 'SOURCE_CAMPAIGN_IDENTIFICATION_CODE')
  )
ORDER BY TABLE_NAME, COLUMN_NAME;

