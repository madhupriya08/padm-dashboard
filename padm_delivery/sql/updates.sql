DELETE FROM DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS C
WHERE EXISTS
(
    SELECT 1
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
    WHERE V.CAMPAIGN_SOURCE_VERSION_ID = C.CAMPAIGN_SOURCE_VERSION_ID
      AND NOT EXISTS
        (
            SELECT 1
            FROM DM_PADM_CAMPAIGN_OFFER AS O
            WHERE O.CAMPAIGN_SOURCE_VERSION_ID = V.CAMPAIGN_SOURCE_VERSION_ID
        )
);

DELETE FROM DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
WHERE NOT EXISTS
    (
        SELECT 1
        FROM DM_PADM_CAMPAIGN_OFFER AS O
        WHERE O.CAMPAIGN_SOURCE_VERSION_ID = V.CAMPAIGN_SOURCE_VERSION_ID
    );
