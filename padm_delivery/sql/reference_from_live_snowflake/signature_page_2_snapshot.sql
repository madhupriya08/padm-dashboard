-- This template creates an immutable Signature Page 2 snapshot.
-- The application supplies Campaign ID, Calculation Run ID, version, and status.

-- Detail and subtotal presentation remains a view or export concern.
-- Snapshot rows are stored at Campaign Offer plus Segment grain.

INSERT INTO DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT
(
      SIGNATURE_PAGE_2_SNAPSHOT_ID
    , CAMPAIGN_ID
    , CALCULATION_RUN_ID
    , SIGNATURE_VERSION_NUMBER
    , CAMPAIGN_OFFER_ID
    , SEGMENT_ID
    , POPULATION_DESCRIPTION
    , SEGMENT_DESCRIPTION
    , ANNUAL_FEE
    , TEST_TYPE
    , NETWORK
    , CREDIT_BUREAU_MODEL
    , CREDIT_BUREAU_SCORE
    , CRS_MODEL
    , CRS_SCORE
    , NRM
    , QUANTITY
    , NBR
    , BOARDS
    , CPP
    , MARKETING_EXPENSE
    , UNWIND_RATE
    , PRE_UNWIND_CPA
    , POST_UNWIND_CPA
    , PROMO
    , IVR
    , UNDERWRITING_FLAG
    , PROSPECT_TYPE
    , TIMES_MAILED_0_PERCENTAGE
    , TIERS
    , PRINT_VENDOR
    , POST_UNWIND_BOARDS
    , MARKETING_PLUS_BOOKING_COSTS
    , SNAPSHOT_STATUS
)
SELECT
      UUID_STRING()
    , A.CAMPAIGN_ID
    , R.CALCULATION_RUN_ID
    , R.CAMPAIGN_WORKING_VERSION_NUMBER
    , A.CAMPAIGN_OFFER_ID
    , A.SEGMENT_ID
    , A.POPULATION_DESCRIPTION
    , O.OFFER_DESCRIPTION
    , CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1), '/', TO_VARCHAR(P.ANNUAL_FEE_YR2))
    , O.TEST_TYPE
    , P.NETWORK
    , NULL::VARCHAR
    , NULL::VARCHAR
    , NULL::VARCHAR
    , O.CRS_SCORE
    , NULL::VARCHAR
    , SUM(C.SELECTED_QUANTITY)
    , SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0)
    , SUM(C.BOOKED_PRE_UNWIND_SELECTED)
    , SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0)
    , SUM(C.MARKETING_COST_SELECTED)
    , SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)
    , SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)
    , SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)
      / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0)
    , O.PROMO_CODE
    , O.APPROVAL_CODE
    , O.UNDERWRITING_FLAG
    , O.PROSPECT_TYPE
    , NULL::NUMBER(18,8)
    , LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ')
      WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER))
    , O.PRINT_VENDOR_ID
    , SUM(C.BOOKED_POST_UNWIND_SELECTED)
    , SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)
    , R.CALCULATION_STATUS
FROM DM_PADM_OFFER_SEGMENT_ALLOCATION AS A
INNER JOIN VW_PADM_CAMPAIGN_OFFER_CURRENT AS O
      ON A.CAMPAIGN_OFFER_ID = O.CAMPAIGN_OFFER_ID
LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P
      ON O.PROGRAM_CODE = P.PROGRAM_CODE
     AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
INNER JOIN DM_PADM_CALCULATION_RUN AS R
      ON A.CAMPAIGN_ID = R.CAMPAIGN_ID
INNER JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C
      ON A.CAMPAIGN_ID = C.CAMPAIGN_ID
     AND A.SEGMENT_ID = C.SEGMENT_ID
WHERE A.IS_CURRENT = TRUE
  AND R.CALCULATION_STATUS = 'COMPLETED'
GROUP BY
      A.CAMPAIGN_ID
    , R.CALCULATION_RUN_ID
    , R.CAMPAIGN_WORKING_VERSION_NUMBER
    , A.CAMPAIGN_OFFER_ID
    , A.SEGMENT_ID
    , A.POPULATION_DESCRIPTION
    , O.OFFER_DESCRIPTION
    , P.ANNUAL_FEE_YR1
    , P.ANNUAL_FEE_YR2
    , O.TEST_TYPE
    , P.NETWORK
    , O.CRS_SCORE
    , O.PROMO_CODE
    , O.APPROVAL_CODE
    , O.UNDERWRITING_FLAG
    , O.PROSPECT_TYPE
    , O.PRINT_VENDOR_ID
    , R.CALCULATION_STATUS;
