USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE TABLE IF NOT EXISTS DM_PADM_SOURCE_LOAD_BATCH
(
    LOAD_BATCH_ID VARCHAR NOT NULL,
    SOURCE_NAME VARCHAR NOT NULL,
    SOURCE_OBJECT_NAME VARCHAR,
    SOURCE_FILE_NAME VARCHAR,
    SOURCE_AS_OF_TS TIMESTAMP_NTZ,
    LOAD_STARTED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    LOAD_COMPLETED_TS TIMESTAMP_NTZ,
    LOAD_STATUS VARCHAR NOT NULL DEFAULT 'STARTED',
    SOURCE_ROW_COUNT NUMBER(38,0),
    LOADED_ROW_COUNT NUMBER(38,0),
    REJECTED_ROW_COUNT NUMBER(38,0),
    ERROR_MESSAGE VARCHAR,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT PK_PADM_SOURCE_LOAD_BATCH PRIMARY KEY (LOAD_BATCH_ID)
);

CREATE TABLE IF NOT EXISTS DM_PADM_CHANGE_EVENT
(
    CHANGE_EVENT_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR,
    ENTITY_TYPE VARCHAR NOT NULL,
    ENTITY_ID VARCHAR NOT NULL,
    CHANGE_TYPE VARCHAR NOT NULL,
    BEFORE_VALUE VARIANT,
    AFTER_VALUE VARIANT,
    CHANGE_REASON VARCHAR,
    CHANGED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CHANGED_FIELDS VARIANT,
    CHANGED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_CHANGE_EVENT PRIMARY KEY (CHANGE_EVENT_ID)
);

CREATE TABLE IF NOT EXISTS DM_PADM_WORKFLOW_EVENT
(
    WORKFLOW_EVENT_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    FROM_STATUS VARCHAR,
    TO_STATUS VARCHAR NOT NULL,
    EVENT_REASON VARCHAR,
    EVENT_COMMENT VARCHAR,
    EVENT_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    EVENT_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_WORKFLOW_EVENT PRIMARY KEY (WORKFLOW_EVENT_ID)
);

CREATE TABLE IF NOT EXISTS DM_PADM_SCORE_RANGE_RULE_1
(
    SCORE_RANGE_RULE_ID VARCHAR NOT NULL,
    SCORE_TYPE VARCHAR NOT NULL,
    SCORE_RANGE_CODE VARCHAR NOT NULL,
    SCORE_MIN NUMBER(10,0) NOT NULL,
    SCORE_MAX NUMBER(10,0) NOT NULL,
    DISPLAY_SEQUENCE NUMBER(10,0),
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    ACTIVE_FLAG BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SCORE_RANGE_RULE PRIMARY KEY (SCORE_RANGE_RULE_ID),
    CONSTRAINT CK_PADM_SCORE_RANGE_BOUNDS CHECK
    (
        SCORE_MIN BETWEEN 0 AND 1000
        AND SCORE_MAX BETWEEN 0 AND 1000
        AND SCORE_MIN <= SCORE_MAX
    )
);

