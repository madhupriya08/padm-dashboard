-- Validate Effective NRR.
-- Expected: no rows.
SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , RESPONSE_MODEL_TIER
    , TIMES_MAILED_BUCKET
    , BASE_NRR
    , EFFECTIVE_RATE_ADJUSTMENT
    , EFFECTIVE_SEASONALITY_REDUCTION
    , EFFECTIVE_NRR
FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
WHERE ABS
    (
        EFFECTIVE_NRR
        -
        (
            BASE_NRR
            * (1 + COALESCE(EFFECTIVE_RATE_ADJUSTMENT, 0))
            * (1 - COALESCE(EFFECTIVE_SEASONALITY_REDUCTION, 0))
        )
    ) > 0.000001;

-- Validate Effective Unwind Rate.
-- Expected: no rows.
SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , RESPONSE_MODEL_TIER
    , TIMES_MAILED_BUCKET
    , HISTORICAL_UNWIND_RATE
    , EFFECTIVE_UNWIND_RATE_ADJUSTMENT
    , EFFECTIVE_UNWIND_RATE
FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
WHERE ABS
    (
        EFFECTIVE_UNWIND_RATE
        -
        (
            HISTORICAL_UNWIND_RATE
            * (1 + COALESCE(EFFECTIVE_UNWIND_RATE_ADJUSTMENT, 0))
        )
    ) > 0.000001;
