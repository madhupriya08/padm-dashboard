-- IMPORTANT: DM_PADM_CAMPAIGN_1's STATUS check constraint below uses the OLD/ORIGINAL status
-- vocabulary (DISCOVERED/DRAFT/READY_FOR_REVIEW/COMPLETED/REOPENED). This is PRE-MIGRATION DDL --
-- the real, currently-running padm/ package uses NEW/DRAFT/IN_PROGRESS/PENDING_APPROVAL/APPROVED/
-- REJECTED instead (see padm/tabs/campaign_creation.py). deploy/01_schema.sql is the migration
-- that renames these -- do not treat this file's DISCOVERED/READY_FOR_REVIEW/COMPLETED/REOPENED
-- values as current; they are historical.
--
-- Also note: DM_PADM_CAMPAIGN_OFFER below has NO CREDIT_BUREAU_MODEL/SCORE/CRS_MODEL/NRM columns
-- (only CRS_SCORE) -- wire_credit_bureau_fields.sql is what adds those 4 columns later.

USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE TABLE IF NOT EXISTS DM_PADM_CAMPAIGN_1
(
    CAMPAIGN_ID VARCHAR NOT NULL,
    SOURCE_CAMPAIGN_IDENTIFICATION_CODE VARCHAR,
    CAMPAIGN_YEAR NUMBER(4,0) NOT NULL,
    CAMPAIGN_MONTH NUMBER(2,0) NOT NULL,
    REPORTING_MONTH DATE NOT NULL,
    CAMPAIGN_SEQUENCE NUMBER(3,0) NOT NULL,
    CAMPAIGN_TYPE VARCHAR NOT NULL,
    CAMPAIGN_DISPLAY_NAME VARCHAR NOT NULL,
    SOURCE_CAMPAIGN_COUNTER_MIN NUMBER(10,0),
    SOURCE_CAMPAIGN_COUNTER_MAX NUMBER(10,0),
    SOURCE_MIN_MAIL_DATE DATE,
    SOURCE_MAX_MAIL_DATE DATE,
    STATUS VARCHAR NOT NULL DEFAULT 'DISCOVERED',
    ACTIVE_FLAG BOOLEAN NOT NULL DEFAULT FALSE,
    SOURCE_CHANGE_PENDING_FLAG BOOLEAN NOT NULL DEFAULT FALSE,
    CURRENT_SOURCE_VERSION_NUMBER NUMBER(10,0) NOT NULL DEFAULT 1,
    CURRENT_WORKING_VERSION_NUMBER NUMBER(10,0) NOT NULL DEFAULT 1,
    ROW_VERSION NUMBER(38,0) NOT NULL DEFAULT 1,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_CAMPAIGN PRIMARY KEY (CAMPAIGN_ID),
    CONSTRAINT UQ_PADM_CAMPAIGN_MONTH_TYPE UNIQUE
    (
        REPORTING_MONTH,
        CAMPAIGN_TYPE
    ),
    CONSTRAINT CK_PADM_CAMPAIGN_TYPE CHECK
    (
        CAMPAIGN_TYPE IN ('MAIN', 'REMAIL')
    ),
    CONSTRAINT CK_PADM_CAMPAIGN_STATUS CHECK
    (
        STATUS IN
        (
            'DISCOVERED',
            'DRAFT',
            'READY_FOR_REVIEW',
            'COMPLETED',
            'REOPENED'
        )
    )
);

