-- This is the real discover_campaign() MERGE that padm/repository.py's discover_campaign calls
-- into, including the plural/singular SOURCE_CAMPAIGN_IDENTIFICATION_CODES mapping.
--
-- NOTE: uses the OLD status vocabulary (DISCOVERED/DRAFT/COMPLETED/REOPENED) -- see
-- campaign_and_offer_tables.sql's note. Pre-migration.

USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Discover one campaign for each reporting month and campaign type.
-- Source identification codes are retained in source-component tables during activation.
-- They are intentionally not loaded into the campaign parent in this discovery step.

MERGE INTO DM_PADM_CAMPAIGN_1 AS T
USING
(
    SELECT
          CAMPAIGN_YEAR
        , CAMPAIGN_MONTH
        , REPORTING_MONTH
        , CAMPAIGN_SEQUENCE
        , CAMPAIGN_TYPE
        , CAMPAIGN_DISPLAY_NAME
        , SOURCE_MIN_MAIL_DATE
        , SOURCE_MAX_MAIL_DATE
    FROM VW_PADM_ACM_CAMPAIGN_CANDIDATE
) AS S

ON T.REPORTING_MONTH = S.REPORTING_MONTH
AND T.CAMPAIGN_TYPE = S.CAMPAIGN_TYPE

WHEN MATCHED
AND T.STATUS IN ('DISCOVERED', 'DRAFT', 'REOPENED')
AND
(
    COALESCE(T.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')

    OR COALESCE(T.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')

    OR COALESCE(T.CAMPAIGN_DISPLAY_NAME, '')
    <>
    COALESCE(S.CAMPAIGN_DISPLAY_NAME, '')

    OR COALESCE(T.CAMPAIGN_SEQUENCE, -1)
    <>
    COALESCE(S.CAMPAIGN_SEQUENCE, -1)
)
THEN UPDATE SET
      T.CAMPAIGN_YEAR = S.CAMPAIGN_YEAR
    , T.CAMPAIGN_MONTH = S.CAMPAIGN_MONTH
    , T.CAMPAIGN_SEQUENCE = S.CAMPAIGN_SEQUENCE
    , T.CAMPAIGN_DISPLAY_NAME = S.CAMPAIGN_DISPLAY_NAME
    , T.SOURCE_MIN_MAIL_DATE = S.SOURCE_MIN_MAIL_DATE
    , T.SOURCE_MAX_MAIL_DATE = S.SOURCE_MAX_MAIL_DATE
    , T.SOURCE_CHANGE_PENDING_FLAG =
        IFF(T.STATUS = 'DISCOVERED', FALSE, TRUE)
    , T.ROW_VERSION = COALESCE(T.ROW_VERSION, 0) + 1
    , T.UPDATED_BY = CURRENT_USER()
    , T.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN MATCHED
AND T.STATUS = 'COMPLETED'
AND
(
    COALESCE(T.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')

    OR COALESCE(T.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')
)
THEN UPDATE SET
      T.SOURCE_CHANGE_PENDING_FLAG = TRUE
    , T.ROW_VERSION = COALESCE(T.ROW_VERSION, 0) + 1
    , T.UPDATED_BY = CURRENT_USER()
    , T.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT
(
      CAMPAIGN_ID
    , CAMPAIGN_YEAR
    , CAMPAIGN_MONTH
    , REPORTING_MONTH
    , CAMPAIGN_SEQUENCE
    , CAMPAIGN_TYPE
    , CAMPAIGN_DISPLAY_NAME
    , SOURCE_MIN_MAIL_DATE
    , SOURCE_MAX_MAIL_DATE
    , STATUS
    , ACTIVE_FLAG
    , SOURCE_CHANGE_PENDING_FLAG
    , ROW_VERSION
    , CREATED_BY
    , CREATED_TS
    , UPDATED_BY
    , UPDATED_TS
)
VALUES
(
      UUID_STRING()
    , S.CAMPAIGN_YEAR
    , S.CAMPAIGN_MONTH
    , S.REPORTING_MONTH
    , S.CAMPAIGN_SEQUENCE
    , S.CAMPAIGN_TYPE
    , S.CAMPAIGN_DISPLAY_NAME
    , S.SOURCE_MIN_MAIL_DATE
    , S.SOURCE_MAX_MAIL_DATE
    , 'DISCOVERED'
    , FALSE
    , FALSE
    , 1
    , CURRENT_USER()
    , CURRENT_TIMESTAMP()
    , CURRENT_USER()
    , CURRENT_TIMESTAMP()
);

-- Review discovered campaigns.
SELECT
      CAMPAIGN_ID
    , REPORTING_MONTH
    , CAMPAIGN_SEQUENCE
    , CAMPAIGN_TYPE
    , CAMPAIGN_DISPLAY_NAME
    , SOURCE_MIN_MAIL_DATE
    , SOURCE_MAX_MAIL_DATE
    , STATUS
    , ACTIVE_FLAG
    , SOURCE_CHANGE_PENDING_FLAG
    , ROW_VERSION
FROM DM_PADM_CAMPAIGN_1
ORDER BY
      REPORTING_MONTH DESC
    , CAMPAIGN_TYPE;

-- Expected result: no rows.
SELECT
      REPORTING_MONTH
    , CAMPAIGN_TYPE
    , COUNT(*) AS ROW_COUNT
FROM DM_PADM_CAMPAIGN_1
GROUP BY
      REPORTING_MONTH
    , CAMPAIGN_TYPE
HAVING COUNT(*) > 1;
