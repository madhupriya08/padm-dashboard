USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE TABLE IF NOT EXISTS DM_PADM_SEGMENT_1
(
    SEGMENT_ID VARCHAR NOT NULL,
    SEGMENT_NAME VARCHAR NOT NULL,
    SOURCE_NAME VARCHAR,
    SCORE_TYPE VARCHAR NOT NULL,
    SCORE_MIN NUMBER(10,0) NOT NULL,
    SCORE_MAX NUMBER(10,0) NOT NULL,
    PROSPECT_SEGMENT_TYPE VARCHAR NOT NULL,
    ANNUAL_FEE VARCHAR,
    NETWORK VARCHAR,
    MLA_FLAG VARCHAR,
    MAIL_REMAIL VARCHAR,
    RESPONSE_MODEL_TYPE VARCHAR,
    RISK_SCORE_TYPE VARCHAR,
    ACTIVE_FLAG BOOLEAN NOT NULL DEFAULT TRUE,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    ROW_VERSION NUMBER(38,0) NOT NULL DEFAULT 1,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SEGMENT PRIMARY KEY (SEGMENT_ID),
    CONSTRAINT CK_PADM_SEGMENT_SCORE_RANGE CHECK
    (
        SCORE_MIN BETWEEN 0 AND 1000
        AND SCORE_MAX BETWEEN 0 AND 1000
        AND SCORE_MIN <= SCORE_MAX
    )
);

CREATE TABLE IF NOT EXISTS DM_PADM_CAMPAIGN_SEGMENT_1
(
    CAMPAIGN_SEGMENT_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    WORKING_VERSION_NUMBER NUMBER(10,0) NOT NULL,
    SEGMENT_STATUS VARCHAR NOT NULL DEFAULT 'ACTIVE',
    SOURCE_CAMPAIGN_ID VARCHAR,
    SOURCE_SEGMENT_ID VARCHAR,
    INITIALIZATION_METHOD VARCHAR NOT NULL,
    VALID_FROM_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO_TS TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    CHANGE_REASON VARCHAR,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_CAMPAIGN_SEGMENT PRIMARY KEY (CAMPAIGN_SEGMENT_ID)
);

CREATE TABLE IF NOT EXISTS DM_PADM_OFFER_SEGMENT_ALLOCATION
(
    OFFER_SEGMENT_ALLOCATION_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    CAMPAIGN_OFFER_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    WORKING_VERSION_NUMBER NUMBER(10,0) NOT NULL,
    POPULATION_GROUP_RULE_ID VARCHAR,
    POPULATION_DESCRIPTION VARCHAR,
    ALLOCATION_STATUS VARCHAR NOT NULL DEFAULT 'ACTIVE',
    SOURCE_CAMPAIGN_ID VARCHAR,
    SOURCE_ALLOCATION_ID VARCHAR,
    INITIALIZATION_METHOD VARCHAR NOT NULL,
    VALID_FROM_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO_TS TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    CHANGE_REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_OFFER_SEGMENT_ALLOCATION PRIMARY KEY (OFFER_SEGMENT_ALLOCATION_ID)
);
