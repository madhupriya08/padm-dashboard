USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE TABLE IF NOT EXISTS DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
(
    CAMPAIGN_ASSUMPTION_VERSION_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    VERSION_NUMBER NUMBER(10,0) NOT NULL,
    CPP NUMBER(18,6),
    UNIT_COST NUMBER(18,4),
    RATE_ADJUSTMENT NUMBER(18,8),
    SEASONALITY_REDUCTION NUMBER(18,8),
    UNWIND_RATE_ADJUSTMENT NUMBER(18,8),
    EFFECTIVE_FROM_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    EFFECTIVE_TO_TS TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    CHANGE_REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_CAMPAIGN_ASSUMPTION_VERSION PRIMARY KEY (CAMPAIGN_ASSUMPTION_VERSION_ID),
    CONSTRAINT UQ_PADM_CAMPAIGN_ASSUMPTION_VERSION UNIQUE
    (
        CAMPAIGN_ID,
        VERSION_NUMBER
    )
);

CREATE TABLE IF NOT EXISTS DM_PADM_SEGMENT_ASSUMPTION_VERSION
(
    SEGMENT_ASSUMPTION_VERSION_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    VERSION_NUMBER NUMBER(10,0) NOT NULL,
    CPP_OVERRIDE NUMBER(18,6),
    UNIT_COST_OVERRIDE NUMBER(18,4),
    RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    SEASONALITY_REDUCTION_OVERRIDE NUMBER(18,8),
    UNWIND_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    EFFECTIVE_FROM_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    EFFECTIVE_TO_TS TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    CHANGE_REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SEGMENT_ASSUMPTION_VERSION PRIMARY KEY (SEGMENT_ASSUMPTION_VERSION_ID),
    CONSTRAINT UQ_PADM_SEGMENT_ASSUMPTION_VERSION UNIQUE
    (
        CAMPAIGN_ID,
        SEGMENT_ID,
        VERSION_NUMBER
    )
);
