SELECT E.VIEW_NAME
FROM EXPECTED_VIEW AS E
LEFT JOIN DB_RISK.INFORMATION_SCHEMA.VIEWS AS V
        ON V.TABLE_SCHEMA = CURRENT_SCHEMA()
       AND V.TABLE_NAME = E.VIEW_NAME
WHERE V.TABLE_NAME IS NULL;

-- Check campaign candidates by month and type.
SELECT
      REPORTING_MONTH
    , CAMPAIGN_TYPE
    , COUNT(*) AS CANDIDATE_COUNT
FROM VW_PADM_ACM_CAMPAIGN_CANDIDATE
GROUP BY
      REPORTING_MONTH
    , CAMPAIGN_TYPE
HAVING COUNT(*) > 1;

-- Check that candidate offers are unique within the source campaign.
SELECT
      SOURCE_CAMPAIGN_IDENTIFICATION_CODE
    , OFFER_RESERVATION_CODE
    , COUNT(*) AS ROW_COUNT
FROM VW_PADM_ACM_OFFER_SOURCE
GROUP BY
      SOURCE_CAMPAIGN_IDENTIFICATION_CODE
    , OFFER_RESERVATION_CODE
HAVING COUNT(*) > 1;

-- Confirm the Program join did not multiply source offers.
SELECT
      SOURCE_CAMPAIGN_IDENTIFICATION_CODE
    , OFFER_RESERVATION_CODE
    , PROGRAM_CODE
    , PROGRAM_VERSION_NUMBER
    , COUNT(*) AS ROW_COUNT
FROM VW_PADM_ACM_OFFER_SOURCE
GROUP BY
      SOURCE_CAMPAIGN_IDENTIFICATION_CODE
    , OFFER_RESERVATION_CODE
    , PROGRAM_CODE
    , PROGRAM_VERSION_NUMBER
HAVING COUNT(*) > 1;

-- Confirm there is no more than one current source version for a campaign.
SELECT
      CAMPAIGN_ID
    , COUNT(*) AS CURRENT_VERSION_COUNT
FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
WHERE IS_CURRENT = TRUE
GROUP BY CAMPAIGN_ID
HAVING COUNT(*) > 1;

-- Confirm there is no more than one current campaign assumption version.
SELECT
      CAMPAIGN_ID
    , COUNT(*) AS CURRENT_VERSION_COUNT
FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
WHERE IS_CURRENT = TRUE
GROUP BY CAMPAIGN_ID
HAVING COUNT(*) > 1;

-- Confirm there is no more than one current Segment override version.
SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , COUNT(*) AS CURRENT_VERSION_COUNT
FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
WHERE IS_CURRENT = TRUE
GROUP BY
      CAMPAIGN_ID
    , SEGMENT_ID
HAVING COUNT(*) > 1;

-- Check active CDE version uniqueness.
SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , COUNT(*) AS ACTIVE_VERSION_COUNT
FROM DM_PADM_CDE_LOAD_BATCH
WHERE ACTIVE_FLAG = TRUE
GROUP BY
      CAMPAIGN_ID
    , SEGMENT_ID
HAVING COUNT(*) > 1;

-- Check calculation formulas after data is loaded.
SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , RESPONSE_MODEL_TIER
    , TIMES_MAILED_BUCKET
    , CDE_VOLUME
    , EMS_REDUCTION_RATE
    , POST_EMS_VOLUME
FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
WHERE ABS
      (
            POST_EMS_VOLUME
          - CDE_VOLUME * (1 - EMS_REDUCTION_RATE)
      ) > 0.000001;

SELECT
      CAMPAIGN_ID
    , SEGMENT_ID
    , RESPONSE_MODEL_TIER
    , TIMES_MAILED_BUCKET
    , POST_EMS_VOLUME
    , SELECTION_PERCENTAGE
    , SELECTED_QUANTITY
FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
WHERE ABS
      (
            SELECTED_QUANTITY
          - ROUND(POST_EMS_VOLUME * SELECTION_PERCENTAGE, 0)
      ) > 0.000001;

