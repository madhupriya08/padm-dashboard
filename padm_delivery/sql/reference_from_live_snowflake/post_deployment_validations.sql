      SELECT COLUMN1 AS VIEW_NAME
      FROM VALUES
            ('VW_PADM_ACM_CAMPAIGN_CANDIDATE')
          , ('VW_PADM_ACM_OFFER_SOURCE')
          , ('VW_PADM_CAMPAIGN_CURRENT')
