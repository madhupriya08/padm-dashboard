-- Idempotent -- safe to re-run.
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Pre Signature Page's 3 tracking fields (Volume, Quantity %/units, Owner/Approver), soft-versioned per offer.
CREATE TABLE IF NOT EXISTS DM_PADM_PRE_SIGNATURE_DETAIL
(
    PRE_SIGNATURE_DETAIL_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    CAMPAIGN_OFFER_ID VARCHAR NOT NULL,
    TOTAL_AVAILABLE_VOLUME NUMBER(38,0),
    QUANTITY_PERCENTAGE VARCHAR,
    QUANTITY_UNITS VARCHAR,
    OWNER_APPROVER VARCHAR,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    CHANGE_REASON VARCHAR,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO_TS TIMESTAMP_NTZ,
    CONSTRAINT PK_PADM_PRE_SIGNATURE_DETAIL PRIMARY KEY (PRE_SIGNATURE_DETAIL_ID)
);

-- Covers an install where this table already exists with the old single QUANTITY column (left in place, unused).
ALTER TABLE DM_PADM_PRE_SIGNATURE_DETAIL ADD COLUMN IF NOT EXISTS QUANTITY_PERCENTAGE VARCHAR;
ALTER TABLE DM_PADM_PRE_SIGNATURE_DETAIL ADD COLUMN IF NOT EXISTS QUANTITY_UNITS VARCHAR;
