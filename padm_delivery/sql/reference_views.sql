CREATE OR REPLACE VIEW VW_PADM_NRR_CURRENT AS
WITH MAPPED AS
(
    SELECT
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
        , SUM(H.MAIL_QUANTITY) AS MAIL_QUANTITY
        , SUM(H.APPLIED_COUNT) AS APPLIED_COUNT
        , SUM(H.BOARDED_COUNT) AS BOARDED_COUNT
    FROM DM_PADM_NRR_HISTORY_CELL AS H
    INNER JOIN DM_PADM_HISTORY_SEGMENT_MAP AS M
            ON H.HISTORY_SEGMENT_KEY_ID = M.HISTORY_SEGMENT_KEY_ID
           AND M.ACTIVE_FLAG = TRUE
           AND COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) >= M.VALID_FROM
           AND
           (
                M.VALID_TO IS NULL
             OR COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) < M.VALID_TO
           )
    GROUP BY
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
),
SEGMENT_FALLBACK AS
(
    SELECT
          SEGMENT_ID
        , CAMPAIGN_TYPE
        , SUM(MAIL_QUANTITY) AS MAIL_QUANTITY
        , SUM(BOARDED_COUNT) AS BOARDED_COUNT
    FROM MAPPED
    GROUP BY
          SEGMENT_ID
        , CAMPAIGN_TYPE
)
SELECT
      M.SEGMENT_ID
    , M.CAMPAIGN_TYPE
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.MAIL_QUANTITY
    , M.APPLIED_COUNT
    , M.BOARDED_COUNT
    , M.BOARDED_COUNT / NULLIF(M.MAIL_QUANTITY, 0) AS BASE_NRR
    , 'EXACT_CELL' AS NRR_SOURCE
FROM MAPPED AS M

UNION ALL

SELECT
      F.SEGMENT_ID
    , F.CAMPAIGN_TYPE
    , NULL::NUMBER AS RESPONSE_MODEL_TIER
    , NULL::VARCHAR AS TIMES_MAILED_BUCKET
    , F.MAIL_QUANTITY
    , NULL::NUMBER AS APPLIED_COUNT
    , F.BOARDED_COUNT
    , F.BOARDED_COUNT / NULLIF(F.MAIL_QUANTITY, 0) AS BASE_NRR
    , 'SEGMENT_FALLBACK' AS NRR_SOURCE
FROM SEGMENT_FALLBACK AS F;

CREATE OR REPLACE VIEW VW_PADM_UNWIND_CURRENT AS
WITH MAPPED AS
(
    SELECT
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
        , SUM(H.BOARD_COUNT) AS BOARD_COUNT
        , SUM(H.UNWIND_COUNT) AS UNWIND_COUNT
    FROM DM_PADM_UNWIND_HISTORY_CELL AS H
    INNER JOIN DM_PADM_HISTORY_SEGMENT_MAP AS M
            ON H.HISTORY_SEGMENT_KEY_ID = M.HISTORY_SEGMENT_KEY_ID
           AND M.ACTIVE_FLAG = TRUE
           AND COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) >= M.VALID_FROM
           AND
           (
                M.VALID_TO IS NULL
             OR COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) < M.VALID_TO
           )
    GROUP BY
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
),
SEGMENT_FALLBACK AS
(
    SELECT
          SEGMENT_ID
        , CAMPAIGN_TYPE
        , SUM(BOARD_COUNT) AS BOARD_COUNT
        , SUM(UNWIND_COUNT) AS UNWIND_COUNT
    FROM MAPPED
    GROUP BY
          SEGMENT_ID
        , CAMPAIGN_TYPE
)
SELECT
      M.SEGMENT_ID
    , M.CAMPAIGN_TYPE
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.BOARD_COUNT
    , M.UNWIND_COUNT
    , M.UNWIND_COUNT / NULLIF(M.BOARD_COUNT, 0) AS HISTORICAL_UNWIND_RATE
    , 'EXACT_CELL' AS UNWIND_SOURCE
FROM MAPPED AS M

UNION ALL

SELECT
      F.SEGMENT_ID
    , F.CAMPAIGN_TYPE
    , NULL::NUMBER AS RESPONSE_MODEL_TIER
    , NULL::VARCHAR AS TIMES_MAILED_BUCKET
    , F.BOARD_COUNT
    , F.UNWIND_COUNT
    , F.UNWIND_COUNT / NULLIF(F.BOARD_COUNT, 0) AS HISTORICAL_UNWIND_RATE
    , 'SEGMENT_FALLBACK' AS UNWIND_SOURCE
FROM SEGMENT_FALLBACK AS F;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_CALCULATION_CURRENT AS
WITH GRID AS
(
    SELECT
          C.CAMPAIGN_ID
        , C.CAMPAIGN_TYPE
        , G.SEGMENT_ID
        , G.RESPONSE_MODEL_TIER
        , G.TIMES_MAILED_BUCKET
        , G.CDE_VOLUME
        , COALESCE
          (
                E1.EMS_REDUCTION_RATE,
                E2.EMS_REDUCTION_RATE,
                E3.EMS_REDUCTION_RATE
          ) AS EMS_REDUCTION_RATE
        , S.SELECTION_PERCENTAGE
        , A.EFFECTIVE_CPP
        , A.EFFECTIVE_UNIT_COST
        , A.EFFECTIVE_RATE_ADJUSTMENT
        , A.EFFECTIVE_SEASONALITY_REDUCTION
        , A.EFFECTIVE_UNWIND_RATE_ADJUSTMENT
    FROM VW_PADM_CDE_GRID_CURRENT AS G
    INNER JOIN DM_PADM_CAMPAIGN_1 AS C
            ON G.CAMPAIGN_ID = C.CAMPAIGN_ID
    LEFT JOIN VW_PADM_SELECTION_CURRENT AS S
            ON G.CAMPAIGN_ID = S.CAMPAIGN_ID
           AND G.SEGMENT_ID = S.SEGMENT_ID
           AND G.RESPONSE_MODEL_TIER = S.RESPONSE_MODEL_TIER
           AND G.TIMES_MAILED_BUCKET = S.TIMES_MAILED_BUCKET
    LEFT JOIN VW_PADM_EFFECTIVE_ASSUMPTION AS A
            ON G.CAMPAIGN_ID = A.CAMPAIGN_ID
           AND G.SEGMENT_ID = A.SEGMENT_ID
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E1
            ON G.CAMPAIGN_ID = E1.CAMPAIGN_ID
           AND G.SEGMENT_ID = E1.SEGMENT_ID
           AND G.RESPONSE_MODEL_TIER = E1.RESPONSE_MODEL_TIER
           AND G.TIMES_MAILED_BUCKET = E1.TIMES_MAILED_BUCKET
           AND E1.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E2
            ON G.CAMPAIGN_ID = E2.CAMPAIGN_ID
           AND G.SEGMENT_ID = E2.SEGMENT_ID
           AND E2.RESPONSE_MODEL_TIER IS NULL
           AND E2.TIMES_MAILED_BUCKET IS NULL
           AND E2.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E3
            ON G.CAMPAIGN_ID = E3.CAMPAIGN_ID
           AND E3.SEGMENT_ID IS NULL
           AND E3.RESPONSE_MODEL_TIER IS NULL
           AND E3.TIMES_MAILED_BUCKET IS NULL
           AND E3.IS_CURRENT = TRUE
),
HISTORY AS
(
    SELECT
          G.CAMPAIGN_ID
        , G.CAMPAIGN_TYPE
        , G.SEGMENT_ID
        , G.RESPONSE_MODEL_TIER
        , G.TIMES_MAILED_BUCKET
        , G.CDE_VOLUME
        , G.EMS_REDUCTION_RATE
        , G.SELECTION_PERCENTAGE
        , G.EFFECTIVE_CPP
        , G.EFFECTIVE_UNIT_COST
        , G.EFFECTIVE_RATE_ADJUSTMENT
        , G.EFFECTIVE_SEASONALITY_REDUCTION
        , G.EFFECTIVE_UNWIND_RATE_ADJUSTMENT
        , COALESCE(NE.BASE_NRR, NF.BASE_NRR) AS BASE_NRR
        , CASE WHEN NE.BASE_NRR IS NOT NULL THEN 'EXACT_CELL' ELSE NF.NRR_SOURCE END AS NRR_SOURCE
        , COALESCE(UE.HISTORICAL_UNWIND_RATE, UF.HISTORICAL_UNWIND_RATE) AS HISTORICAL_UNWIND_RATE
        , CASE WHEN UE.HISTORICAL_UNWIND_RATE IS NOT NULL THEN 'EXACT_CELL' ELSE UF.UNWIND_SOURCE END AS UNWIND_SOURCE
    FROM GRID AS G
    LEFT JOIN VW_PADM_NRR_CURRENT AS NE
            ON G.SEGMENT_ID = NE.SEGMENT_ID
           AND G.CAMPAIGN_TYPE = NE.CAMPAIGN_TYPE
           AND G.RESPONSE_MODEL_TIER = NE.RESPONSE_MODEL_TIER
           AND G.TIMES_MAILED_BUCKET = NE.TIMES_MAILED_BUCKET
           AND NE.NRR_SOURCE = 'EXACT_CELL'
    LEFT JOIN VW_PADM_NRR_CURRENT AS NF
            ON G.SEGMENT_ID = NF.SEGMENT_ID
           AND G.CAMPAIGN_TYPE = NF.CAMPAIGN_TYPE
           AND NF.NRR_SOURCE = 'SEGMENT_FALLBACK'
    LEFT JOIN VW_PADM_UNWIND_CURRENT AS UE
            ON G.SEGMENT_ID = UE.SEGMENT_ID
           AND G.CAMPAIGN_TYPE = UE.CAMPAIGN_TYPE
           AND G.RESPONSE_MODEL_TIER = UE.RESPONSE_MODEL_TIER
           AND G.TIMES_MAILED_BUCKET = UE.TIMES_MAILED_BUCKET
           AND UE.UNWIND_SOURCE = 'EXACT_CELL'
    LEFT JOIN VW_PADM_UNWIND_CURRENT AS UF
            ON G.SEGMENT_ID = UF.SEGMENT_ID
           AND G.CAMPAIGN_TYPE = UF.CAMPAIGN_TYPE
           AND UF.UNWIND_SOURCE = 'SEGMENT_FALLBACK'
),
MEASURES AS
    (
        SELECT
            H.CAMPAIGN_ID
          , H.CAMPAIGN_TYPE
          , H.SEGMENT_ID
          , H.RESPONSE_MODEL_TIER
          , H.TIMES_MAILED_BUCKET
          , H.CDE_VOLUME
          , H.EMS_REDUCTION_RATE
          , H.CDE_VOLUME * (1 - H.EMS_REDUCTION_RATE) AS POST_EMS_VOLUME
          , COALESCE(H.SELECTION_PERCENTAGE, 0) AS SELECTION_PERCENTAGE
          , ROUND
            (
                H.CDE_VOLUME
                * (1 - H.EMS_REDUCTION_RATE)
                * COALESCE(H.SELECTION_PERCENTAGE, 0),
                0
            ) AS SELECTED_QUANTITY
          , H.BASE_NRR
          , H.BASE_NRR
            * (1 + COALESCE(H.EFFECTIVE_RATE_ADJUSTMENT, 0))
            * (1 - COALESCE(H.EFFECTIVE_SEASONALITY_REDUCTION, 0))
                AS EFFECTIVE_NRR
          , H.HISTORICAL_UNWIND_RATE
          , H.HISTORICAL_UNWIND_RATE
            * (1 + COALESCE(H.EFFECTIVE_UNWIND_RATE_ADJUSTMENT, 0))
                AS EFFECTIVE_UNWIND_RATE
          , H.EFFECTIVE_CPP
          , H.EFFECTIVE_UNIT_COST
          , H.NRR_SOURCE
          , H.UNWIND_SOURCE
        FROM HISTORY AS H
    )
SELECT
      M.CAMPAIGN_ID
    , M.CAMPAIGN_TYPE
    , M.SEGMENT_ID
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.CDE_VOLUME
    , M.EMS_REDUCTION_RATE
    , M.POST_EMS_VOLUME
    , M.SELECTION_PERCENTAGE
    , M.SELECTED_QUANTITY
    , M.BASE_NRR
    , M.EFFECTIVE_NRR
    , IFF(M.SELECTED_QUANTITY > 0, M.EFFECTIVE_NRR, NULL) AS SELECTED_NRR
    , M.HISTORICAL_UNWIND_RATE
    , M.EFFECTIVE_UNWIND_RATE
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR AS BOOKED_PRE_UNWIND_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR AS BOOKED_PRE_UNWIND_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_CPP AS MARKETING_COST_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_CPP AS MARKETING_COST_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST AS BOOKING_COST_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST AS BOOKING_COST_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNWIND_RATE AS EXPECTED_UNWINDS_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNWIND_RATE AS EXPECTED_UNWINDS_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE) AS BOOKED_POST_UNWIND_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE) AS BOOKED_POST_UNWIND_SELECTED
    , (M.POST_EMS_VOLUME * M.EFFECTIVE_CPP)
      / NULLIF(M.POST_EMS_VOLUME * M.EFFECTIVE_NRR, 0)
        AS PRE_UNWIND_CPA_UNIVERSE
    , (M.SELECTED_QUANTITY * M.EFFECTIVE_CPP)
      / NULLIF(M.SELECTED_QUANTITY * M.EFFECTIVE_NRR, 0)
        AS PRE_UNWIND_CPA_SELECTED
    , (
          (M.POST_EMS_VOLUME * M.EFFECTIVE_CPP)
          + (M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST)
      )
      / NULLIF
      (
          M.POST_EMS_VOLUME
          * M.EFFECTIVE_NRR
          * (1 - M.EFFECTIVE_UNWIND_RATE),
          0
      ) AS POST_UNWIND_CPA_UNIVERSE
    , (
          (M.SELECTED_QUANTITY * M.EFFECTIVE_CPP)
          + (M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST)
      )
      / NULLIF
      (
          M.SELECTED_QUANTITY
          * M.EFFECTIVE_NRR
          * (1 - M.EFFECTIVE_UNWIND_RATE),
          0
      ) AS POST_UNWIND_CPA_SELECTED
    , M.EFFECTIVE_CPP
    , M.EFFECTIVE_UNIT_COST
    , M.NRR_SOURCE
    , M.UNWIND_SOURCE
FROM MEASURES AS M;

CREATE OR REPLACE VIEW VW_PADM_CDE_GRID_CURRENT
AS
SELECT
      D.CDE_LOAD_BATCH_ID
    , D.CDE_VERSION_NUMBER
    , D.CAMPAIGN_ID
    , D.SEGMENT_ID
    , D.TRM10_TIER AS RESPONSE_MODEL_TIER
    , D.TIMES_MAILED_BUCKET
    , SUM(D.DISTINCT_EPIN_COUNT)::NUMBER(38,6) AS CDE_VOLUME
