CREATE OR REPLACE VIEW VW_PADM_EFFECTIVE_ASSUMPTION AS
SELECT
      CS.CAMPAIGN_ID
    , CS.SEGMENT_ID
    , COALESCE(SA.CPP_OVERRIDE, CA.CPP) AS EFFECTIVE_CPP
    , COALESCE(SA.UNIT_COST_OVERRIDE, CA.UNIT_COST) AS EFFECTIVE_UNIT_COST
    , COALESCE(SA.RATE_ADJUSTMENT_OVERRIDE, CA.RATE_ADJUSTMENT, 0) AS EFFECTIVE_RATE_ADJUSTMENT
    , COALESCE(SA.SEASONALITY_REDUCTION_OVERRIDE, CA.SEASONALITY_REDUCTION, 0) AS EFFECTIVE_SEASONALITY_REDUCTION
    , COALESCE(SA.UNWIND_RATE_ADJUSTMENT_OVERRIDE, CA.UNWIND_RATE_ADJUSTMENT, 0) AS EFFECTIVE_UNWIND_RATE_ADJUSTMENT
FROM DM_PADM_CAMPAIGN_SEGMENT_1 AS CS
LEFT JOIN VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS CA
    ON CS.CAMPAIGN_ID = CA.CAMPAIGN_ID
LEFT JOIN VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS SA
    ON CS.CAMPAIGN_ID = SA.CAMPAIGN_ID
   AND CS.SEGMENT_ID = SA.SEGMENT_ID
WHERE CS.IS_CURRENT = TRUE;

