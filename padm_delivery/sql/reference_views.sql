      D.CDE_LOAD_BATCH_ID
    , D.CDE_VERSION_NUMBER
    , D.CAMPAIGN_ID
    , D.SEGMENT_ID
    , D.TRM10_TIER
    , D.TIMES_MAILED_BUCKET;

