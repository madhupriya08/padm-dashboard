USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

SELECT DISTINCT CAMPAIGN_SOURCE FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
WHERE MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01';

SELECT DISTINCT CAMPAIGN_SOURCE FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
WHERE MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01';

-- CAMPAIGN_SOURCE on the raw mailfile tables is NOT 'PADM'/'MAP'/'PAREMAIL' -- it's a single
-- letter/digit code (confirmed from the real classification script: 'V','E','A','W','C','D','M',
-- 'R','N','I','G','B','J','Q' for Experian; 'U','1'-'9','H','L','Z' for TransUnion). CAMPAIGN_WAVE
-- below reproduces that script's own CAMPAIGN_SOURCE -> MAIN/REMAIL mapping exactly (its REMAIL
-- codes are additionally gated on CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05'), kept here).
-- PROSPECT_SEGMENT_TYPE is carried through for completeness/future use but is not currently part
-- of the join below (the original script didn't join on it either -- only SOURCE_NAME/SCORE_TYPE/
-- SCORE_MIN/SCORE_MAX). The former 'LIFT' leg is dropped: LIFT_SCORE isn't a peer bureau score
-- type the way VS3/VS4 are (it buckets into RESPONSE_MODEL_TIER instead, per the same reference
-- script), so no DM_PADM_SCORE_RANGE_RULE_1 row should exist for it and that leg always matched 0.
INSERT INTO DM_PADM_MAILFILE_CELL
    (MAILFILE_CELL_ID, CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
     MAIL_QUANTITY, IS_CURRENT)
WITH RAW_MAILFILE AS
(
    SELECT 'EXPERIAN' AS SOURCE,
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','C','D','M','R','N','W','V','E') THEN 'MAIN'
               WHEN CAMPAIGN_SOURCE IN ('I','G','J','B','Q')
                    AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'REMAIL'
           END AS CAMPAIGN_WAVE,
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END AS PROSPECT_SEGMENT_TYPE,
           UPPER(COALESCE(MLA_INDICATOR, 'N')) AS MLA_FLAG, RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE,
           RESPONSE_MODEL_TIER, MAIL_DATE,
           CASE WHEN TIMES_MAILED_12_MONTH_COUNT >= 9 THEN '9+' ELSE TO_VARCHAR(TIMES_MAILED_12_MONTH_COUNT) END AS TIMES_MAILED_BUCKET,
           'VS3' AS BUREAU_SCORE_TYPE, PRESCREEN_VANTAGE_V3 AS RAW_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    UNION ALL
    SELECT 'EXPERIAN',
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','C','D','M','R','N','W','V','E') THEN 'MAIN'
               WHEN CAMPAIGN_SOURCE IN ('I','G','J','B','Q')
                    AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'REMAIL'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')), RESPONSE_MODEL_TYPE,
           RISK_SCORE_TYPE, RESPONSE_MODEL_TIER, MAIL_DATE,
           CASE WHEN TIMES_MAILED_12_MONTH_COUNT >= 9 THEN '9+' ELSE TO_VARCHAR(TIMES_MAILED_12_MONTH_COUNT) END,
           'VS4', PRESCREEN_VANTAGE_V4
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V4 IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    UNION ALL
    SELECT 'TRANSUNION',
           CASE
               WHEN CAMPAIGN_SOURCE IN ('U','1','2','3','4','5','6','7') THEN 'MAIN'
               WHEN CAMPAIGN_SOURCE IN ('H','8','9','L','Z')
                    AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'REMAIL'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE = 'U' THEN 'PROSPECTING'
               WHEN CAMPAIGN_SOURCE IN ('3','4','5','6','7','8','9','L','Z') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE = 'H' AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'RETARGETING'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')), RESPONSE_MODEL_TYPE,
           RISK_SCORE_TYPE, RESPONSE_MODEL_TIER, MAIL_DATE,
           CASE WHEN TM12_3B >= 9 THEN '9+' ELSE TO_VARCHAR(TM12_3B) END,
           'VS3', PRESCREEN_VANTAGE_V3
    FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    -- T_MAP_MAILFILE: existing-customer "multiple account" offers. CAMPAIGN_SOURCE is a constant
    -- 'S' across the whole table (confirmed via SELECT DISTINCT) -- always folds into REMAIL per
    -- the campaign model (MAP + PAREMAIL -> REMAIL). Classified RETARGETING: a repeat-contact offer
    -- to a current customer, not new-prospect outreach. JUDGMENT CALL, not a confirmed fact: this
    -- table has no RESPONSE_MODEL_TIER or TIMES_MAILED column at all, so both are set to a single
    -- placeholder value (0 / '0') meaning "no tier/times-mailed breakdown exists for MAP" -- flag
    -- this to the business; if MAP volume needs its own real tier dimension later, don't just widen
    -- this placeholder, trace back to a real source column first.
    UNION ALL
    SELECT 'MAP', 'REMAIL', 'RETARGETING', 'N', NULL, NULL, 0, MAIL_DATE, '0',
           'VS3', TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0))
    FROM CSTONE_BIZ.REFERENCE.T_MAP_MAILFILE
    WHERE TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0)) IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'
),
MATCHED AS
(
    SELECT
        C.CAMPAIGN_ID,
        S.SEGMENT_ID,
        M.SOURCE AS SOURCE_NAME,
        CAST(M.RESPONSE_MODEL_TIER AS NUMBER(10,0)) AS RESPONSE_MODEL_TIER,
        M.TIMES_MAILED_BUCKET
    FROM RAW_MAILFILE AS M
    INNER JOIN DM_PADM_SCORE_RANGE_RULE_1 AS R
            ON UPPER(M.BUREAU_SCORE_TYPE) = UPPER(R.SCORE_TYPE)
           AND M.RAW_SCORE BETWEEN R.SCORE_MIN AND R.SCORE_MAX
           AND R.ACTIVE_FLAG = TRUE
    INNER JOIN DM_PADM_SEGMENT_1 AS S
            ON UPPER(S.SOURCE_NAME) = UPPER(M.SOURCE)
           AND UPPER(S.SCORE_TYPE) = UPPER(M.BUREAU_SCORE_TYPE)
           AND S.SCORE_MIN = R.SCORE_MIN AND S.SCORE_MAX = R.SCORE_MAX
           AND S.ACTIVE_FLAG = TRUE
    INNER JOIN DM_PADM_CAMPAIGN_1 AS C
            ON C.REPORTING_MONTH = DATE_TRUNC('MONTH', M.MAIL_DATE)::DATE
           AND C.CAMPAIGN_TYPE = M.CAMPAIGN_WAVE
)
SELECT UUID_STRING(), CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
       COUNT(*), TRUE
FROM MATCHED
WHERE RESPONSE_MODEL_TIER IS NOT NULL
GROUP BY CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET;

