INSERT INTO DM_PADM_MAILFILE_CELL
    (MAILFILE_CELL_ID, CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
     MAIL_QUANTITY, IS_CURRENT)
WITH RAW_MAILFILE AS
(
    SELECT 'EXPERIAN' AS SOURCE, TRIM(UPPER(PROSPECT_TYPE)) AS PROSPECT_SEGMENT_TYPE,
           UPPER(COALESCE(MLA_INDICATOR, 'N')) AS MLA_FLAG, RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE,
           RESPONSE_MODEL_TIER, MAIL_DATE, CAMPAIGN_SOURCE,
           CASE WHEN TIMES_MAILED_12_MONTH_COUNT >= 9 THEN '9+' ELSE TO_VARCHAR(TIMES_MAILED_12_MONTH_COUNT) END AS TIMES_MAILED_BUCKET,
           'VS3' AS BUREAU_SCORE_TYPE, PRESCREEN_VANTAGE_V3 AS RAW_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    UNION ALL
    SELECT 'EXPERIAN', TRIM(UPPER(PROSPECT_TYPE)), UPPER(COALESCE(MLA_INDICATOR, 'N')), RESPONSE_MODEL_TYPE,
           RISK_SCORE_TYPE, RESPONSE_MODEL_TIER, MAIL_DATE, CAMPAIGN_SOURCE,
           CASE WHEN TIMES_MAILED_12_MONTH_COUNT >= 9 THEN '9+' ELSE TO_VARCHAR(TIMES_MAILED_12_MONTH_COUNT) END,
           'VS4', PRESCREEN_VANTAGE_V4
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V4 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    UNION ALL
    SELECT 'EXPERIAN', TRIM(UPPER(PROSPECT_TYPE)), UPPER(COALESCE(MLA_INDICATOR, 'N')), RESPONSE_MODEL_TYPE,
           RISK_SCORE_TYPE, RESPONSE_MODEL_TIER, MAIL_DATE, CAMPAIGN_SOURCE,
           CASE WHEN TIMES_MAILED_12_MONTH_COUNT >= 9 THEN '9+' ELSE TO_VARCHAR(TIMES_MAILED_12_MONTH_COUNT) END,
           'LIFT', LIFT_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE LIFT_SCORE IS NOT NULL AND PROSPECT_TYPE IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'

    UNION ALL
    SELECT 'TRANSUNION', TRIM(UPPER(PROSPECT_TYPE)), UPPER(COALESCE(MLA_INDICATOR, 'N')), RESPONSE_MODEL_TYPE,
           RISK_SCORE_TYPE, RESPONSE_MODEL_TIER, MAIL_DATE, CAMPAIGN_SOURCE,
           CASE WHEN TM12_3B >= 9 THEN '9+' ELSE TO_VARCHAR(TM12_3B) END,
           'VS3', PRESCREEN_VANTAGE_V3
    FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL
      AND MAIL_DATE >= '2026-01-01' AND MAIL_DATE < '2027-01-01'
),
MATCHED AS
(
    SELECT
        C.CAMPAIGN_ID,
        S.SEGMENT_ID,
        M.SOURCE AS SOURCE_NAME,
        TRY_CAST(M.RESPONSE_MODEL_TIER AS NUMBER(10,0)) AS RESPONSE_MODEL_TIER,
        M.TIMES_MAILED_BUCKET
    FROM RAW_MAILFILE AS M
    INNER JOIN DM_PADM_SCORE_RANGE_RULE_1 AS R
            ON UPPER(M.BUREAU_SCORE_TYPE) = UPPER(R.SCORE_TYPE)
           AND M.RAW_SCORE BETWEEN R.SCORE_MIN AND R.SCORE_MAX
           AND R.ACTIVE_FLAG = TRUE
    INNER JOIN DM_PADM_SEGMENT_1 AS S
            ON UPPER(S.SOURCE_NAME) = UPPER(M.SOURCE)
           AND UPPER(S.SCORE_TYPE) = UPPER(M.BUREAU_SCORE_TYPE)
           AND S.SCORE_MIN = R.SCORE_MIN AND S.SCORE_MAX = R.SCORE_MAX
           AND S.ACTIVE_FLAG = TRUE
    INNER JOIN DM_PADM_CAMPAIGN_1 AS C
            ON C.REPORTING_MONTH = DATE_TRUNC('MONTH', M.MAIL_DATE)::DATE
           AND (
                 (C.CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(M.CAMPAIGN_SOURCE)) = 'PADM')
              OR (C.CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(M.CAMPAIGN_SOURCE)) IN ('MAP', 'PAREMAIL'))
               )
)
SELECT UUID_STRING(), CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
       COUNT(*), TRUE
FROM MATCHED
WHERE RESPONSE_MODEL_TIER IS NOT NULL
GROUP BY CAMPAIGN_ID, SEGMENT_ID, SOURCE_NAME, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET;

