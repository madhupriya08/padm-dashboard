-- Idempotent -- safe to re-run.
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Candidate segments derived from the raw Experian/TransUnion/MAP mailfile tables, bucketed into
-- score ranges -- backs the "discover segments from mailfile" flow and the backfill script.
CREATE OR REPLACE VIEW VW_PADM_SEGMENT_SOURCE_CANDIDATE(
    SEGMENT_KEY,
    SUGGESTED_SEGMENT_NAME,
    SOURCE_SEGMENT_NAME,
    SOURCE,
    BUREAU_SCORE_TYPE,
    BUREAU_SCORE_RANGE,
    SCORE_MIN,
    SCORE_MAX,
    PROSPECT_SEGMENT_TYPE,
    ANNUAL_FEE,
    NETWORK,
    MLA_FLAG,
    RESPONSE_MODEL_TYPE,
    RISK_SCORE_TYPE,
    MAIL_REMAIL,
    SOURCE_RECORD_COUNT,
    FIRST_MAIL_DATE,
    LAST_MAIL_DATE
) AS
-- PROSPECT_SEGMENT_TYPE/SOURCE_SEGMENT_NAME are derived from CAMPAIGN_SOURCE (a letter/digit code), per the real classification script.
WITH RAW_SCORES AS
(
    SELECT 'EXPERIAN' AS SOURCE,
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END AS PROSPECT_SEGMENT_TYPE,
           CASE
               WHEN CAMPAIGN_SOURCE = 'V' AND UPPER(MLA_INDICATOR) = 'Y' THEN 'Experian Vantage MLA'
               WHEN CAMPAIGN_SOURCE = 'E' THEN 'Emerging Consumer'
               WHEN CAMPAIGN_SOURCE = 'V' THEN 'Experian Vantage'
               WHEN CAMPAIGN_SOURCE IN ('A','W') THEN 'ABDN'
               WHEN CAMPAIGN_SOURCE = 'C' THEN 'PCO'
               WHEN CAMPAIGN_SOURCE IN ('D','M') THEN 'PDCL'
               WHEN CAMPAIGN_SOURCE IN ('R','N') THEN 'PCL'
               WHEN CAMPAIGN_SOURCE = 'I' THEN 'Remails, Experian Vantage'
               WHEN CAMPAIGN_SOURCE = 'G' THEN 'Remails, Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE IN ('B','J') THEN 'Remails, Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'Q' THEN 'Remails, Prior Decline'
           END AS SOURCE_SEGMENT_NAME,
           UPPER(COALESCE(MLA_INDICATOR, 'N')) AS MLA_FLAG,
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE,
           'VS3' AS BUREAU_SCORE_TYPE, PRESCREEN_VANTAGE_V3 AS RAW_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL

    UNION ALL
    SELECT 'EXPERIAN',
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE = 'V' AND UPPER(MLA_INDICATOR) = 'Y' THEN 'Experian Vantage MLA'
               WHEN CAMPAIGN_SOURCE = 'E' THEN 'Emerging Consumer'
               WHEN CAMPAIGN_SOURCE = 'V' THEN 'Experian Vantage'
               WHEN CAMPAIGN_SOURCE IN ('A','W') THEN 'ABDN'
               WHEN CAMPAIGN_SOURCE = 'C' THEN 'PCO'
               WHEN CAMPAIGN_SOURCE IN ('D','M') THEN 'PDCL'
               WHEN CAMPAIGN_SOURCE IN ('R','N') THEN 'PCL'
               WHEN CAMPAIGN_SOURCE = 'I' THEN 'Remails, Experian Vantage'
               WHEN CAMPAIGN_SOURCE = 'G' THEN 'Remails, Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE IN ('B','J') THEN 'Remails, Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'Q' THEN 'Remails, Prior Decline'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS4', PRESCREEN_VANTAGE_V4
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V4 IS NOT NULL

    UNION ALL
    SELECT 'TRANSUNION',
           CASE
               WHEN CAMPAIGN_SOURCE = 'U' THEN 'PROSPECTING'
               WHEN CAMPAIGN_SOURCE IN ('3','4','5','6','7','8','9','L','Z') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE = 'H' AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'RETARGETING'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE = 'U' THEN 'TU'
               WHEN CAMPAIGN_SOURCE IN ('3','4') THEN 'TU Prior Decline'
               WHEN CAMPAIGN_SOURCE IN ('5','6') THEN 'TU Prior Closure'
               WHEN CAMPAIGN_SOURCE = '7' THEN 'TU Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE = 'H' AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'Remails, TU'
               WHEN CAMPAIGN_SOURCE IN ('8','9') THEN 'Remails, TU Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'L' THEN 'Remails, TU Prior Decline'
               WHEN CAMPAIGN_SOURCE = 'Z' THEN 'Remails, TU Charge-Off'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS3', PRESCREEN_VANTAGE_V3
    FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL

    -- T_MAP_MAILFILE: existing-customer repeat-contact offers, classified RETARGETING.
    UNION ALL
    SELECT 'MAP', 'RETARGETING', 'MAP (existing-customer multiple account offer)',
           'N', NULL, NULL, MAIL_DATE, 'VS3', TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0))
    FROM CSTONE_BIZ.REFERENCE.T_MAP_MAILFILE
    WHERE TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0)) IS NOT NULL
)
SELECT
      SHA2(
          CONCAT_WS('|', M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, M.PROSPECT_SEGMENT_TYPE,
                     COALESCE(M.MLA_FLAG, ''), COALESCE(M.RESPONSE_MODEL_TYPE, ''), COALESCE(M.RISK_SCORE_TYPE, '')),
          256
      ) AS SEGMENT_KEY
    , M.BUREAU_SCORE_TYPE || ' ' || TO_VARCHAR(R.SCORE_MIN) || '-' || TO_VARCHAR(R.SCORE_MAX) || ' ' || M.SOURCE AS SUGGESTED_SEGMENT_NAME
    , M.SOURCE_SEGMENT_NAME
    , M.SOURCE
    , M.BUREAU_SCORE_TYPE
    , R.SCORE_RANGE_CODE AS BUREAU_SCORE_RANGE
    , R.SCORE_MIN
    , R.SCORE_MAX
    , M.PROSPECT_SEGMENT_TYPE
    , NULL AS ANNUAL_FEE
    , NULL AS NETWORK
    , M.MLA_FLAG
    , M.RESPONSE_MODEL_TYPE
    , M.RISK_SCORE_TYPE
    , NULL AS MAIL_REMAIL
    , COUNT(1) AS SOURCE_RECORD_COUNT
    , MIN(M.MAIL_DATE) AS FIRST_MAIL_DATE
    , MAX(M.MAIL_DATE) AS LAST_MAIL_DATE
FROM RAW_SCORES AS M
INNER JOIN DB_RISK.RISK_SBX.DM_PADM_SCORE_RANGE_RULE_1 AS R
        ON UPPER(M.BUREAU_SCORE_TYPE) = UPPER(R.SCORE_TYPE)
       AND M.RAW_SCORE BETWEEN R.SCORE_MIN AND R.SCORE_MAX
       AND R.ACTIVE_FLAG = TRUE
GROUP BY M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, R.SCORE_MIN, R.SCORE_MAX,
         M.PROSPECT_SEGMENT_TYPE, M.SOURCE_SEGMENT_NAME, M.MLA_FLAG, M.RESPONSE_MODEL_TYPE, M.RISK_SCORE_TYPE;

-- Validation query: sanity-check row counts per score range after the view is (re)created.
SELECT SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX,
       COUNT(DISTINCT PROSPECT_SEGMENT_TYPE) AS DISTINCT_PROSPECT_TYPES, SUM(SOURCE_RECORD_COUNT) AS TOTAL_RECORDS
FROM VW_PADM_SEGMENT_SOURCE_CANDIDATE
GROUP BY SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX
ORDER BY SOURCE, BUREAU_SCORE_TYPE, SCORE_MIN;
