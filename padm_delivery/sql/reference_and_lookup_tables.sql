-- Idempotent -- safe to re-run.
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Catalog of every assumption field (CPP, Unit Cost, NBR, Unwind Rate, ...), campaign- or
-- segment-level, used to drive Campaign Assumptions / Segment Viewer's input forms.
CREATE TABLE IF NOT EXISTS DM_PADM_ASSUMPTION_DEFINITION
(
    ASSUMPTION_CODE VARCHAR NOT NULL,
    ASSUMPTION_LABEL VARCHAR NOT NULL,
    DATA_TYPE VARCHAR NOT NULL,
    DISPLAY_UNIT VARCHAR NOT NULL,
    DECIMALS NUMBER(2,0) NOT NULL,
    MIN_VALUE NUMBER(18,8),
    MAX_VALUE NUMBER(18,8),
    ALLOW_NEGATIVE BOOLEAN NOT NULL DEFAULT FALSE,
    ASSUMPTION_LEVEL VARCHAR NOT NULL,
    CAMPAIGN_COLUMN VARCHAR,
    SEGMENT_COLUMN VARCHAR,
    ENTERED_ON VARCHAR NOT NULL,
    DISPLAY_SEQUENCE NUMBER(10,0),
    ACTIVE_FLAG BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_ASSUMPTION_DEFINITION PRIMARY KEY (ASSUMPTION_CODE)
);

-- Seed the 7 assumption definitions (CPP, Unit Cost, NBR, Unwind Rate + 3 segment-level rate adjustments).
MERGE INTO DM_PADM_ASSUMPTION_DEFINITION AS T
USING
(
    SELECT * FROM VALUES
      ('CPP',                              'CPP',                          'NUMBER', 'CURRENCY', 4, 0,    NULL, FALSE, 'CAMPAIGN_SEGMENT',  'CPP',       'CPP_OVERRIDE',
       'BOTH',             10)
    , ('UNIT_COST',                        'Unit Cost',                    'NUMBER', 'CURRENCY', 2, 0,    NULL, FALSE, 'CAMPAIGN_SEGMENT',  'UNIT_COST', 'UNIT_COST_OVERRIDE',
       'BOTH',             20)
    , ('NBR',                              'NBR',                          'NUMBER', 'FRACTION', 4, 0,    1,    FALSE, 'CAMPAIGN_SEGMENT',  'NBR',       'NBR_OVERRIDE',
       'ASSUMPTIONS',      30)

    , ('UNWIND_RATE',                      'Unwind Rate',                  'NUMBER', 'PERCENT',  2, 0,    1,    FALSE, 'CAMPAIGN_SEGMENT',  'UNWIND_RATE', 'UNWIND_RATE_OVERRIDE',
       'BOTH',             40)
    , ('UNWIND_RATE_ADJUSTMENT',           'Unwind Rate Adjustment',       'NUMBER', 'PERCENT',  2, -1,   10,   TRUE,  'SEGMENT',           NULL,
       'UNWIND_RATE_ADJUSTMENT_OVERRIDE',  'SEGMENT_VIEWER',    50)
    , ('RATE_ADJUSTMENT',                  'Rate Adjustment',              'NUMBER', 'PERCENT',  2, -1,   10,   TRUE,  'SEGMENT',           NULL,
       'RATE_ADJUSTMENT_OVERRIDE',         'SEGMENT_VIEWER',    60)
    , ('SEASONALITY_REDUCTION',            'Seasonality Rate Adjustment',  'PERCENTAGE', 'PERCENT', 2, -1, 1,    TRUE,  'SEGMENT',           NULL,
       'SEASONALITY_REDUCTION_OVERRIDE',   'SEGMENT_VIEWER',    70)
    AS V(ASSUMPTION_CODE, ASSUMPTION_LABEL, DATA_TYPE, DISPLAY_UNIT, DECIMALS, MIN_VALUE, MAX_VALUE, ALLOW_NEGATIVE,
         ASSUMPTION_LEVEL, CAMPAIGN_COLUMN, SEGMENT_COLUMN, ENTERED_ON, DISPLAY_SEQUENCE)
) AS S
ON T.ASSUMPTION_CODE = S.ASSUMPTION_CODE
WHEN NOT MATCHED THEN INSERT
    (ASSUMPTION_CODE, ASSUMPTION_LABEL, DATA_TYPE, DISPLAY_UNIT, DECIMALS, MIN_VALUE, MAX_VALUE, ALLOW_NEGATIVE,
     ASSUMPTION_LEVEL, CAMPAIGN_COLUMN, SEGMENT_COLUMN, ENTERED_ON, DISPLAY_SEQUENCE)
VALUES
    (S.ASSUMPTION_CODE, S.ASSUMPTION_LABEL, S.DATA_TYPE, S.DISPLAY_UNIT, S.DECIMALS, S.MIN_VALUE, S.MAX_VALUE, S.ALLOW_NEGATIVE,
     S.ASSUMPTION_LEVEL, S.CAMPAIGN_COLUMN, S.SEGMENT_COLUMN, S.ENTERED_ON, S.DISPLAY_SEQUENCE);

-- Maps an ACM segment name to PROSPECTING vs. RETARGETING.
CREATE TABLE IF NOT EXISTS DM_PADM_PROSPECT_TYPE_RULE
(
    ACM_SEGMENT_NAME VARCHAR NOT NULL,
    PROSPECT_TYPE VARCHAR NOT NULL,
    VALID_FROM DATE NOT NULL DEFAULT CURRENT_DATE(),
    VALID_TO DATE,
    ACTIVE_FLAG BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_PROSPECT_TYPE_RULE PRIMARY KEY (ACM_SEGMENT_NAME)
);

-- Seed the known retargeting segment names; everything else defaults to PROSPECTING ('*').
MERGE INTO DM_PADM_PROSPECT_TYPE_RULE AS T
USING
(
    SELECT * FROM VALUES
        ('PQ ABANDON', 'RETARGETING'), ('PQ DECLINE', 'RETARGETING'), ('PRIOR CHARGE OFF', 'RETARGETING'),
        ('PRIOR CLOSURE', 'RETARGETING'), ('PRIOR DECLINE', 'RETARGETING'), ('REMARKET', 'RETARGETING'),
        ('TU PRIOR CHARGE OFF', 'RETARGETING'), ('TU PRIOR CLOSURE', 'RETARGETING'),
        ('TU PRIOR DECLINE', 'RETARGETING'), ('*', 'PROSPECTING')
    AS V(ACM_SEGMENT_NAME, PROSPECT_TYPE)
) AS S
ON T.ACM_SEGMENT_NAME = S.ACM_SEGMENT_NAME
WHEN NOT MATCHED THEN INSERT (ACM_SEGMENT_NAME, PROSPECT_TYPE) VALUES (S.ACM_SEGMENT_NAME, S.PROSPECT_TYPE);

