CREATE OR REPLACE VIEW VW_PADM_CAMPAIGN_OFFER_CURRENT AS
SELECT
      O.CAMPAIGN_OFFER_ID
    , O.CAMPAIGN_ID
    , O.CAMPAIGN_SOURCE_COMPONENT_ID
    , O.OFFER_RESERVATION_CODE
    , O.PROGRAM_CODE
    , O.PROGRAM_VERSION_NUMBER
    , O.SOURCE_MAIL_DATE
    , O.OFFER_DESCRIPTION
    , O.OFFER_SEGMENT_NAME
    , O.TEST_TYPE
    , O.SOURCE_CPP
    , O.PROMO_CODE
    , O.APPROVAL_CODE
    , O.UNDERWRITING_FLAG
    , O.PROSPECT_TYPE
    , O.PRINT_VENDOR_ID
    , O.CRS_SCORE
    , O.OFFER_STATUS
FROM DM_PADM_CAMPAIGN_OFFER AS O
INNER JOIN DM_PADM_CAMPAIGN_SOURCE_VERSION AS S
    ON O.CAMPAIGN_SOURCE_VERSION_ID = S.CAMPAIGN_SOURCE_VERSION_ID
   AND S.IS_CURRENT = TRUE
WHERE O.IS_CURRENT = TRUE;

