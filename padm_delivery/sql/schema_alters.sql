-- SEGMENT_KEY: materializes the segment natural key into one column, backfilled, then made UNIQUE
-- (NOVALIDATE -- Snowflake doesn't enforce UNIQUE at the storage layer, so this won't fail even if
-- duplicates exist; real duplicate prevention stays in repository.find_segment()/create_segment()).
ALTER TABLE DM_PADM_SEGMENT_1 ADD COLUMN IF NOT EXISTS SEGMENT_KEY VARCHAR;

UPDATE DM_PADM_SEGMENT_1
SET SEGMENT_KEY = UPPER(COALESCE(SOURCE_NAME, '')) || '|' || UPPER(SCORE_TYPE) || '|' || SCORE_MIN || '|' || SCORE_MAX
WHERE SEGMENT_KEY IS NULL OR SEGMENT_KEY <>
      UPPER(COALESCE(SOURCE_NAME, '')) || '|' || UPPER(SCORE_TYPE) || '|' || SCORE_MIN || '|' || SCORE_MAX;

ALTER TABLE DM_PADM_SEGMENT_1 ADD CONSTRAINT UQ_PADM_SEGMENT_KEY UNIQUE (SEGMENT_KEY) ENABLE NOVALIDATE;

-- CAMPAIGN_SEGMENT_KEY: same idea, identifying "this campaign's copy of this segment" by one
-- column instead of (CAMPAIGN_ID, SEGMENT_ID). No UNIQUE here -- this table is intentionally
-- versioned, so the same pair legitimately repeats across history.
ALTER TABLE DM_PADM_CAMPAIGN_SEGMENT_1 ADD COLUMN IF NOT EXISTS CAMPAIGN_SEGMENT_KEY VARCHAR;

UPDATE DM_PADM_CAMPAIGN_SEGMENT_1
SET CAMPAIGN_SEGMENT_KEY = CAMPAIGN_ID || '|' || SEGMENT_ID
WHERE CAMPAIGN_SEGMENT_KEY IS NULL;

-- Widen the segment natural-key uniqueness constraint to the full set of selected fields (drop
-- the old, narrower version first if present).
EXECUTE IMMEDIATE $$
DECLARE
    V_RESULT VARCHAR;
BEGIN
    ALTER TABLE DM_PADM_SEGMENT_1 DROP CONSTRAINT UQ_PADM_SEGMENT_NATURAL_KEY;
    V_RESULT := 'dropped';
    RETURN V_RESULT;
EXCEPTION
    WHEN OTHER THEN
        V_RESULT := 'not found, skipped';
        RETURN V_RESULT;
END;
$$;
ALTER TABLE DM_PADM_SEGMENT_1 ADD CONSTRAINT UQ_PADM_SEGMENT_NATURAL_KEY UNIQUE
(
    SOURCE_NAME, SCORE_TYPE, SCORE_MIN, SCORE_MAX, PROSPECT_SEGMENT_TYPE, ANNUAL_FEE, NETWORK,
    MLA_FLAG, RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE
) ENABLE NOVALIDATE;

