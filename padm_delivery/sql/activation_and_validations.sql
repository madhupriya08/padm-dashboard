USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

EXECUTE IMMEDIATE $$
DECLARE
    V_CAMPAIGN_ID VARCHAR;
    V_RESULT VARCHAR;
    V_COMPLETED_COUNT NUMBER DEFAULT 0;
    C_CAMPAIGNS CURSOR FOR
        SELECT C.CAMPAIGN_ID
        FROM DM_PADM_CAMPAIGN_1 AS C
        WHERE C.REPORTING_MONTH >= DATE '2026-01-01'
          AND C.REPORTING_MONTH < DATE '2026-05-01'
          AND C.STATUS IN ('DISCOVERED', 'REOPENED', 'DRAFT')
          AND NOT EXISTS
            (
                SELECT 1
                FROM DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
                WHERE V.CAMPAIGN_ID = C.CAMPAIGN_ID
                  AND V.IS_CURRENT = TRUE
            )
        ORDER BY C.REPORTING_MONTH, C.CAMPAIGN_TYPE;
BEGIN
    FOR REC IN C_CAMPAIGNS DO
        V_CAMPAIGN_ID := REC.CAMPAIGN_ID;
        CALL SP_PADM_ACTIVATE_CAMPAIGN(:V_CAMPAIGN_ID, 'Activate January through April 2026') INTO :V_RESULT;
        IF (V_RESULT LIKE 'Campaign source snapshot completed.%') THEN
            V_COMPLETED_COUNT := V_COMPLETED_COUNT + 1;
        END IF;
    END FOR;
    RETURN 'Completed source snapshots for ' || TO_VARCHAR(V_COMPLETED_COUNT) || ' campaigns.';
END;
$$;

-- Expected: no rows.
SELECT CAMPAIGN_ID, COUNT(*) AS CURRENT_VERSION_COUNT
FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
WHERE IS_CURRENT = TRUE
GROUP BY CAMPAIGN_ID
HAVING COUNT(*) <> 1;

-- Expected: no rows for January through April 2026.
SELECT C.CAMPAIGN_ID, C.REPORTING_MONTH, C.CAMPAIGN_TYPE
FROM DM_PADM_CAMPAIGN_1 AS C
LEFT JOIN DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
       ON C.CAMPAIGN_ID = V.CAMPAIGN_ID AND V.IS_CURRENT = TRUE
LEFT JOIN DM_PADM_CAMPAIGN_OFFER AS O
       ON V.CAMPAIGN_SOURCE_VERSION_ID = O.CAMPAIGN_SOURCE_VERSION_ID
WHERE C.REPORTING_MONTH >= DATE '2026-01-01'
  AND C.REPORTING_MONTH < DATE '2026-05-01'
GROUP BY C.CAMPAIGN_ID, C.REPORTING_MONTH, C.CAMPAIGN_TYPE
HAVING COUNT(DISTINCT V.CAMPAIGN_SOURCE_VERSION_ID) <> 1
    OR COUNT(DISTINCT O.CAMPAIGN_OFFER_ID) = 0;

SELECT
      CAMPAIGN_ID
    , REPORTING_MONTH
    , CAMPAIGN_SEQUENCE
    , CAMPAIGN_TYPE
    , CAMPAIGN_DISPLAY_NAME
    , STATUS
    , ACTIVE_FLAG
    , SOURCE_CHANGE_PENDING_FLAG
    , CURRENT_SOURCE_VERSION_NUMBER
    , ROW_VERSION
    , UPDATED_BY
    , UPDATED_TS
FROM DB_RISK.RISK_SBX.DM_PADM_CAMPAIGN_1
WHERE REPORTING_MONTH >= DATE '2026-01-01'
  AND REPORTING_MONTH <  DATE '2026-05-01'
ORDER BY
      REPORTING_MONTH
    , CAMPAIGN_TYPE;

SELECT
      C.CAMPAIGN_ID
    , C.REPORTING_MONTH
    , C.CAMPAIGN_TYPE
    , C.STATUS
    , C.ACTIVE_FLAG
    , COUNT(
        DISTINCT V.CAMPAIGN_SOURCE_VERSION_ID
      ) AS CURRENT_SOURCE_VERSION_COUNT
    , COUNT(
        DISTINCT SC.CAMPAIGN_SOURCE_COMPONENT_ID
      ) AS SOURCE_COMPONENT_COUNT
    , COUNT(
        DISTINCT O.CAMPAIGN_OFFER_ID
      ) AS OFFER_COUNT
    , COUNT(
        DISTINCT P.CAMPAIGN_OFFER_PROFILE_ID
      ) AS OFFER_PROFILE_COUNT

FROM DB_RISK.RISK_SBX.DM_PADM_CAMPAIGN_1 AS C

LEFT JOIN DB_RISK.RISK_SBX
        .DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
     ON C.CAMPAIGN_ID = V.CAMPAIGN_ID
    AND V.IS_CURRENT = TRUE

LEFT JOIN DB_RISK.RISK_SBX
        .DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS SC
     ON V.CAMPAIGN_SOURCE_VERSION_ID =
        SC.CAMPAIGN_SOURCE_VERSION_ID

LEFT JOIN DB_RISK.RISK_SBX
        .DM_PADM_CAMPAIGN_OFFER AS O
     ON V.CAMPAIGN_SOURCE_VERSION_ID =
        O.CAMPAIGN_SOURCE_VERSION_ID
    AND O.IS_CURRENT = TRUE

LEFT JOIN DB_RISK.RISK_SBX
        .DM_PADM_CAMPAIGN_OFFER_PROFILE AS P
     ON O.CAMPAIGN_OFFER_ID =
        P.CAMPAIGN_OFFER_ID
    AND P.IS_CURRENT = TRUE

WHERE C.REPORTING_MONTH >= DATE '2026-01-01'
  AND C.REPORTING_MONTH <  DATE '2026-05-01'

GROUP BY
      C.CAMPAIGN_ID
    , C.REPORTING_MONTH
    , C.CAMPAIGN_TYPE
    , C.STATUS
    , C.ACTIVE_FLAG

ORDER BY
      C.REPORTING_MONTH
    , C.CAMPAIGN_TYPE;
