CREATE OR REPLACE VIEW VW_PADM_SIGNATURE_PAGE_LIVE AS
WITH TIMES_MAILED_0 AS (
    SELECT CAMPAIGN_OFFER_ID,
           TIMES_MAILED_0_COUNT / NULLIF(TIMES_MAILED_0_COUNT+TIMES_MAILED_1_COUNT+TIMES_MAILED_2_COUNT+TIMES_MAILED_3_COUNT
               +TIMES_MAILED_4_COUNT+TIMES_MAILED_5_COUNT+TIMES_MAILED_6_COUNT+TIMES_MAILED_7_COUNT+TIMES_MAILED_8_COUNT
               +TIMES_MAILED_9_PLUS_COUNT, 0) AS TIMES_MAILED_0_PERCENTAGE
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE WHERE IS_CURRENT = TRUE
)
SELECT
    A.CAMPAIGN_ID,
    A.CAMPAIGN_OFFER_ID,
    A.SEGMENT_ID,
    A.POPULATION_DESCRIPTION,
    O.OFFER_DESCRIPTION                                                              AS SEGMENT_DESCRIPTION,
    O.TEST_TYPE,
    COALESCE(SRC.NETWORK, P.NETWORK)                                                 AS NETWORK,
    O.CREDIT_BUREAU_MODEL,
    O.CREDIT_BUREAU_SCORE,
    SRC.CRS_MODEL,
    O.CRS_SCORE,
    SRC.NRM,
    CONCAT(TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1)), '/',
           TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2)))               AS ANNUAL_FEE,
    O.PROMO_CODE                                                                     AS PROMO,
    O.APPROVAL_CODE                                                                  AS IVR,
    O.UNDERWRITING_FLAG,
    O.PROSPECT_TYPE,
    O.PRINT_VENDOR_ID                                                                AS PRINT_VENDOR,
    T0.TIMES_MAILED_0_PERCENTAGE,
    SUM(C.SELECTED_QUANTITY)                                                         AS QUANTITY,
    SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS NBR,
    SUM(C.BOOKED_PRE_UNWIND_SELECTED)                                                AS BOARDS,
    SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS CPP,
    SUM(C.MARKETING_COST_SELECTED)                                                   AS MARKETING_EXPENSE,
    SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)  AS UNWIND_RATE,
    SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)    AS PRE_UNWIND_CPA,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0) AS POST_UNWIND_CPA,
    SUM(C.BOOKED_POST_UNWIND_SELECTED)                                               AS POST_UNWIND_BOARDS,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)                         AS MARKETING_PLUS_BOOKING_COSTS,
    LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ') WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER)) AS TIERS
FROM DM_PADM_OFFER_SEGMENT_ALLOCATION AS A
INNER JOIN VW_PADM_CAMPAIGN_OFFER_CURRENT AS O ON A.CAMPAIGN_OFFER_ID = O.CAMPAIGN_OFFER_ID
LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P ON O.PROGRAM_CODE = P.PROGRAM_CODE AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
LEFT JOIN VW_PADM_ACM_OFFER_SOURCE AS SRC ON O.OFFER_RESERVATION_CODE = SRC.OFFER_RESERVATION_CODE
LEFT JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C ON A.CAMPAIGN_ID = C.CAMPAIGN_ID AND A.SEGMENT_ID = C.SEGMENT_ID
LEFT JOIN TIMES_MAILED_0 AS T0 ON A.CAMPAIGN_OFFER_ID = T0.CAMPAIGN_OFFER_ID
WHERE A.IS_CURRENT = TRUE
GROUP BY A.CAMPAIGN_ID, A.CAMPAIGN_OFFER_ID, A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION,
         O.TEST_TYPE, SRC.NETWORK, P.NETWORK, O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, SRC.CRS_MODEL, O.CRS_SCORE,
         SRC.NRM, SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1, SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2, O.PROMO_CODE,
         O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE, O.PRINT_VENDOR_ID, T0.TIMES_MAILED_0_PERCENTAGE;

