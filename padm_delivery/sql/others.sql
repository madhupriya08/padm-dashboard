AND T.STATUS = 'COMPLETED'
AND
(
    COALESCE(T.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MIN_MAIL_DATE, DATE '1900-01-01')

    OR COALESCE(T.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')
    <>
    COALESCE(S.SOURCE_MAX_MAIL_DATE, DATE '1900-01-01')
)
THEN UPDATE SET
      T.SOURCE_CHANGE_PENDING_FLAG = TRUE
    , T.ROW_VERSION = COALESCE(T.ROW_VERSION, 0) + 1
    , T.UPDATED_BY = CURRENT_USER()
    , T.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT
