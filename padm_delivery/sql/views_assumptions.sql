-- Idempotent -- safe to re-run.
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Current (IS_CURRENT) row per campaign-level assumption version.
CREATE OR REPLACE VIEW VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS
SELECT
      CAMPAIGN_ASSUMPTION_VERSION_ID
    , CAMPAIGN_ID
    , VERSION_NUMBER
    , CPP
    , UNIT_COST
    , NBR
    , UNWIND_RATE
    , RATE_ADJUSTMENT
    , SEASONALITY_REDUCTION
    , UNWIND_RATE_ADJUSTMENT
    , CHANGE_REASON
    , CREATED_BY
    , CREATED_TS
FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
WHERE IS_CURRENT = TRUE;

-- Current (IS_CURRENT) row per segment-level assumption override version.
CREATE OR REPLACE VIEW VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS
SELECT
      SEGMENT_ASSUMPTION_VERSION_ID
    , CAMPAIGN_ID
    , SEGMENT_ID
    , VERSION_NUMBER
    , CPP_OVERRIDE
    , UNIT_COST_OVERRIDE
    , NBR_OVERRIDE
    , UNWIND_RATE_OVERRIDE
    , RATE_ADJUSTMENT_OVERRIDE
    , SEASONALITY_REDUCTION_OVERRIDE
    , UNWIND_RATE_ADJUSTMENT_OVERRIDE
    , CHANGE_REASON
    , CREATED_BY
    , CREATED_TS
FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
WHERE IS_CURRENT = TRUE;

-- Effective assumption per (campaign, segment): segment-level override if set, else the campaign-level value.
CREATE OR REPLACE VIEW VW_PADM_EFFECTIVE_ASSUMPTION AS
SELECT
      CS.CAMPAIGN_ID
    , CS.SEGMENT_ID
    , COALESCE(SA.CPP_OVERRIDE, CA.CPP) AS EFFECTIVE_CPP
    , COALESCE(SA.UNIT_COST_OVERRIDE, CA.UNIT_COST) AS EFFECTIVE_UNIT_COST
    , COALESCE(SA.NBR_OVERRIDE, CA.NBR) AS EFFECTIVE_NBR
    , COALESCE(SA.UNWIND_RATE_OVERRIDE, CA.UNWIND_RATE) AS EFFECTIVE_UNWIND_RATE
    , COALESCE(SA.RATE_ADJUSTMENT_OVERRIDE, 0) AS EFFECTIVE_RATE_ADJUSTMENT
    , COALESCE(SA.SEASONALITY_REDUCTION_OVERRIDE, 0) AS EFFECTIVE_SEASONALITY_REDUCTION
    , COALESCE(SA.UNWIND_RATE_ADJUSTMENT_OVERRIDE, 0) AS EFFECTIVE_UNWIND_RATE_ADJUSTMENT
FROM DM_PADM_CAMPAIGN_SEGMENT_1 AS CS
LEFT JOIN VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS CA
       ON CS.CAMPAIGN_ID = CA.CAMPAIGN_ID
LEFT JOIN VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS SA
       ON CS.CAMPAIGN_ID = SA.CAMPAIGN_ID
      AND CS.SEGMENT_ID = SA.SEGMENT_ID
WHERE CS.IS_CURRENT = TRUE;
