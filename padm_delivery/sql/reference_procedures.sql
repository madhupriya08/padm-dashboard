CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CAMPAIGN
(
    P_CAMPAIGN_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_REPORTING_MONTH DATE;
    V_CAMPAIGN_TYPE VARCHAR;
    V_SOURCE_VERSION_ID VARCHAR;
    V_LOAD_BATCH_ID VARCHAR;
    V_SOURCE_HASH VARCHAR;
    V_NEXT_SOURCE_VERSION NUMBER(10,0);
    V_CURRENT_VERSION_COUNT NUMBER DEFAULT 0;
    V_COMPONENT_COUNT NUMBER DEFAULT 0;
    V_OFFER_COUNT NUMBER DEFAULT 0;
    V_PROFILE_COUNT NUMBER DEFAULT 0;
BEGIN
    SELECT MAX(STATUS), MAX(REPORTING_MONTH), MAX(CAMPAIGN_TYPE)
      INTO :V_STATUS, :V_REPORTING_MONTH, :V_CAMPAIGN_TYPE
    FROM DM_PADM_CAMPAIGN_1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS IS NULL) THEN
        RETURN 'Campaign was not found.';
    END IF;

    IF (V_STATUS NOT IN ('DISCOVERED', 'REOPENED', 'DRAFT')) THEN
        RETURN 'Only DISCOVERED, REOPENED, or incomplete DRAFT campaigns can be activated.';
    END IF;

    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN
        RETURN 'Change Reason is required.';
    END IF;

    SELECT COUNT(*)
      INTO :V_CURRENT_VERSION_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_CURRENT_VERSION_COUNT > 0) THEN
        RETURN 'Campaign already has a current source version.';
    END IF;

    SELECT COALESCE(MAX(SOURCE_VERSION_NUMBER), 0) + 1
      INTO :V_NEXT_SOURCE_VERSION
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    V_SOURCE_VERSION_ID := UUID_STRING();
    V_LOAD_BATCH_ID := UUID_STRING();

    SELECT SHA2(
            COALESCE(TO_VARCHAR(:V_REPORTING_MONTH), '') || '|' ||
            COALESCE(:V_CAMPAIGN_TYPE, '') || '|' ||
            COALESCE(TO_VARCHAR(COUNT(*)), '') || '|' ||
            COALESCE(TO_VARCHAR(MIN(SOURCE_MAIL_DATE)), '') || '|' ||
            COALESCE(TO_VARCHAR(MAX(SOURCE_MAIL_DATE)), ''),
            256
          )
      INTO :V_SOURCE_HASH
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
           (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
        OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    IF (V_SOURCE_HASH IS NULL) THEN
        RETURN 'No eligible ACM offers were found for the campaign month and type.';
    END IF;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_VERSION
    (
          CAMPAIGN_SOURCE_VERSION_ID
        , CAMPAIGN_ID
        , SOURCE_VERSION_NUMBER
        , SOURCE_HASH
        , SOURCE_ROW_COUNT
        , SOURCE_MIN_MAIL_DATE
        , SOURCE_MAX_MAIL_DATE
        , LOAD_BATCH_ID
        , IS_CURRENT
        , CHANGE_SUMMARY
    )
    SELECT
          :V_SOURCE_VERSION_ID
        , :P_CAMPAIGN_ID
        , :V_NEXT_SOURCE_VERSION
        , :V_SOURCE_HASH
        , COUNT(*)
        , MIN(SOURCE_MAIL_DATE)
        , MAX(SOURCE_MAIL_DATE)
        , :V_LOAD_BATCH_ID
        , TRUE
        , :P_CHANGE_REASON
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
           (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
        OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    (
          CAMPAIGN_SOURCE_COMPONENT_ID
        , CAMPAIGN_SOURCE_VERSION_ID
        , CAMPAIGN_ID
        , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
        , SOURCE_CAMPAIGN_GROUP_CODE
        , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
        , SOURCE_CAMPAIGN_TYPE_CODE
        , SOURCE_CAMPAIGN_TYPE_NAME
        , SOURCE_MAIL_DATE
        , SOURCE_GROUP_START_DATE
        , SOURCE_GROUP_END_DATE
        , SOURCE_GROUP_RETIRE_DATE
        , SOURCE_GROUP_EXPIRE_DATE
        , SOURCE_LETTER_EXPIRE_DATE
        , SOURCE_OFFER_COUNT
    )
    SELECT
          UUID_STRING()
        , :V_SOURCE_VERSION_ID
        , :P_CAMPAIGN_ID
        , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
        , SOURCE_CAMPAIGN_GROUP_CODE
        , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
        , SOURCE_CAMPAIGN_TYPE_CODE
        , SOURCE_CAMPAIGN_TYPE_NAME
        , SOURCE_MAIL_DATE
        , SOURCE_GROUP_START_DATE
        , SOURCE_GROUP_END_DATE
        , SOURCE_GROUP_RETIRE_DATE
        , SOURCE_GROUP_EXPIRE_DATE
        , SOURCE_LETTER_EXPIRE_DATE
        , COUNT(DISTINCT OFFER_RESERVATION_CODE)
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
           (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
        OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    GROUP BY
          SOURCE_CAMPAIGN_IDENTIFICATION_CODE
        , SOURCE_CAMPAIGN_GROUP_CODE
        , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
        , SOURCE_CAMPAIGN_TYPE_CODE
        , SOURCE_CAMPAIGN_TYPE_NAME
        , SOURCE_MAIL_DATE
        , SOURCE_GROUP_START_DATE
        , SOURCE_GROUP_END_DATE
        , SOURCE_GROUP_RETIRE_DATE
        , SOURCE_GROUP_EXPIRE_DATE
        , SOURCE_LETTER_EXPIRE_DATE;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER
    (
          CAMPAIGN_OFFER_ID
        , CAMPAIGN_SOURCE_VERSION_ID
        , CAMPAIGN_ID
        , CAMPAIGN_SOURCE_COMPONENT_ID
        , OFFER_RESERVATION_CODE
        , PROGRAM_CODE
        , PROGRAM_VERSION_NUMBER
        , PROGRAM_MATCH_STATUS
        , MATCHED_PROGRAM_VERSION_NUMBER
        , SOURCE_CAMPAIGN_CODE
        , SOURCE_CAMPAIGN_NAME
        , SOURCE_CAMPAIGN_DESCRIPTION
        , SOURCE_MAIL_DATE
        , OFFER_DESCRIPTION
        , OFFER_SEGMENT_NAME
        , TEST_TYPE
        , SOURCE_CPP
        , PROMO_CODE
        , APPROVAL_CODE
        , UNDERWRITING_FLAG
        , PROSPECT_TYPE
        , PRINT_VENDOR_ID
        , CRS_SCORE
        , OFFER_STATUS
        , SOURCE_RECORD_ID
        , SOURCE_ROW_HASH
        , IS_CURRENT
    )
    SELECT
          UUID_STRING()
        , :V_SOURCE_VERSION_ID
        , :P_CAMPAIGN_ID
        , C.CAMPAIGN_SOURCE_COMPONENT_ID
        , S.OFFER_RESERVATION_CODE
        , S.PROGRAM_CODE
        , S.PROGRAM_VERSION_NUMBER
        , S.PROGRAM_MATCH_STATUS
        , S.MATCHED_PROGRAM_VERSION_NUMBER
        , S.SOURCE_CAMPAIGN_CODE
        , S.SOURCE_CAMPAIGN_NAME
        , S.SOURCE_CAMPAIGN_DESCRIPTION
        , S.SOURCE_MAIL_DATE
        , S.OFFER_DESCRIPTION
        , S.ACM_SEGMENT_NAME
        , S.TEST_TYPE
        , S.SOURCE_CPP

        , S.PROMO
        , S.IVR
        , S.UNDERWRITING_FLAG
        , S.PROSPECT_TYPE
        , S.PRINT_VENDOR_ID
        , S.CRS_SCORE
        , S.SOURCE_OFFER_STATUS
        , S.SOURCE_RECORD_ID
        , SHA2(
            COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') || '|' ||
            COALESCE(S.OFFER_RESERVATION_CODE, '') || '|' ||
            COALESCE(S.PROGRAM_CODE, '') || '|' ||
            COALESCE(TO_VARCHAR(S.PROGRAM_VERSION_NUMBER), '') || '|' ||
            COALESCE(S.OFFER_DESCRIPTION, '') || '|' ||
            COALESCE(TO_VARCHAR(S.SOURCE_CPP), ''),
            256
          )
        , TRUE
    FROM VW_PADM_ACM_OFFER_SOURCE AS S
    INNER JOIN DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS C
        ON C.CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND C.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
       AND COALESCE(C.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '')
       AND COALESCE(C.SOURCE_CAMPAIGN_GROUP_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_GROUP_CODE, '')
       AND C.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE DATE_TRUNC('MONTH', S.SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
           (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
        OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY S.OFFER_RESERVATION_CODE
        ORDER BY S.SOURCE_MAIL_DATE DESC, S.SOURCE_RECORD_ID DESC
    ) = 1;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER_PROFILE
    (
          CAMPAIGN_OFFER_PROFILE_ID
        , CAMPAIGN_ID
        , CAMPAIGN_OFFER_ID
        , PROFILE_VERSION_NUMBER
        , PROFILE_SOURCE_TYPE
        , ANNUAL_FEE
        , NETWORK
        , IS_CURRENT
    )
    SELECT
          UUID_STRING()
        , O.CAMPAIGN_ID
        , O.CAMPAIGN_OFFER_ID
        , 1
        , 'ACM_SOURCE'
        , S.ANNUAL_FEE
        , S.NETWORK
        , TRUE
    FROM DM_PADM_CAMPAIGN_OFFER AS O
    INNER JOIN VW_PADM_ACM_OFFER_SOURCE AS S
        ON O.OFFER_RESERVATION_CODE = S.OFFER_RESERVATION_CODE
       AND O.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE O.CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND O.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY O.CAMPAIGN_OFFER_ID
        ORDER BY S.SOURCE_RECORD_ID DESC
    ) = 1;

    UPDATE DM_PADM_CAMPAIGN_1
       SET STATUS = 'DRAFT'
         , ACTIVE_FLAG = TRUE
         , SOURCE_CHANGE_PENDING_FLAG = FALSE
         , CURRENT_SOURCE_VERSION_NUMBER = :V_NEXT_SOURCE_VERSION
         , ROW_VERSION = COALESCE(ROW_VERSION, 0) + 1
         , UPDATED_BY = CURRENT_USER()
         , UPDATED_TS = CURRENT_TIMESTAMP()
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS <> 'DRAFT') THEN
        INSERT INTO DM_PADM_WORKFLOW_EVENT
        (
              WORKFLOW_EVENT_ID
            , CAMPAIGN_ID
            , FROM_STATUS
            , TO_STATUS
            , EVENT_REASON
        )
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_STATUS, 'DRAFT', :P_CHANGE_REASON;
    END IF;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
          CHANGE_EVENT_ID
        , CAMPAIGN_ID
        , ENTITY_TYPE
        , ENTITY_ID
        , CHANGE_TYPE
        , BEFORE_VALUE
        , AFTER_VALUE
        , CHANGE_REASON
    )
    SELECT
          UUID_STRING()
        , :P_CAMPAIGN_ID
        , 'CAMPAIGN_SOURCE_VERSION'
        , :V_SOURCE_VERSION_ID
        , IFF(:V_STATUS = 'DRAFT', 'SOURCE_SNAPSHOT_REPAIRED', 'CAMPAIGN_ACTIVATED')
        , NULL
        , OBJECT_CONSTRUCT(
              'SOURCE_VERSION_NUMBER', :V_NEXT_SOURCE_VERSION,
              'REPORTING_MONTH', :V_REPORTING_MONTH,
              'CAMPAIGN_TYPE', :V_CAMPAIGN_TYPE
          )
        , :P_CHANGE_REASON;

    SELECT COUNT(*) INTO :V_COMPONENT_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_OFFER_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_PROFILE_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_COMPONENT_COUNT = 0 OR V_OFFER_COUNT = 0 OR V_PROFILE_COUNT <> V_OFFER_COUNT) THEN
        ROLLBACK;
        RETURN 'Source snapshot validation failed. No changes were committed.';
    END IF;

    COMMIT;
    RETURN 'Campaign source snapshot completed. Components: '
           || TO_VARCHAR(V_COMPONENT_COUNT)
           || ', Offers: '
           || TO_VARCHAR(V_OFFER_COUNT)
           || ', Profiles: '
           || TO_VARCHAR(V_PROFILE_COUNT)
           || '.';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_CAMPAIGN_ASSUMPTION
(
    P_CAMPAIGN_ID VARCHAR,
    P_CPP NUMBER(18,6),
    P_UNIT_COST NUMBER(18,4),
    P_RATE_ADJUSTMENT NUMBER(18,8),
    P_SEASONALITY_REDUCTION NUMBER(18,8),
    P_UNWIND_RATE_ADJUSTMENT NUMBER(18,8),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_NEXT_VERSION NUMBER(10,0);
    V_STATUS VARCHAR;
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS
    FROM DM_PADM_CAMPAIGN_1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS IS NULL) THEN RETURN 'Campaign was not found.'; END IF;
    IF (V_STATUS = 'COMPLETED') THEN RETURN 'Completed campaigns are read-only.'; END IF;
    IF (P_CPP IS NULL OR P_CPP < 0 OR P_UNIT_COST IS NULL OR P_UNIT_COST < 0) THEN
        RETURN 'CPP and Unit Cost must be nonnegative values.';
    END IF;
    IF (P_SEASONALITY_REDUCTION IS NULL OR P_SEASONALITY_REDUCTION < 0 OR P_SEASONALITY_REDUCTION > 1) THEN
        RETURN 'Seasonality Reduction must be between 0 and 1.';
    END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'Change Reason is required.'; END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    BEGIN TRANSACTION;

    UPDATE DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
       SET IS_CURRENT = FALSE, EFFECTIVE_TO_TS = CURRENT_TIMESTAMP()
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE;

    INSERT INTO DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
    (
        CAMPAIGN_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, VERSION_NUMBER
      , CPP, UNIT_COST, RATE_ADJUSTMENT, SEASONALITY_REDUCTION
      , UNWIND_RATE_ADJUSTMENT, IS_CURRENT, CHANGE_REASON
    )
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_NEXT_VERSION
        , :P_CPP, :P_UNIT_COST, :P_RATE_ADJUSTMENT, :P_SEASONALITY_REDUCTION
        , :P_UNWIND_RATE_ADJUSTMENT, TRUE, :P_CHANGE_REASON;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
        CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE
      , BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON
    )
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'CAMPAIGN_ASSUMPTION', :P_CAMPAIGN_ID
        , 'VERSION_CREATED', NULL
        , OBJECT_CONSTRUCT('VERSION_NUMBER', :V_NEXT_VERSION, 'CPP', :P_CPP, 'UNIT_COST', :P_UNIT_COST)
        , :P_CHANGE_REASON;

    COMMIT;
    RETURN 'Campaign assumption version saved.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CDE_VERSION
(
    P_CDE_LOAD_BATCH_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_CAMPAIGN_ID VARCHAR;
    V_SEGMENT_ID VARCHAR;
    V_VALIDATION_STATUS VARCHAR;
BEGIN
    SELECT MAX(CAMPAIGN_ID), MAX(SEGMENT_ID), MAX(VALIDATION_STATUS)
      INTO :V_CAMPAIGN_ID, :V_SEGMENT_ID, :V_VALIDATION_STATUS
    FROM DM_PADM_CDE_LOAD_BATCH
    WHERE CDE_LOAD_BATCH_ID = :P_CDE_LOAD_BATCH_ID;

    IF (V_CAMPAIGN_ID IS NULL OR V_SEGMENT_ID IS NULL) THEN RETURN 'CDE load batch was not found.'; END IF;
    IF (V_VALIDATION_STATUS <> 'VALID') THEN RETURN 'Only a validated CDE version can be activated.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'Change Reason is required.'; END IF;

    BEGIN TRANSACTION;

    UPDATE DM_PADM_CDE_LOAD_BATCH
       SET ACTIVE_FLAG = FALSE
     WHERE CAMPAIGN_ID = :V_CAMPAIGN_ID
       AND SEGMENT_ID = :V_SEGMENT_ID
       AND ACTIVE_FLAG = TRUE;

    UPDATE DM_PADM_CDE_LOAD_BATCH
       SET ACTIVE_FLAG = TRUE
         , ACTIVATED_BY = CURRENT_USER()
         , ACTIVATED_TS = CURRENT_TIMESTAMP()
     WHERE CDE_LOAD_BATCH_ID = :P_CDE_LOAD_BATCH_ID;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
        CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE
      , BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON
    )
    SELECT UUID_STRING(), :V_CAMPAIGN_ID, 'CDE_LOAD_BATCH', :P_CDE_LOAD_BATCH_ID
        , 'VERSION_ACTIVATED', NULL
        , OBJECT_CONSTRUCT('SEGMENT_ID', :V_SEGMENT_ID, 'CDE_LOAD_BATCH_ID', :P_CDE_LOAD_BATCH_ID)
        , :P_CHANGE_REASON;

    COMMIT;
    RETURN 'CDE version activated.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SEGMENT_ASSUMPTION(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_CPP_OVERRIDE NUMBER(18,6),
    P_UNIT_COST_OVERRIDE NUMBER(18,4),
    P_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_SEASONALITY_REDUCTION_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
BEGIN
    SELECT STATUS INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN
        RETURN 'Campaign not found.';
    END IF;
    IF (V_STATUS = 'COMPLETED') THEN
        RETURN 'Campaign is COMPLETED and read-only. Reopen the campaign before changing assumptions.';
    END IF;
    IF (P_CHANGE_REASON IS NULL OR TRIM(P_CHANGE_REASON) = '') THEN
        RETURN 'A change reason is required.';
    END IF;
    IF ((P_CPP_OVERRIDE IS NOT NULL AND P_CPP_OVERRIDE < 0) OR (P_UNIT_COST_OVERRIDE IS NOT NULL AND P_UNIT_COST_OVERRIDE < 0)) THEN
        RETURN 'CPP and Unit Cost cannot be negative.';
    END IF;
    IF (P_SEASONALITY_REDUCTION_OVERRIDE IS NOT NULL AND (P_SEASONALITY_REDUCTION_OVERRIDE < 0 OR P_SEASONALITY_REDUCTION_OVERRIDE > 1)) THEN
        RETURN 'Seasonality Reduction must be between 0 and 1.';
    END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    BEGIN TRANSACTION;

    UPDATE DM_PADM_SEGMENT_ASSUMPTION_VERSION
    SET IS_CURRENT = FALSE, EFFECTIVE_TO_TS = CURRENT_TIMESTAMP()
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE;

    INSERT INTO DM_PADM_SEGMENT_ASSUMPTION_VERSION (
        SEGMENT_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER,
        CPP_OVERRIDE, UNIT_COST_OVERRIDE, RATE_ADJUSTMENT_OVERRIDE,
        SEASONALITY_REDUCTION_OVERRIDE, UNWIND_RATE_ADJUSTMENT_OVERRIDE,
        IS_CURRENT, CHANGE_REASON
    ) VALUES (
        UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION,
        :P_CPP_OVERRIDE, :P_UNIT_COST_OVERRIDE, :P_RATE_ADJUSTMENT_OVERRIDE,
        :P_SEASONALITY_REDUCTION_OVERRIDE, :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE,
        TRUE, :P_CHANGE_REASON
    );

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, CHANGE_REASON, CHANGED_BY)
    VALUES (UUID_STRING(), :P_CAMPAIGN_ID, 'SEGMENT_ASSUMPTION', :P_SEGMENT_ID, 'VERSION_CREATED', :P_CHANGE_REASON, CURRENT_USER());

    COMMIT;
    RETURN 'Segment assumption version ' || :V_NEXT_VERSION || ' saved.';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SELECTION_SET(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_NEXT_VERSION NUMBER(10,0);
    V_SET_ID VARCHAR;
    V_CHANGED_CELLS NUMBER(38,0);
BEGIN
    IF (P_CHANGE_REASON IS NULL OR TRIM(P_CHANGE_REASON) = '') THEN
        RETURN 'A change reason is required.';
    END IF;

    SELECT COUNT(*) INTO :V_CHANGED_CELLS
    FROM DM_PADM_SELECTION_WORKING
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_DIRTY = TRUE;

    IF (V_CHANGED_CELLS = 0) THEN
        RETURN 'No unsaved selection changes for this segment.';
    END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_SELECTION_SET
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    V_SET_ID := UUID_STRING();

    BEGIN TRANSACTION;

    UPDATE DM_PADM_SELECTION_SET
    SET IS_CURRENT = FALSE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE;

    INSERT INTO DM_PADM_SELECTION_SET (SELECTION_SET_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER, STATUS, IS_CURRENT, IS_FINAL, CHANGE_REASON)
    VALUES (:V_SET_ID, :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION, 'SAVED', TRUE, FALSE, :P_CHANGE_REASON);

    INSERT INTO DM_PADM_SELECTION_SET_CELL (SELECTION_SET_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET, SELECTION_PERCENTAGE)
    SELECT :V_SET_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET, SELECTION_PERCENTAGE
    FROM DM_PADM_SELECTION_WORKING
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    INSERT INTO DM_PADM_SELECTION_EVENT (
        SELECTION_EVENT_ID, CAMPAIGN_ID, SEGMENT_ID, SELECTION_SET_ID, ACTION_TYPE,
        CHANGED_CELL_COUNT, CHANGE_REASON
    ) VALUES (
        UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_SET_ID, 'SAVE',
        :V_CHANGED_CELLS, :P_CHANGE_REASON
    );

    UPDATE DM_PADM_SELECTION_WORKING
    SET IS_DIRTY = FALSE, ROW_VERSION = ROW_VERSION + 1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    COMMIT;
    RETURN 'Selection set version ' || :V_NEXT_VERSION || ' saved (' || :V_CHANGED_CELLS || ' cells).';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_RUN_CALCULATION(
    P_CAMPAIGN_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_RUN_ID VARCHAR;
    V_WORKING_VERSION NUMBER(10,0);
    V_ASSUMPTION_VERSION_ID VARCHAR;
    V_CELL_COUNT NUMBER(38,0);
BEGIN
    SELECT CURRENT_WORKING_VERSION_NUMBER INTO :V_WORKING_VERSION FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_WORKING_VERSION IS NULL) THEN
        RETURN 'Campaign not found.';
    END IF;

    SELECT CAMPAIGN_ASSUMPTION_VERSION_ID INTO :V_ASSUMPTION_VERSION_ID
    FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE;

    V_RUN_ID := UUID_STRING();

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CALCULATION_RUN (
        CALCULATION_RUN_ID, CAMPAIGN_ID, CAMPAIGN_WORKING_VERSION_NUMBER, CAMPAIGN_ASSUMPTION_VERSION_ID,
        CALCULATION_STATUS, SOURCE_DATA_AS_OF_TS
    ) VALUES (
        :V_RUN_ID, :P_CAMPAIGN_ID, :V_WORKING_VERSION, :V_ASSUMPTION_VERSION_ID,
        'STARTED', CURRENT_TIMESTAMP()
    );

    INSERT INTO DM_PADM_CALCULATION_CELL (
        CALCULATION_CELL_ID, CALCULATION_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED,
        BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED,
        POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    )
    SELECT
        UUID_STRING(), :V_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED,
        BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED,
        POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    SELECT COUNT(*) INTO :V_CELL_COUNT FROM DM_PADM_CALCULATION_CELL WHERE CALCULATION_RUN_ID = :V_RUN_ID;

    UPDATE DM_PADM_CALCULATION_RUN
    SET CALCULATION_STATUS = 'COMPLETED', CALCULATION_COMPLETED_TS = CURRENT_TIMESTAMP()
    WHERE CALCULATION_RUN_ID = :V_RUN_ID;

    COMMIT;
    RETURN :V_RUN_ID || '|' || :V_CELL_COUNT;
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_GENERATE_SIGNATURE_PAGE_2(
    P_CAMPAIGN_ID VARCHAR,
    P_CALCULATION_RUN_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_RUN_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_ROW_COUNT NUMBER(38,0);
BEGIN
    SELECT CALCULATION_STATUS INTO :V_RUN_STATUS FROM DM_PADM_CALCULATION_RUN
    WHERE CALCULATION_RUN_ID = :P_CALCULATION_RUN_ID AND CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_RUN_STATUS IS NULL) THEN
        RETURN 'Calculation run not found for this campaign.';
    END IF;
    IF (V_RUN_STATUS <> 'COMPLETED') THEN
        RETURN 'Calculation run is not COMPLETED yet.';
    END IF;

    SELECT COALESCE(MAX(SIGNATURE_VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT
    (SIGNATURE_PAGE_2_SNAPSHOT_ID, CAMPAIGN_ID, CALCULATION_RUN_ID, SIGNATURE_VERSION_NUMBER,
     CAMPAIGN_OFFER_ID, SEGMENT_ID, POPULATION_DESCRIPTION, SEGMENT_DESCRIPTION, ANNUAL_FEE,
     TEST_TYPE, NETWORK, CREDIT_BUREAU_MODEL, CREDIT_BUREAU_SCORE, CRS_MODEL, CRS_SCORE, NRM,
     QUANTITY, NBR, BOARDS, CPP, MARKETING_EXPENSE, UNWIND_RATE, PRE_UNWIND_CPA, POST_UNWIND_CPA,
     PROMO, IVR, UNDERWRITING_FLAG, PROSPECT_TYPE, TIMES_MAILED_0_PERCENTAGE, TIERS, PRINT_VENDOR,
     POST_UNWIND_BOARDS, MARKETING_PLUS_BOOKING_COSTS, SNAPSHOT_STATUS)
    SELECT
        UUID_STRING(), A.CAMPAIGN_ID, R.CALCULATION_RUN_ID, :V_NEXT_VERSION,
        A.CAMPAIGN_OFFER_ID, A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION,
        CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1),'/',TO_VARCHAR(P.ANNUAL_FEE_YR2)), O.TEST_TYPE, P.NETWORK,
        O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, O.CRS_MODEL, O.CRS_SCORE, O.NRM,
        SUM(C.SELECTED_QUANTITY),
        SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0),
        SUM(C.BOOKED_PRE_UNWIND_SELECTED),
        SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0),
        SUM(C.MARKETING_COST_SELECTED),
        SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0),
        SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0),
        SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0),
        O.PROMO_CODE, O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE,
        MAX(TMP.TIMES_MAILED_0_PERCENTAGE),
        LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ') WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER)),
        O.PRINT_VENDOR_ID,
        SUM(C.BOOKED_POST_UNWIND_SELECTED),
        SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED),
        R.CALCULATION_STATUS
    FROM DM_PADM_OFFER_SEGMENT_ALLOCATION AS A
    INNER JOIN VW_PADM_CAMPAIGN_OFFER_CURRENT AS O ON A.CAMPAIGN_OFFER_ID = O.CAMPAIGN_OFFER_ID
    LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P ON O.PROGRAM_CODE = P.PROGRAM_CODE AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
    INNER JOIN DM_PADM_CALCULATION_RUN AS R ON A.CAMPAIGN_ID = R.CAMPAIGN_ID
    INNER JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C ON A.CAMPAIGN_ID = C.CAMPAIGN_ID AND A.SEGMENT_ID = C.SEGMENT_ID
    LEFT JOIN (
        SELECT CAMPAIGN_OFFER_ID,
               TIMES_MAILED_0_COUNT / NULLIF(TIMES_MAILED_0_COUNT+TIMES_MAILED_1_COUNT+TIMES_MAILED_2_COUNT+TIMES_MAILED_3_COUNT
                   +TIMES_MAILED_4_COUNT+TIMES_MAILED_5_COUNT+TIMES_MAILED_6_COUNT+TIMES_MAILED_7_COUNT+TIMES_MAILED_8_COUNT
                   +TIMES_MAILED_9_PLUS_COUNT, 0) AS TIMES_MAILED_0_PERCENTAGE
        FROM DM_PADM_CAMPAIGN_OFFER_PROFILE WHERE IS_CURRENT = TRUE
    ) AS TMP ON A.CAMPAIGN_OFFER_ID = TMP.CAMPAIGN_OFFER_ID
    WHERE A.IS_CURRENT = TRUE AND R.CALCULATION_RUN_ID = :P_CALCULATION_RUN_ID
    GROUP BY A.CAMPAIGN_ID, R.CALCULATION_RUN_ID, A.CAMPAIGN_OFFER_ID,
             A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION, P.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR2,
             O.TEST_TYPE, P.NETWORK, O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, O.CRS_MODEL, O.CRS_SCORE, O.NRM, O.PROMO_CODE,
             O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE, O.PRINT_VENDOR_ID, R.CALCULATION_STATUS;

    SELECT COUNT(*) INTO :V_ROW_COUNT FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SIGNATURE_VERSION_NUMBER = :V_NEXT_VERSION;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, CHANGE_REASON, CHANGED_BY)
    VALUES (UUID_STRING(), :P_CAMPAIGN_ID, 'SIGNATURE_PAGE_2', :P_CALCULATION_RUN_ID, 'SNAPSHOT_CREATED',
            'Signature Page 2 v' || :V_NEXT_VERSION || ' generated', CURRENT_USER());

    COMMIT;
    RETURN 'Signature Page 2 version ' || :V_NEXT_VERSION || ' created (' || :V_ROW_COUNT || ' rows).';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

CREATE OR REPLACE VIEW VW_PADM_SIGNATURE_PAGE_LIVE AS
WITH TIMES_MAILED_0 AS (
    SELECT CAMPAIGN_OFFER_ID,
           TIMES_MAILED_0_COUNT / NULLIF(TIMES_MAILED_0_COUNT+TIMES_MAILED_1_COUNT+TIMES_MAILED_2_COUNT+TIMES_MAILED_3_COUNT
               +TIMES_MAILED_4_COUNT+TIMES_MAILED_5_COUNT+TIMES_MAILED_6_COUNT+TIMES_MAILED_7_COUNT+TIMES_MAILED_8_COUNT
               +TIMES_MAILED_9_PLUS_COUNT, 0) AS TIMES_MAILED_0_PERCENTAGE
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE WHERE IS_CURRENT = TRUE
)
SELECT
    A.CAMPAIGN_ID,
    A.CAMPAIGN_OFFER_ID,
    A.SEGMENT_ID,
    A.POPULATION_DESCRIPTION,
    O.OFFER_DESCRIPTION                                                              AS SEGMENT_DESCRIPTION,
    O.TEST_TYPE,
    P.NETWORK,
    O.CREDIT_BUREAU_MODEL,
    O.CREDIT_BUREAU_SCORE,
    O.CRS_MODEL,
    O.CRS_SCORE,
    O.NRM,
    CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1), '/', TO_VARCHAR(P.ANNUAL_FEE_YR2))          AS ANNUAL_FEE,
    O.PROMO_CODE                                                                     AS PROMO,
    O.APPROVAL_CODE                                                                  AS IVR,
    O.UNDERWRITING_FLAG,
    O.PROSPECT_TYPE,
    O.PRINT_VENDOR_ID                                                                AS PRINT_VENDOR,
    T0.TIMES_MAILED_0_PERCENTAGE,
    SUM(C.SELECTED_QUANTITY)                                                         AS QUANTITY,
    SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0)  AS NBR,
    SUM(C.BOOKED_PRE_UNWIND_SELECTED)                                                AS BOARDS,
    SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS CPP,
    SUM(C.MARKETING_COST_SELECTED)                                                   AS MARKETING_EXPENSE,
    SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)  AS UNWIND_RATE,
    SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0)    AS PRE_UNWIND_CPA,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0) AS POST_UNWIND_CPA,
    SUM(C.BOOKED_POST_UNWIND_SELECTED)                                               AS POST_UNWIND_BOARDS,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)                         AS MARKETING_PLUS_BOOKING_COSTS,
    LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ') WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER)) AS TIERS
FROM DM_PADM_OFFER_SEGMENT_ALLOCATION AS A
INNER JOIN VW_PADM_CAMPAIGN_OFFER_CURRENT AS O ON A.CAMPAIGN_OFFER_ID = O.CAMPAIGN_OFFER_ID
LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P ON O.PROGRAM_CODE = P.PROGRAM_CODE AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
LEFT JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C ON A.CAMPAIGN_ID = C.CAMPAIGN_ID AND A.SEGMENT_ID = C.SEGMENT_ID
LEFT JOIN TIMES_MAILED_0 AS T0 ON A.CAMPAIGN_OFFER_ID = T0.CAMPAIGN_OFFER_ID
WHERE A.IS_CURRENT = TRUE
GROUP BY A.CAMPAIGN_ID, A.CAMPAIGN_OFFER_ID, A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION,
         O.TEST_TYPE, P.NETWORK, O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, O.CRS_MODEL, O.CRS_SCORE, O.NRM, P.ANNUAL_FEE_YR1,
         P.ANNUAL_FEE_YR2, O.PROMO_CODE, O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE,
         O.PRINT_VENDOR_ID, T0.TIMES_MAILED_0_PERCENTAGE;

SELECT 'SP_PADM_SAVE_SEGMENT_ASSUMPTION' AS OBJECT_NAME, COUNT(*) AS FOUND FROM INFORMATION_SCHEMA.PROCEDURES WHERE PROCEDURE_NAME = 'SP_PADM_SAVE_SEGMENT_ASSUMPTION'
UNION ALL SELECT 'SP_PADM_SAVE_SELECTION_SET', COUNT(*) FROM INFORMATION_SCHEMA.PROCEDURES WHERE PROCEDURE_NAME = 'SP_PADM_SAVE_SELECTION_SET'
