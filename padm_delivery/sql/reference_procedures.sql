UNION ALL SELECT 'SP_PADM_GENERATE_SIGNATURE_PAGE_2', COUNT(*) FROM INFORMATION_SCHEMA.PROCEDURES WHERE PROCEDURE_NAME = 'SP_PADM_GENERATE_SIGNATURE_PAGE_2'
