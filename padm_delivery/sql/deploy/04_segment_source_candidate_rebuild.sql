-- Rebuild of VW_PADM_SEGMENT_SOURCE_CANDIDATE, sourced from the real project tables
-- (CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE / T_TRANSUNION_MAILFILE) instead of
-- DM_PADM_TR_MAILFILE_NORMALIZED (dropped 2026-11-19 -- confirmed not part of this project).
--
-- Column list is unchanged from the original view (confirmed via GET_DDL earlier this session),
-- so repository.discover_segments()'s MERGE needs no changes -- it just reads this view by name.
--
-- Simplifications made, and why:
--   - ANNUAL_FEE / NETWORK / MAIL_REMAIL are NULL here. The raw mailfile tables (confirmed via
--     their real data dictionaries) don't carry these -- they're offer/program-level attributes,
--     not prospect-level. Safe to leave NULL: DM_PADM_SEGMENT_1 has all three as nullable
--     columns (confirmed via DESC TABLE), and Create Segment's own form never requires them.
--   - CAMPAIGN_SOURCE / CAMPAIGN_SCORE_SEGMENT (seen in both raw tables) were NOT used -- they're
--     internal letter/number codes (e.g. 'A','V','1'..'9') with no decode table available, and
--     PROSPECT_TYPE / PROSPECT_SOURCE already give the same classification in clean, readable form.
--   - BUREAU_SCORE_TYPE / SCORE_MIN / SCORE_MAX come from banding the RAW numeric score columns
--     (PRESCREEN_VANTAGE_V3, PRESCREEN_VANTAGE_V4, LIFT_SCORE) against DM_PADM_SCORE_RANGE_RULE_1
--     (the "_1" table -- the one the app actually reads elsewhere, not the no-suffix
--     DM_PADM_SCORE_RANGE_RULE) via a SCORE_MIN/SCORE_MAX BETWEEN join. Confirmed real ranges:
--     Experian VS3 4-823, VS4 0-850, LIFT 500-807; TransUnion VS3 0-730 (the low sentinel values
--     like 0/4 naturally fail to match any real band and are dropped by the INNER JOIN).
--   - TransUnion has no LIFT_SCORE column (confirmed from its data dictionary) -- no TRANSUNION +
--     LIFT branch exists here. The Create Segment dropdown shows LIFT for TransUnion anyway (the
--     user's explicit UI choice); selecting it will correctly hit "no active score-range rules"
--     until/unless real TransUnion LIFT data is found elsewhere.

USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_SOURCE_CANDIDATE(
    SEGMENT_KEY,
    SUGGESTED_SEGMENT_NAME,
    SOURCE_SEGMENT_NAME,
    SOURCE,
    BUREAU_SCORE_TYPE,
    BUREAU_SCORE_RANGE,
    SCORE_MIN,
    SCORE_MAX,
    PROSPECT_SEGMENT_TYPE,
    ANNUAL_FEE,
    NETWORK,
    MLA_FLAG,
    RESPONSE_MODEL_TYPE,
    RISK_SCORE_TYPE,
    MAIL_REMAIL,
    SOURCE_RECORD_COUNT,
    FIRST_MAIL_DATE,
    LAST_MAIL_DATE
) AS
WITH RAW_SCORES AS
(
    SELECT 'EXPERIAN' AS SOURCE, TRIM(UPPER(PROSPECT_TYPE)) AS PROSPECT_SEGMENT_TYPE,
           PROSPECT_SOURCE AS SOURCE_SEGMENT_NAME, UPPER(COALESCE(MLA_INDICATOR, 'N')) AS MLA_FLAG,
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE,
           'VS3' AS BUREAU_SCORE_TYPE, PRESCREEN_VANTAGE_V3 AS RAW_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL

    UNION ALL
    SELECT 'EXPERIAN', TRIM(UPPER(PROSPECT_TYPE)), PROSPECT_SOURCE, UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS4', PRESCREEN_VANTAGE_V4
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V4 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL

    UNION ALL
    SELECT 'EXPERIAN', TRIM(UPPER(PROSPECT_TYPE)), PROSPECT_SOURCE, UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'LIFT', LIFT_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE LIFT_SCORE IS NOT NULL AND PROSPECT_TYPE IS NOT NULL

    UNION ALL
    SELECT 'TRANSUNION', TRIM(UPPER(PROSPECT_TYPE)), PROSPECT_SOURCE, UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS3', PRESCREEN_VANTAGE_V3
    FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL AND PROSPECT_TYPE IS NOT NULL
)
SELECT
      SHA2(
          CONCAT_WS('|', M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, M.PROSPECT_SEGMENT_TYPE,
                     COALESCE(M.MLA_FLAG, ''), COALESCE(M.RESPONSE_MODEL_TYPE, ''), COALESCE(M.RISK_SCORE_TYPE, '')),
          256
      ) AS SEGMENT_KEY
    , M.BUREAU_SCORE_TYPE || ' ' || TO_VARCHAR(R.SCORE_MIN) || '-' || TO_VARCHAR(R.SCORE_MAX) || ' ' || M.SOURCE AS SUGGESTED_SEGMENT_NAME
    , M.SOURCE_SEGMENT_NAME
    , M.SOURCE
    , M.BUREAU_SCORE_TYPE
    , R.SCORE_RANGE_CODE AS BUREAU_SCORE_RANGE
    , R.SCORE_MIN
    , R.SCORE_MAX
    , M.PROSPECT_SEGMENT_TYPE
    , NULL AS ANNUAL_FEE
    , NULL AS NETWORK
    , M.MLA_FLAG
    , M.RESPONSE_MODEL_TYPE
    , M.RISK_SCORE_TYPE
    , NULL AS MAIL_REMAIL
    , COUNT(1) AS SOURCE_RECORD_COUNT
    , MIN(M.MAIL_DATE) AS FIRST_MAIL_DATE
    , MAX(M.MAIL_DATE) AS LAST_MAIL_DATE
FROM RAW_SCORES AS M
INNER JOIN DB_RISK.RISK_SBX.DM_PADM_SCORE_RANGE_RULE_1 AS R
        ON UPPER(M.BUREAU_SCORE_TYPE) = UPPER(R.SCORE_TYPE)
       AND M.RAW_SCORE BETWEEN R.SCORE_MIN AND R.SCORE_MAX
       AND R.ACTIVE_FLAG = TRUE
GROUP BY M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, R.SCORE_MIN, R.SCORE_MAX,
         M.PROSPECT_SEGMENT_TYPE, M.SOURCE_SEGMENT_NAME, M.MLA_FLAG, M.RESPONSE_MODEL_TYPE, M.RISK_SCORE_TYPE;

-- Sanity check: should return real rows, grouped by bureau/score-type/band.
SELECT SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX,
       COUNT(DISTINCT PROSPECT_SEGMENT_TYPE) AS DISTINCT_PROSPECT_TYPES, SUM(SOURCE_RECORD_COUNT) AS TOTAL_RECORDS
FROM VW_PADM_SEGMENT_SOURCE_CANDIDATE
GROUP BY SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX
ORDER BY SOURCE, BUREAU_SCORE_TYPE, SCORE_MIN;
