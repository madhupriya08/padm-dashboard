-- -------------------------------------------------------------------------------------------
-- Segment-level assumptions. NULL = inherit the campaign-level value. CPP is campaign-only and
-- is carried forward from the previous segment version.
-- Seasonality is a fraction that may be negative (spec 5.2), bounded to [-1, 1].
-- -------------------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SEGMENT_ASSUMPTION
(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_UNIT_COST_OVERRIDE NUMBER(18,4),
    P_NBR_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_OVERRIDE NUMBER(18,8),
    P_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_SEASONALITY_REDUCTION_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_EXPECTED_VERSION NUMBER(10,0),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_CURRENT_VERSION NUMBER(10,0);
    V_NEXT_VERSION NUMBER(10,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;
    IF ((P_UNIT_COST_OVERRIDE IS NOT NULL AND P_UNIT_COST_OVERRIDE < 0)
        OR (P_NBR_OVERRIDE IS NOT NULL AND P_NBR_OVERRIDE < 0)
        OR (P_UNWIND_RATE_OVERRIDE IS NOT NULL AND P_UNWIND_RATE_OVERRIDE < 0)) THEN
        RETURN 'ERROR: Unit Cost, NBR and Unwind Rate must be >= 0.';
    END IF;
    IF (P_SEASONALITY_REDUCTION_OVERRIDE IS NOT NULL
        AND (P_SEASONALITY_REDUCTION_OVERRIDE < -1 OR P_SEASONALITY_REDUCTION_OVERRIDE > 1)) THEN
        RETURN 'ERROR: Seasonality Rate Adjustment must be between -100% and 100%.';
    END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) INTO :V_CURRENT_VERSION
    FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;
    IF (P_EXPECTED_VERSION IS NOT NULL AND V_CURRENT_VERSION <> P_EXPECTED_VERSION) THEN
        RETURN 'ERROR: Record changed by another user -- reload.';
    END IF;
    V_NEXT_VERSION := V_CURRENT_VERSION + 1;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'SEGMENT_ASSUMPTION', :P_SEGMENT_ID, 'VERSION_CREATED'
        , (SELECT OBJECT_CONSTRUCT('VERSION_NUMBER', VERSION_NUMBER, 'UNIT_COST', UNIT_COST_OVERRIDE,
                                    'NBR', NBR_OVERRIDE, 'UNWIND_RATE', UNWIND_RATE_OVERRIDE,
                                    'RATE_ADJUSTMENT', RATE_ADJUSTMENT_OVERRIDE,
                                    'SEASONALITY_REDUCTION', SEASONALITY_REDUCTION_OVERRIDE,
                                    'UNWIND_RATE_ADJUSTMENT', UNWIND_RATE_ADJUSTMENT_OVERRIDE)
           FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
           WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE)
        , OBJECT_CONSTRUCT('VERSION_NUMBER', :V_NEXT_VERSION, 'UNIT_COST', :P_UNIT_COST_OVERRIDE,
                            'NBR', :P_NBR_OVERRIDE, 'UNWIND_RATE', :P_UNWIND_RATE_OVERRIDE,
                            'RATE_ADJUSTMENT', :P_RATE_ADJUSTMENT_OVERRIDE,
                            'SEASONALITY_REDUCTION', :P_SEASONALITY_REDUCTION_OVERRIDE,
                            'UNWIND_RATE_ADJUSTMENT', :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE)
        , :P_CHANGE_REASON;

    INSERT INTO DM_PADM_SEGMENT_ASSUMPTION_VERSION
    (
        SEGMENT_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER
      , CPP_OVERRIDE, UNIT_COST_OVERRIDE, NBR_OVERRIDE, UNWIND_RATE_OVERRIDE
      , RATE_ADJUSTMENT_OVERRIDE, SEASONALITY_REDUCTION_OVERRIDE, UNWIND_RATE_ADJUSTMENT_OVERRIDE
      , IS_CURRENT, CHANGE_REASON, ROW_VERSION, UPDATED_BY, UPDATED_TS
    )
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION
         , P.CPP_OVERRIDE, :P_UNIT_COST_OVERRIDE, :P_NBR_OVERRIDE, :P_UNWIND_RATE_OVERRIDE
         , :P_RATE_ADJUSTMENT_OVERRIDE, :P_SEASONALITY_REDUCTION_OVERRIDE, :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE
         , FALSE, :P_CHANGE_REASON, :V_NEXT_VERSION, CURRENT_USER(), CURRENT_TIMESTAMP()
    FROM (SELECT 1 AS K) AS D
    LEFT JOIN DM_PADM_SEGMENT_ASSUMPTION_VERSION AS P
           ON P.CAMPAIGN_ID = :P_CAMPAIGN_ID AND P.SEGMENT_ID = :P_SEGMENT_ID AND P.IS_CURRENT = TRUE;

    UPDATE DM_PADM_SEGMENT_ASSUMPTION_VERSION
       SET IS_CURRENT = (VERSION_NUMBER = :V_NEXT_VERSION)
         , EFFECTIVE_TO_TS = IFF(VERSION_NUMBER = :V_NEXT_VERSION, NULL, CURRENT_TIMESTAMP())
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND SEGMENT_ID = :P_SEGMENT_ID
       AND (IS_CURRENT = TRUE OR VERSION_NUMBER = :V_NEXT_VERSION);

    COMMIT;
    RETURN 'Segment assumption version ' || :V_NEXT_VERSION || ' saved.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

