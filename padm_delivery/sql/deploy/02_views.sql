    , SEGMENT_ID
    , VERSION_NUMBER
    , CPP_OVERRIDE
    , UNIT_COST_OVERRIDE
    , NBR_OVERRIDE
    , UNWIND_RATE_OVERRIDE
    , RATE_ADJUSTMENT_OVERRIDE
    , SEASONALITY_REDUCTION_OVERRIDE
    , UNWIND_RATE_ADJUSTMENT_OVERRIDE
    , CHANGE_REASON
    , CREATED_BY
    , CREATED_TS
