-- ===========================================================================================
-- 2. VW_PADM_CAMPAIGN_OFFER_CURRENT -- same passthrough as before, with the 2 new columns
--    added (placed after CRS_SCORE, matching the sign-off proposal's field grouping).
--    Full CREATE OR REPLACE required to change a view's column list.
-- ===========================================================================================

CREATE OR REPLACE VIEW VW_PADM_CAMPAIGN_OFFER_CURRENT(
    CAMPAIGN_OFFER_ID,
    CAMPAIGN_ID,
    CAMPAIGN_SOURCE_COMPONENT_ID,
    OFFER_RESERVATION_CODE,
    PROGRAM_CODE,
    PROGRAM_VERSION_NUMBER,
    SOURCE_MAIL_DATE,
    OFFER_DESCRIPTION,
    OFFER_SEGMENT_NAME,
    TEST_TYPE,
    SOURCE_CPP,
    PROMO_CODE,
    APPROVAL_CODE,
    UNDERWRITING_FLAG,
    PROSPECT_TYPE,
    PRINT_VENDOR_ID,
    CRS_SCORE,
    CREDIT_BUREAU_MODEL,
    CREDIT_BUREAU_SCORE,
    OFFER_STATUS
) AS
SELECT
      O.CAMPAIGN_OFFER_ID
    , O.CAMPAIGN_ID
    , O.CAMPAIGN_SOURCE_COMPONENT_ID
    , O.OFFER_RESERVATION_CODE
    , O.PROGRAM_CODE
    , O.PROGRAM_VERSION_NUMBER
    , O.SOURCE_MAIL_DATE
    , O.OFFER_DESCRIPTION
    , O.OFFER_SEGMENT_NAME
    , O.TEST_TYPE
    , O.SOURCE_CPP
    , O.PROMO_CODE
    , O.APPROVAL_CODE
    , O.UNDERWRITING_FLAG
    , O.PROSPECT_TYPE
    , O.PRINT_VENDOR_ID
    , O.CRS_SCORE
    , O.CREDIT_BUREAU_MODEL
    , O.CREDIT_BUREAU_SCORE
    , O.OFFER_STATUS
FROM DM_PADM_CAMPAIGN_OFFER AS O
INNER JOIN DM_PADM_CAMPAIGN_SOURCE_VERSION AS S
    ON O.CAMPAIGN_SOURCE_VERSION_ID = S.CAMPAIGN_SOURCE_VERSION_ID
   AND S.IS_CURRENT = TRUE
WHERE O.IS_CURRENT = TRUE;

-- ===========================================================================================
-- 3. SP_PADM_ACTIVATE_CAMPAIGN -- identical to the existing procedure, with CREDIT_BUREAU_MODEL /
--    CREDIT_BUREAU_SCORE added to the DM_PADM_CAMPAIGN_OFFER INSERT's column list and its SELECT
--    (pulling S.CREDIT_BUREAU_MODEL / S.CREDIT_BUREAU_SCORE, which VW_PADM_ACM_OFFER_SOURCE
--    already provides). Nothing else in this procedure was changed -- same validations, same
--    hash, same QUALIFY dedup.
--
--    NOTE: this procedure checks V_STATUS NOT IN ('DISCOVERED', 'REOPENED', 'DRAFT') -- i.e. the
--    OLD status vocabulary is live in this real, currently-running procedure, not just in stale
--    DDL/docs.
-- ===========================================================================================
CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CAMPAIGN(P_CAMPAIGN_ID VARCHAR, P_CHANGE_REASON VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_REPORTING_MONTH DATE;
    V_CAMPAIGN_TYPE VARCHAR;
    V_SOURCE_VERSION_ID VARCHAR;
    V_LOAD_BATCH_ID VARCHAR;
    V_SOURCE_HASH VARCHAR;
    V_NEXT_SOURCE_VERSION NUMBER(10,0);
    V_CURRENT_VERSION_COUNT NUMBER DEFAULT 0;
    V_COMPONENT_COUNT NUMBER DEFAULT 0;
    V_OFFER_COUNT NUMBER DEFAULT 0;
    V_PROFILE_COUNT NUMBER DEFAULT 0;
BEGIN
    SELECT MAX(STATUS), MAX(REPORTING_MONTH), MAX(CAMPAIGN_TYPE)
      INTO :V_STATUS, :V_REPORTING_MONTH, :V_CAMPAIGN_TYPE
    FROM DM_PADM_CAMPAIGN_1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS IS NULL) THEN
        RETURN 'Campaign was not found.';
    END IF;

    IF (V_STATUS NOT IN ('DISCOVERED', 'REOPENED', 'DRAFT')) THEN
        RETURN 'Only DISCOVERED, REOPENED, or incomplete DRAFT campaigns can be activated.';
    END IF;

    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN
        RETURN 'Change Reason is required.';
    END IF;

    SELECT COUNT(*)
      INTO :V_CURRENT_VERSION_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_CURRENT_VERSION_COUNT > 0) THEN
        RETURN 'Campaign already has a current source version.';
    END IF;

    SELECT COALESCE(MAX(SOURCE_VERSION_NUMBER), 0) + 1
      INTO :V_NEXT_SOURCE_VERSION
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    V_SOURCE_VERSION_ID := UUID_STRING();
    V_LOAD_BATCH_ID := UUID_STRING();

    SELECT SHA2(
                COALESCE(TO_VARCHAR(:V_REPORTING_MONTH), '') || '|' ||
                COALESCE(:V_CAMPAIGN_TYPE, '') || '|' ||
                COALESCE(TO_VARCHAR(COUNT(*)), '') || '|' ||
                COALESCE(TO_VARCHAR(MIN(SOURCE_MAIL_DATE)), '') || '|' ||
                COALESCE(TO_VARCHAR(MAX(SOURCE_MAIL_DATE)), ''),
                256
           )
      INTO :V_SOURCE_HASH
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    IF (V_SOURCE_HASH IS NULL) THEN
        RETURN 'No eligible ACM offers were found for the campaign month and type.';
    END IF;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_VERSION
    (
        CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_VERSION_NUMBER
      , SOURCE_HASH
      , SOURCE_ROW_COUNT
      , SOURCE_MIN_MAIL_DATE
      , SOURCE_MAX_MAIL_DATE
      , LOAD_BATCH_ID
      , IS_CURRENT
      , CHANGE_SUMMARY
    )
    SELECT
        :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , :V_NEXT_SOURCE_VERSION
      , :V_SOURCE_HASH
      , COUNT(*)
      , MIN(SOURCE_MAIL_DATE)
      , MAX(SOURCE_MAIL_DATE)
      , :V_LOAD_BATCH_ID
      , TRUE
      , :P_CHANGE_REASON
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    (
        CAMPAIGN_SOURCE_COMPONENT_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , SOURCE_OFFER_COUNT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , COUNT(DISTINCT OFFER_RESERVATION_CODE)
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    GROUP BY
        SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE;

    -- *** CHANGED: CREDIT_BUREAU_MODEL, CREDIT_BUREAU_SCORE added below (target + SELECT) ***
    INSERT INTO DM_PADM_CAMPAIGN_OFFER
    (
        CAMPAIGN_OFFER_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , CAMPAIGN_SOURCE_COMPONENT_ID
      , OFFER_RESERVATION_CODE
      , PROGRAM_CODE
      , PROGRAM_VERSION_NUMBER
      , PROGRAM_MATCH_STATUS
      , MATCHED_PROGRAM_VERSION_NUMBER
      , SOURCE_CAMPAIGN_CODE
      , SOURCE_CAMPAIGN_NAME
      , SOURCE_CAMPAIGN_DESCRIPTION
      , SOURCE_MAIL_DATE
      , OFFER_DESCRIPTION
      , OFFER_SEGMENT_NAME
      , TEST_TYPE
      , SOURCE_CPP
      , PROMO_CODE
      , APPROVAL_CODE
      , UNDERWRITING_FLAG
      , PROSPECT_TYPE
      , PRINT_VENDOR_ID
      , CRS_SCORE
      , CREDIT_BUREAU_MODEL
      , CREDIT_BUREAU_SCORE
      , OFFER_STATUS
      , SOURCE_RECORD_ID
      , SOURCE_ROW_HASH
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , C.CAMPAIGN_SOURCE_COMPONENT_ID
      , S.OFFER_RESERVATION_CODE
      , S.PROGRAM_CODE
      , S.PROGRAM_VERSION_NUMBER
      , S.PROGRAM_MATCH_STATUS
      , S.MATCHED_PROGRAM_VERSION_NUMBER
      , S.SOURCE_CAMPAIGN_CODE
      , S.SOURCE_CAMPAIGN_NAME
      , S.SOURCE_CAMPAIGN_DESCRIPTION
      , S.SOURCE_MAIL_DATE
      , S.OFFER_DESCRIPTION
      , S.ACM_SEGMENT_NAME
      , S.TEST_TYPE
      , S.SOURCE_CPP
      , S.PROMO
      , S.IVR
      , S.UNDERWRITING_FLAG
      , S.PROSPECT_TYPE
      , S.PRINT_VENDOR_ID
      , S.CRS_SCORE
      , S.CREDIT_BUREAU_MODEL
      , S.CREDIT_BUREAU_SCORE
      , S.SOURCE_OFFER_STATUS
      , S.SOURCE_RECORD_ID
      , SHA2(
            COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') || '|' ||
            COALESCE(S.OFFER_RESERVATION_CODE, '') || '|' ||
            COALESCE(S.PROGRAM_CODE, '') || '|' ||
            COALESCE(TO_VARCHAR(S.PROGRAM_VERSION_NUMBER), '') || '|' ||
            COALESCE(S.OFFER_DESCRIPTION, '') || '|' ||
            COALESCE(TO_VARCHAR(S.SOURCE_CPP), ''),
            256
        )
      , TRUE
    FROM VW_PADM_ACM_OFFER_SOURCE AS S
    INNER JOIN DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS C
        ON C.CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND C.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
       AND COALESCE(C.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '')
       AND COALESCE(C.SOURCE_CAMPAIGN_GROUP_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_GROUP_CODE, '')
       AND C.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE DATE_TRUNC('MONTH', S.SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.OFFER_RESERVATION_CODE
        ORDER BY S.SOURCE_MAIL_DATE DESC, S.SOURCE_RECORD_ID DESC
    ) = 1;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER_PROFILE
    (
        CAMPAIGN_OFFER_PROFILE_ID
      , CAMPAIGN_ID
      , CAMPAIGN_OFFER_ID
      , PROFILE_VERSION_NUMBER
      , PROFILE_SOURCE_TYPE
      , ANNUAL_FEE
      , NETWORK
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , O.CAMPAIGN_ID
      , O.CAMPAIGN_OFFER_ID
      , 1
      , 'ACM_SOURCE'
      , S.ANNUAL_FEE
      , S.NETWORK
      , TRUE
    FROM DM_PADM_CAMPAIGN_OFFER AS O
    INNER JOIN VW_PADM_ACM_OFFER_SOURCE AS S
        ON O.OFFER_RESERVATION_CODE = S.OFFER_RESERVATION_CODE
       AND O.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE O.CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND O.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.CAMPAIGN_OFFER_ID
        ORDER BY S.SOURCE_RECORD_ID DESC
    ) = 1;

    UPDATE DM_PADM_CAMPAIGN_1
       SET STATUS = 'DRAFT'
         , ACTIVE_FLAG = TRUE
         , SOURCE_CHANGE_PENDING_FLAG = FALSE
         , CURRENT_SOURCE_VERSION_NUMBER = :V_NEXT_SOURCE_VERSION
         , ROW_VERSION = COALESCE(ROW_VERSION, 0) + 1
         , UPDATED_BY = CURRENT_USER()
         , UPDATED_TS = CURRENT_TIMESTAMP()
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS <> 'DRAFT') THEN
        INSERT INTO DM_PADM_WORKFLOW_EVENT
        (
            WORKFLOW_EVENT_ID
          , CAMPAIGN_ID
          , FROM_STATUS
          , TO_STATUS
          , EVENT_REASON
        )
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_STATUS, 'DRAFT', :P_CHANGE_REASON;
    END IF;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
        CHANGE_EVENT_ID
      , CAMPAIGN_ID
      , ENTITY_TYPE
      , ENTITY_ID
      , CHANGE_TYPE
      , BEFORE_VALUE
      , AFTER_VALUE
      , CHANGE_REASON
    )
    SELECT
        UUID_STRING()
      , :P_CAMPAIGN_ID
      , 'CAMPAIGN_SOURCE_VERSION'
      , :V_SOURCE_VERSION_ID
      , IFF(:V_STATUS = 'DRAFT', 'SOURCE_SNAPSHOT_REPAIRED', 'CAMPAIGN_ACTIVATED')
      , NULL
      , OBJECT_CONSTRUCT(
            'SOURCE_VERSION_NUMBER', :V_NEXT_SOURCE_VERSION,
            'REPORTING_MONTH', :V_REPORTING_MONTH,
            'CAMPAIGN_TYPE', :V_CAMPAIGN_TYPE
        )
      , :P_CHANGE_REASON;

    SELECT COUNT(*) INTO :V_COMPONENT_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_OFFER_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_PROFILE_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_COMPONENT_COUNT = 0 OR V_OFFER_COUNT = 0 OR V_PROFILE_COUNT <> V_OFFER_COUNT) THEN
        ROLLBACK;
        RETURN 'Source snapshot validation failed. No changes were committed.';
    END IF;

    COMMIT;
    RETURN 'Campaign source snapshot completed. Components: '
        || TO_VARCHAR(V_COMPONENT_COUNT)
        || ', Offers: '
        || TO_VARCHAR(V_OFFER_COUNT)
        || ', Profiles: '
        || TO_VARCHAR(V_PROFILE_COUNT)
        || '.';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

-- ===========================================================================================
-- 4. One-time backfill for offers already activated BEFORE this change (their rows got NULL
--    from the ALTER TABLE above). Safe to run once; re-running only touches rows still NULL.
--    Uses the same dedup (QUALIFY) the procedure itself uses, so it won't double-match.
-- ===========================================================================================

UPDATE DM_PADM_CAMPAIGN_OFFER AS O
SET CREDIT_BUREAU_MODEL = S.CREDIT_BUREAU_MODEL,
    CREDIT_BUREAU_SCORE = S.CREDIT_BUREAU_SCORE
FROM (
    SELECT OFFER_RESERVATION_CODE, SOURCE_MAIL_DATE, CREDIT_BUREAU_MODEL, CREDIT_BUREAU_SCORE
    FROM VW_PADM_ACM_OFFER_SOURCE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY OFFER_RESERVATION_CODE
        ORDER BY SOURCE_MAIL_DATE DESC, SOURCE_RECORD_ID DESC
    ) = 1
) AS S
WHERE O.OFFER_RESERVATION_CODE = S.OFFER_RESERVATION_CODE
  AND O.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
  AND O.CREDIT_BUREAU_MODEL IS NULL;

