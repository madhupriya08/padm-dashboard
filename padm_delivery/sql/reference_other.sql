EXECUTE IMMEDIATE $$
DECLARE
    V_CAMPAIGN_ID VARCHAR;
    V_RESULT VARCHAR;
    V_COMPLETED_COUNT NUMBER DEFAULT 0;
    C_CAMPAIGNS CURSOR FOR
        SELECT C.CAMPAIGN_ID
        FROM DM_PADM_CAMPAIGN_1 AS C
        WHERE C.REPORTING_MONTH >= DATE '2026-01-01'
          AND C.REPORTING_MONTH < DATE '2026-05-01'
          AND C.STATUS IN ('DISCOVERED', 'REOPENED', 'DRAFT')
          AND NOT EXISTS
            (
                SELECT 1
                FROM DM_PADM_CAMPAIGN_SOURCE_VERSION AS V
                WHERE V.CAMPAIGN_ID = C.CAMPAIGN_ID
                  AND V.IS_CURRENT = TRUE
            )
        ORDER BY C.REPORTING_MONTH, C.CAMPAIGN_TYPE;
BEGIN
    FOR REC IN C_CAMPAIGNS DO
        V_CAMPAIGN_ID := REC.CAMPAIGN_ID;
        CALL SP_PADM_ACTIVATE_CAMPAIGN(:V_CAMPAIGN_ID, 'Activate January through April 2026') INTO :V_RESULT;
        IF (V_RESULT LIKE 'Campaign source snapshot completed.%') THEN
            V_COMPLETED_COUNT := V_COMPLETED_COUNT + 1;
        END IF;
    END FOR;
    RETURN 'Completed source snapshots for ' || TO_VARCHAR(V_COMPLETED_COUNT) || ' campaigns.';
END;
$$;

