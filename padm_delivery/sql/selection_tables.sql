USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

CREATE TABLE IF NOT EXISTS DM_PADM_SELECTION_WORKING
(
    CAMPAIGN_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    RESPONSE_MODEL_TIER NUMBER(10,0) NOT NULL,
    TIMES_MAILED_BUCKET VARCHAR NOT NULL,
    SELECTION_PERCENTAGE NUMBER(18,8) NOT NULL DEFAULT 0,
    SOURCE_CAMPAIGN_ID VARCHAR,
    SOURCE_SEGMENT_ID VARCHAR,
    INITIALIZATION_METHOD VARCHAR NOT NULL,
    IS_DIRTY BOOLEAN NOT NULL DEFAULT FALSE,
    ROW_VERSION NUMBER(38,0) NOT NULL DEFAULT 1,
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    UPDATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SELECTION_WORKING PRIMARY KEY
    (
        CAMPAIGN_ID,
        SEGMENT_ID,
        RESPONSE_MODEL_TIER,
        TIMES_MAILED_BUCKET
    ),
    CONSTRAINT CK_PADM_SELECTION_WORKING_PERCENT CHECK
    (
        SELECTION_PERCENTAGE BETWEEN 0 AND 1
    )
);

CREATE TABLE IF NOT EXISTS DM_PADM_SELECTION_SET
(
    SELECTION_SET_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    VERSION_NUMBER NUMBER(10,0) NOT NULL,
    STATUS VARCHAR NOT NULL,
    SOURCE_CAMPAIGN_ID VARCHAR,
    SOURCE_SEGMENT_ID VARCHAR,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    IS_FINAL BOOLEAN NOT NULL DEFAULT FALSE,
    CHANGE_REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CREATED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SELECTION_SET PRIMARY KEY (SELECTION_SET_ID),
    CONSTRAINT UQ_PADM_SELECTION_SET_VERSION UNIQUE
    (
        CAMPAIGN_ID,
        SEGMENT_ID,
        VERSION_NUMBER
    )
);

CREATE TABLE IF NOT EXISTS DM_PADM_SELECTION_SET_CELL
(
    SELECTION_SET_ID VARCHAR NOT NULL,
    RESPONSE_MODEL_TIER NUMBER(10,0) NOT NULL,
    TIMES_MAILED_BUCKET VARCHAR NOT NULL,
    SELECTION_PERCENTAGE NUMBER(18,8) NOT NULL,
    CONSTRAINT PK_PADM_SELECTION_SET_CELL PRIMARY KEY
    (
        SELECTION_SET_ID,
        RESPONSE_MODEL_TIER,
        TIMES_MAILED_BUCKET
    ),
    CONSTRAINT CK_PADM_SELECTION_SET_CELL_PERCENT CHECK
    (
        SELECTION_PERCENTAGE BETWEEN 0 AND 1
    )
);

CREATE TABLE IF NOT EXISTS DM_PADM_SELECTION_EVENT
(
    SELECTION_EVENT_ID VARCHAR NOT NULL,
    CAMPAIGN_ID VARCHAR NOT NULL,
    SEGMENT_ID VARCHAR NOT NULL,
    SELECTION_SET_ID VARCHAR,
    ACTION_TYPE VARCHAR NOT NULL,
    TIER_FROM NUMBER(10,0),
    TIER_TO NUMBER(10,0),
    TIMES_MAILED_FROM VARCHAR,
    TIMES_MAILED_TO VARCHAR,
    ENTERED_PERCENTAGE NUMBER(18,8),
    CHANGED_CELL_COUNT NUMBER(38,0),
    PRIOR_VALUE_SUMMARY VARIANT,
    CHANGE_REASON VARCHAR NOT NULL,
    CHANGED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CHANGED_TS TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PADM_SELECTION_EVENT PRIMARY KEY (SELECTION_EVENT_ID)
);
