CREATE OR REPLACE VIEW VW_PADM_CDE_DETAIL_CURRENT
AS
SELECT
      B.CDE_LOAD_BATCH_ID
    , B.CAMPAIGN_ID
    , B.SEGMENT_ID
    , B.VERSION_NUMBER AS CDE_VERSION_NUMBER
    , B.SOURCE_FILE_NAME
    , B.SOURCE_FILE_HASH
    , B.SOURCE_AS_OF_DATE
    , SUM(D.DISTINCT_EPIN_COUNT) OVER
      (
        PARTITION BY D.CDE_LOAD_BATCH_ID
      ) AS SOURCE_TOTAL_VOLUME
    , D.CDE_DETAIL_ID
    , D.VANTAGE_SCORE_BAND
    , D.TIMES_MAILED_BUCKET
    , D.TRM10_TIER
    , D.CRS23_SCORE
    , D.DISTINCT_EPIN_COUNT
    , D.SOURCE_ROW_NUMBER
FROM DM_PADM_CDE_LOAD_BATCH AS B
INNER JOIN DM_PADM_CDE_DETAIL AS D
    ON B.CDE_LOAD_BATCH_ID = D.CDE_LOAD_BATCH_ID
   AND B.CAMPAIGN_ID = D.CAMPAIGN_ID
   AND B.SEGMENT_ID = D.SEGMENT_ID
WHERE B.ACTIVE_FLAG = TRUE
  AND B.VALIDATION_STATUS = 'VALID';

-- Expected: no rows.
