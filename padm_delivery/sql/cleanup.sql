-- Idempotent -- safe to re-run.
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Drop unused legacy NRR/Unwind-history scaffolding (superseded, nothing reads these).
DROP VIEW IF EXISTS VW_PADM_NRR_CURRENT;
DROP VIEW IF EXISTS VW_PADM_UNWIND_CURRENT;
DROP TABLE IF EXISTS DM_PADM_NRR_HISTORY_CELL;
DROP TABLE IF EXISTS DM_PADM_UNWIND_HISTORY_CELL;
DROP TABLE IF EXISTS DM_PADM_HISTORY_SEGMENT_MAP;
DROP TABLE IF EXISTS DM_PADM_HISTORY_SEGMENT_KEY;
DROP TABLE IF EXISTS DM_PADM_HISTORY_LOAD_BATCH;
DROP TABLE IF EXISTS DM_PADM_SOURCE_LOAD_BATCH;
DROP TABLE IF EXISTS DM_PADM_LIFT_TIER_RULE;

-- Drop the old campaign STATUS check constraint, if present, before migrating values.
EXECUTE IMMEDIATE $$
DECLARE
    V_RESULT VARCHAR;
BEGIN
    ALTER TABLE DM_PADM_CAMPAIGN_1 DROP CONSTRAINT CK_PADM_CAMPAIGN_STATUS;
    V_RESULT := 'dropped';
    RETURN V_RESULT;
EXCEPTION
    WHEN OTHER THEN
        V_RESULT := 'not found, skipped';
        RETURN V_RESULT;
END;
$$;

-- Migrate campaign STATUS values from the old vocabulary to the current one.
UPDATE DM_PADM_CAMPAIGN_1
SET STATUS = CASE STATUS
                WHEN 'DISCOVERED' THEN 'NEW'
                WHEN 'READY_FOR_REVIEW' THEN 'PENDING_APPROVAL'
                WHEN 'COMPLETED' THEN 'APPROVED'
                WHEN 'REOPENED' THEN 'DRAFT'
                ELSE STATUS
             END
WHERE STATUS IN ('DISCOVERED', 'READY_FOR_REVIEW', 'COMPLETED', 'REOPENED');

-- Re-add the STATUS check constraint with the current vocabulary.
ALTER TABLE DM_PADM_CAMPAIGN_1 ADD CONSTRAINT CK_PADM_CAMPAIGN_STATUS CHECK
(
    STATUS IN ('NEW', 'DRAFT', 'IN_PROGRESS', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED')
) ENABLE NOVALIDATE ;
