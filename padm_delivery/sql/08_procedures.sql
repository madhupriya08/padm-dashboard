    P_CAMPAIGN_ID VARCHAR,
    P_CALCULATION_RUN_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_LATEST_RUN VARCHAR;
    V_LATEST_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_ROW_COUNT NUMBER(38,0);
    V_EVENT_ID VARCHAR;
