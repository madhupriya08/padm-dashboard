-- Saves selection percentages for a campaign (replaces the working selection set).
CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SELECTION_SET(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_SET_ID VARCHAR;
    V_CHANGED_CELLS NUMBER(38,0);
    V_EVENT_ID VARCHAR;
