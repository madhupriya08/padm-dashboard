-- Idempotent -- safe to re-run (CREATE OR REPLACE).
USE DATABASE DB_RISK;
USE SCHEMA RISK_SBX;

-- Snapshots ACM offers into DM_PADM_CAMPAIGN_OFFER for this campaign (NEW -> DRAFT), or refreshes an already-activated campaign when new ACM data exists.
CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CAMPAIGN(P_CAMPAIGN_ID VARCHAR, P_CHANGE_REASON VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_REPORTING_MONTH DATE;
    V_CAMPAIGN_TYPE VARCHAR;
    V_SOURCE_VERSION_ID VARCHAR;
    V_LOAD_BATCH_ID VARCHAR;
    V_SOURCE_HASH VARCHAR;
    V_NEXT_SOURCE_VERSION NUMBER(10,0);
    V_CURRENT_VERSION_COUNT NUMBER DEFAULT 0;
    V_COMPONENT_COUNT NUMBER DEFAULT 0;
    V_OFFER_COUNT NUMBER DEFAULT 0;
    V_PROFILE_COUNT NUMBER DEFAULT 0;
    V_ELIGIBLE_COUNT NUMBER DEFAULT 0;
BEGIN
    SELECT MAX(STATUS), MAX(REPORTING_MONTH), MAX(CAMPAIGN_TYPE)
      INTO :V_STATUS, :V_REPORTING_MONTH, :V_CAMPAIGN_TYPE
    FROM DM_PADM_CAMPAIGN_1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS IS NULL) THEN
        RETURN 'Campaign was not found.';
    END IF;

    IF (V_STATUS NOT IN ('NEW', 'DRAFT')) THEN
        RETURN 'Only NEW or incomplete DRAFT campaigns can be activated.';
    END IF;

    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN
        RETURN 'Change Reason is required.';
    END IF;

    SELECT COUNT(*)
      INTO :V_CURRENT_VERSION_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_CURRENT_VERSION_COUNT > 0) THEN
        RETURN 'Campaign already has a current source version.';
    END IF;

    SELECT COALESCE(MAX(SOURCE_VERSION_NUMBER), 0) + 1
      INTO :V_NEXT_SOURCE_VERSION
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    V_SOURCE_VERSION_ID := UUID_STRING();
    V_LOAD_BATCH_ID := UUID_STRING();

    SELECT COUNT(*), SHA2(
                COALESCE(TO_VARCHAR(:V_REPORTING_MONTH), '') || '|' ||
                COALESCE(:V_CAMPAIGN_TYPE, '') || '|' ||
                COALESCE(TO_VARCHAR(COUNT(*)), '') || '|' ||
                COALESCE(TO_VARCHAR(MIN(SOURCE_MAIL_DATE)), '') || '|' ||
                COALESCE(TO_VARCHAR(MAX(SOURCE_MAIL_DATE)), ''),
                256
           )
      INTO :V_ELIGIBLE_COUNT, :V_SOURCE_HASH
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    -- SHA2(...) above always returns a non-null hash even when COUNT(*) = 0 (every piece going
    -- into it is COALESCE'd to '' first), so the old "IF (V_SOURCE_HASH IS NULL)" check here could
    -- never actually fire -- a month/type with zero eligible ACM offers fell all the way through
    -- to the post-insert validation at the end instead, with the far less useful "Source snapshot
    -- validation failed" message. Check the real row count directly.
    IF (V_ELIGIBLE_COUNT = 0) THEN
        RETURN 'No eligible ACM offers were found for the campaign month and type.';
    END IF;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_VERSION
    (
        CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_VERSION_NUMBER
      , SOURCE_HASH
      , SOURCE_ROW_COUNT
      , SOURCE_MIN_MAIL_DATE
      , SOURCE_MAX_MAIL_DATE
      , LOAD_BATCH_ID
      , IS_CURRENT
      , CHANGE_SUMMARY
    )
    SELECT
        :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , :V_NEXT_SOURCE_VERSION
      , :V_SOURCE_HASH
      , COUNT(*)
      , MIN(SOURCE_MAIL_DATE)
      , MAX(SOURCE_MAIL_DATE)
      , :V_LOAD_BATCH_ID
      , TRUE
      , :P_CHANGE_REASON
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    (
        CAMPAIGN_SOURCE_COMPONENT_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , SOURCE_OFFER_COUNT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , COUNT(DISTINCT OFFER_RESERVATION_CODE)
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    GROUP BY
        SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER
    (
        CAMPAIGN_OFFER_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , CAMPAIGN_SOURCE_COMPONENT_ID
      , OFFER_RESERVATION_CODE
      , PROGRAM_CODE
      , PROGRAM_VERSION_NUMBER
      , PROGRAM_MATCH_STATUS
      , MATCHED_PROGRAM_VERSION_NUMBER
      , SOURCE_CAMPAIGN_CODE
      , SOURCE_CAMPAIGN_NAME
      , SOURCE_CAMPAIGN_DESCRIPTION
      , SOURCE_MAIL_DATE
      , OFFER_DESCRIPTION
      , OFFER_SEGMENT_NAME
      , TEST_TYPE
      , SOURCE_CPP
      , PROMO_CODE
      , APPROVAL_CODE
      , UNDERWRITING_FLAG
      , PROSPECT_TYPE
      , PRINT_VENDOR_ID
      , CRS_SCORE
      , CREDIT_BUREAU_MODEL
      , CREDIT_BUREAU_SCORE
      , OFFER_STATUS
      , SOURCE_RECORD_ID
      , SOURCE_ROW_HASH
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , C.CAMPAIGN_SOURCE_COMPONENT_ID
      , S.OFFER_RESERVATION_CODE
      , S.PROGRAM_CODE
      , S.PROGRAM_VERSION_NUMBER
      , S.PROGRAM_MATCH_STATUS
      , S.MATCHED_PROGRAM_VERSION_NUMBER
      , S.SOURCE_CAMPAIGN_CODE
      , S.SOURCE_CAMPAIGN_NAME
      , S.SOURCE_CAMPAIGN_DESCRIPTION
      , S.SOURCE_MAIL_DATE
      , S.OFFER_DESCRIPTION
      , S.ACM_SEGMENT_NAME
      , S.TEST_TYPE
      , S.SOURCE_CPP
      , S.PROMO
      , S.IVR
      , S.UNDERWRITING_FLAG
      , S.PROSPECT_TYPE
      , S.PRINT_VENDOR_ID
      , S.CRS_SCORE
      , S.CREDIT_BUREAU_MODEL
      , S.CREDIT_BUREAU_SCORE
      , S.SOURCE_OFFER_STATUS
      , S.SOURCE_RECORD_ID
      , SHA2(
            COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') || '|' ||
            COALESCE(S.OFFER_RESERVATION_CODE, '') || '|' ||
            COALESCE(S.PROGRAM_CODE, '') || '|' ||
            COALESCE(TO_VARCHAR(S.PROGRAM_VERSION_NUMBER), '') || '|' ||
            COALESCE(S.OFFER_DESCRIPTION, '') || '|' ||
            COALESCE(TO_VARCHAR(S.SOURCE_CPP), ''),
            256
        )
      , TRUE
    FROM VW_PADM_ACM_OFFER_SOURCE AS S
    INNER JOIN DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS C
        ON C.CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND C.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
       AND COALESCE(C.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '')
       AND COALESCE(C.SOURCE_CAMPAIGN_GROUP_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_GROUP_CODE, '')
       AND C.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE DATE_TRUNC('MONTH', S.SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.OFFER_RESERVATION_CODE
        ORDER BY S.SOURCE_MAIL_DATE DESC, S.SOURCE_RECORD_ID DESC
    ) = 1;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER_PROFILE
    (
        CAMPAIGN_OFFER_PROFILE_ID
      , CAMPAIGN_ID
      , CAMPAIGN_OFFER_ID
      , PROFILE_VERSION_NUMBER
      , PROFILE_SOURCE_TYPE
      , ANNUAL_FEE
      , NETWORK
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , O.CAMPAIGN_ID
      , O.CAMPAIGN_OFFER_ID
      , 1
      , 'ACM_SOURCE'
      , S.ANNUAL_FEE
      , S.NETWORK
      , TRUE
    FROM DM_PADM_CAMPAIGN_OFFER AS O
    INNER JOIN VW_PADM_ACM_OFFER_SOURCE AS S
        ON O.OFFER_RESERVATION_CODE = S.OFFER_RESERVATION_CODE
       AND O.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE O.CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND O.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.CAMPAIGN_OFFER_ID
        ORDER BY S.SOURCE_RECORD_ID DESC
    ) = 1;

    UPDATE DM_PADM_CAMPAIGN_1
       SET STATUS = 'DRAFT'
         , ACTIVE_FLAG = TRUE
         , SOURCE_CHANGE_PENDING_FLAG = FALSE
         , CURRENT_SOURCE_VERSION_NUMBER = :V_NEXT_SOURCE_VERSION
         , ROW_VERSION = COALESCE(ROW_VERSION, 0) + 1
         , UPDATED_BY = CURRENT_USER()
         , UPDATED_TS = CURRENT_TIMESTAMP()
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS <> 'DRAFT') THEN
        INSERT INTO DM_PADM_WORKFLOW_EVENT
        (
            WORKFLOW_EVENT_ID
          , CAMPAIGN_ID
          , FROM_STATUS
          , TO_STATUS
          , EVENT_REASON
        )
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_STATUS, 'DRAFT', :P_CHANGE_REASON;
    END IF;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
        CHANGE_EVENT_ID
      , CAMPAIGN_ID
      , ENTITY_TYPE
      , ENTITY_ID
      , CHANGE_TYPE
      , BEFORE_VALUE
      , AFTER_VALUE
      , CHANGE_REASON
    )
    SELECT
        UUID_STRING()
      , :P_CAMPAIGN_ID
      , 'CAMPAIGN_SOURCE_VERSION'
      , :V_SOURCE_VERSION_ID
      , IFF(:V_STATUS = 'DRAFT', 'SOURCE_SNAPSHOT_REPAIRED', 'CAMPAIGN_ACTIVATED')
      , NULL
      , OBJECT_CONSTRUCT(
            'SOURCE_VERSION_NUMBER', :V_NEXT_SOURCE_VERSION,
            'REPORTING_MONTH', :V_REPORTING_MONTH,
            'CAMPAIGN_TYPE', :V_CAMPAIGN_TYPE
        )
      , :P_CHANGE_REASON;

    SELECT COUNT(*) INTO :V_COMPONENT_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_OFFER_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_PROFILE_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_COMPONENT_COUNT = 0 OR V_OFFER_COUNT = 0 OR V_PROFILE_COUNT <> V_OFFER_COUNT) THEN
        ROLLBACK;
        RETURN 'Source snapshot validation failed. No changes were committed.';
    END IF;

    COMMIT;
    RETURN 'Campaign source snapshot completed. Components: '
        || TO_VARCHAR(V_COMPONENT_COUNT)
        || ', Offers: '
        || TO_VARCHAR(V_OFFER_COUNT)
        || ', Profiles: '
        || TO_VARCHAR(V_PROFILE_COUNT)
        || '.';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

DROP PROCEDURE IF EXISTS SP_PADM_SAVE_CAMPAIGN_ASSUMPTION(VARCHAR, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, VARCHAR);
DROP PROCEDURE IF EXISTS SP_PADM_SAVE_SEGMENT_ASSUMPTION(VARCHAR, VARCHAR, NUMBER, NUMBER, NUMBER, NUMBER, NUMBER, VARCHAR);


-- Saves a new campaign-level assumption version (CPP, Unit Cost, NBR, Unwind Rate).
CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_CAMPAIGN_ASSUMPTION
(
    P_CAMPAIGN_ID VARCHAR,
    P_CPP NUMBER(18,6),
    P_UNIT_COST NUMBER(18,4),
    P_NBR NUMBER(18,8),
    P_UNWIND_RATE NUMBER(18,8),
    P_EXPECTED_VERSION NUMBER(10,0),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_CURRENT_VERSION NUMBER(10,0);
    V_NEXT_VERSION NUMBER(10,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;
    IF ((P_CPP IS NOT NULL AND P_CPP < 0) OR (P_UNIT_COST IS NOT NULL AND P_UNIT_COST < 0)
        OR (P_NBR IS NOT NULL AND P_NBR < 0) OR (P_UNWIND_RATE IS NOT NULL AND P_UNWIND_RATE < 0)) THEN
        RETURN 'ERROR: CPP, Unit Cost, NBR and Unwind Rate must be >= 0.';
    END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) INTO :V_CURRENT_VERSION
    FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (P_EXPECTED_VERSION IS NOT NULL AND V_CURRENT_VERSION <> P_EXPECTED_VERSION) THEN
        RETURN 'ERROR: Record changed by another user -- reload.';
    END IF;
    V_NEXT_VERSION := V_CURRENT_VERSION + 1;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'CAMPAIGN_ASSUMPTION', :P_CAMPAIGN_ID, 'VERSION_CREATED',
           (SELECT OBJECT_CONSTRUCT('VERSION_NUMBER', VERSION_NUMBER, 'NBR', NBR, 'UNWIND_RATE', UNWIND_RATE)
           FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE),
           OBJECT_CONSTRUCT('VERSION_NUMBER', :V_NEXT_VERSION, 'CPP', :P_CPP, 'UNIT_COST', :P_UNIT_COST,
                             'NBR', :P_NBR, 'UNWIND_RATE', :P_UNWIND_RATE),
           :P_CHANGE_REASON;

    INSERT INTO DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
        (CAMPAIGN_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, VERSION_NUMBER, CPP, UNIT_COST, NBR, UNWIND_RATE
        , RATE_ADJUSTMENT, SEASONALITY_REDUCTION, UNWIND_RATE_ADJUSTMENT
        , IS_CURRENT, CHANGE_REASON, ROW_VERSION, UPDATED_BY, UPDATED_TS)
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_NEXT_VERSION, :P_CPP, :P_UNIT_COST, :P_NBR, :P_UNWIND_RATE
         , P.RATE_ADJUSTMENT, P.SEASONALITY_REDUCTION, P.UNWIND_RATE_ADJUSTMENT
         , TRUE, :P_CHANGE_REASON, :V_NEXT_VERSION, CURRENT_USER(), CURRENT_TIMESTAMP()
    FROM (SELECT 1 AS K) AS D
    LEFT JOIN DM_PADM_CAMPAIGN_ASSUMPTION_VERSION AS P
           ON P.CAMPAIGN_ID = :P_CAMPAIGN_ID AND P.IS_CURRENT = TRUE;

    UPDATE DM_PADM_CAMPAIGN_ASSUMPTION_VERSION
       SET IS_CURRENT = (VERSION_NUMBER = :V_NEXT_VERSION)
         , EFFECTIVE_TO_TS = IFF(VERSION_NUMBER = :V_NEXT_VERSION, NULL, CURRENT_TIMESTAMP())
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND (IS_CURRENT = TRUE OR VERSION_NUMBER = :V_NEXT_VERSION);

    COMMIT;
    RETURN 'Campaign assumption version ' || :V_NEXT_VERSION || ' saved.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;


-- Saves a new segment-level assumption override version for one campaign+segment.
CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SEGMENT_ASSUMPTION
(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_CPP_OVERRIDE NUMBER(18,6),
    P_UNIT_COST_OVERRIDE NUMBER(18,4),
    P_NBR_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_OVERRIDE NUMBER(18,8),
    P_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_SEASONALITY_REDUCTION_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_EXPECTED_VERSION NUMBER(10,0),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_CURRENT_VERSION NUMBER(10,0);
    V_NEXT_VERSION NUMBER(10,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;
    IF ((P_CPP_OVERRIDE IS NOT NULL AND P_CPP_OVERRIDE < 0)
        OR (P_UNIT_COST_OVERRIDE IS NOT NULL AND P_UNIT_COST_OVERRIDE < 0)
        OR (P_NBR_OVERRIDE IS NOT NULL AND P_NBR_OVERRIDE < 0)
        OR (P_UNWIND_RATE_OVERRIDE IS NOT NULL AND P_UNWIND_RATE_OVERRIDE < 0)) THEN
        RETURN 'ERROR: CPP, Unit Cost, NBR and Unwind Rate must be >= 0.';
    END IF;
    IF (P_SEASONALITY_REDUCTION_OVERRIDE IS NOT NULL
        AND (P_SEASONALITY_REDUCTION_OVERRIDE < -1 OR P_SEASONALITY_REDUCTION_OVERRIDE > 1)) THEN
        RETURN 'ERROR: Seasonality Rate Adjustment must be between -100% and 100%.';
    END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) INTO :V_CURRENT_VERSION
    FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;
    IF (P_EXPECTED_VERSION IS NOT NULL AND V_CURRENT_VERSION <> P_EXPECTED_VERSION) THEN
        RETURN 'ERROR: Record changed by another user -- reload.';
    END IF;
    V_NEXT_VERSION := V_CURRENT_VERSION + 1;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'SEGMENT_ASSUMPTION', :P_SEGMENT_ID, 'VERSION_CREATED'
        , (SELECT OBJECT_CONSTRUCT('VERSION_NUMBER', VERSION_NUMBER, 'CPP', CPP_OVERRIDE,
                                    'UNIT_COST', UNIT_COST_OVERRIDE,
                                    'NBR', NBR_OVERRIDE, 'UNWIND_RATE', UNWIND_RATE_OVERRIDE,
                                    'RATE_ADJUSTMENT', RATE_ADJUSTMENT_OVERRIDE,
                                    'SEASONALITY_REDUCTION', SEASONALITY_REDUCTION_OVERRIDE,
                                    'UNWIND_RATE_ADJUSTMENT', UNWIND_RATE_ADJUSTMENT_OVERRIDE)
           FROM DM_PADM_SEGMENT_ASSUMPTION_VERSION
           WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE)
        , OBJECT_CONSTRUCT('VERSION_NUMBER', :V_NEXT_VERSION, 'CPP', :P_CPP_OVERRIDE,
                            'UNIT_COST', :P_UNIT_COST_OVERRIDE,
                            'NBR', :P_NBR_OVERRIDE, 'UNWIND_RATE', :P_UNWIND_RATE_OVERRIDE,
                            'RATE_ADJUSTMENT', :P_RATE_ADJUSTMENT_OVERRIDE,
                            'SEASONALITY_REDUCTION', :P_SEASONALITY_REDUCTION_OVERRIDE,
                            'UNWIND_RATE_ADJUSTMENT', :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE)
        , :P_CHANGE_REASON;

    INSERT INTO DM_PADM_SEGMENT_ASSUMPTION_VERSION
    (
        SEGMENT_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER
      , CPP_OVERRIDE, UNIT_COST_OVERRIDE, NBR_OVERRIDE, UNWIND_RATE_OVERRIDE
      , RATE_ADJUSTMENT_OVERRIDE, SEASONALITY_REDUCTION_OVERRIDE, UNWIND_RATE_ADJUSTMENT_OVERRIDE
      , IS_CURRENT, CHANGE_REASON, ROW_VERSION, UPDATED_BY, UPDATED_TS
    )
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION
         , :P_CPP_OVERRIDE, :P_UNIT_COST_OVERRIDE, :P_NBR_OVERRIDE, :P_UNWIND_RATE_OVERRIDE
         , :P_RATE_ADJUSTMENT_OVERRIDE, :P_SEASONALITY_REDUCTION_OVERRIDE, :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE
         , FALSE, :P_CHANGE_REASON, :V_NEXT_VERSION, CURRENT_USER(), CURRENT_TIMESTAMP();

    UPDATE DM_PADM_SEGMENT_ASSUMPTION_VERSION
       SET IS_CURRENT = (VERSION_NUMBER = :V_NEXT_VERSION)
         , EFFECTIVE_TO_TS = IFF(VERSION_NUMBER = :V_NEXT_VERSION, NULL, CURRENT_TIMESTAMP())
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND SEGMENT_ID = :P_SEGMENT_ID
       AND (IS_CURRENT = TRUE OR VERSION_NUMBER = :V_NEXT_VERSION);

    COMMIT;
    RETURN 'Segment assumption version ' || :V_NEXT_VERSION || ' saved.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
