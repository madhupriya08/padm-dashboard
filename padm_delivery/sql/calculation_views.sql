        , G.RESPONSE_MODEL_TIER
        , G.TIMES_MAILED_BUCKET
        , G.CDE_VOLUME
        , G.EMS_REDUCTION_RATE
        , G.SELECTION_PERCENTAGE
        , G.EFFECTIVE_CPP
        , G.EFFECTIVE_UNIT_COST
        , G.EFFECTIVE_RATE_ADJUSTMENT
        , G.EFFECTIVE_SEASONALITY_REDUCTION
        , G.EFFECTIVE_UNWIND_RATE_ADJUSTMENT
        , COALESCE(NE.BASE_NRR, NF.BASE_NRR) AS BASE_NRR
        , CASE WHEN NE.BASE_NRR IS NOT NULL THEN 'EXACT_CELL' ELSE NF.NRR_SOURCE END AS NRR_SOURCE
        , COALESCE(UE.HISTORICAL_UNWIND_RATE, UF.HISTORICAL_UNWIND_RATE) AS HISTORICAL_UNWIND_RATE
