CREATE OR REPLACE VIEW VW_PADM_NRR_CURRENT AS
WITH MAPPED AS
(
    SELECT
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
        , SUM(H.MAIL_QUANTITY) AS MAIL_QUANTITY
        , SUM(H.APPLIED_COUNT) AS APPLIED_COUNT
        , SUM(H.BOARDED_COUNT) AS BOARDED_COUNT
    FROM DM_PADM_NRR_HISTORY_CELL AS H
    INNER JOIN DM_PADM_HISTORY_SEGMENT_MAP AS M
            ON H.HISTORY_SEGMENT_KEY_ID = M.HISTORY_SEGMENT_KEY_ID
           AND M.ACTIVE_FLAG = TRUE
           AND COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) >= M.VALID_FROM
           AND
           (
                M.VALID_TO IS NULL
             OR COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) < M.VALID_TO
           )
    GROUP BY
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
),
SEGMENT_FALLBACK AS
(
    SELECT
          SEGMENT_ID
        , CAMPAIGN_TYPE
        , SUM(MAIL_QUANTITY) AS MAIL_QUANTITY
        , SUM(BOARDED_COUNT) AS BOARDED_COUNT
    FROM MAPPED
    GROUP BY
          SEGMENT_ID
        , CAMPAIGN_TYPE
)
SELECT
      M.SEGMENT_ID
    , M.CAMPAIGN_TYPE
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.MAIL_QUANTITY
    , M.APPLIED_COUNT
    , M.BOARDED_COUNT
    , M.BOARDED_COUNT / NULLIF(M.MAIL_QUANTITY, 0) AS BASE_NRR
    , 'EXACT_CELL' AS NRR_SOURCE
FROM MAPPED AS M

UNION ALL

SELECT
      F.SEGMENT_ID
    , F.CAMPAIGN_TYPE
    , NULL::NUMBER AS RESPONSE_MODEL_TIER
    , NULL::VARCHAR AS TIMES_MAILED_BUCKET
    , F.MAIL_QUANTITY
    , NULL::NUMBER AS APPLIED_COUNT
    , F.BOARDED_COUNT
    , F.BOARDED_COUNT / NULLIF(F.MAIL_QUANTITY, 0) AS BASE_NRR
    , 'SEGMENT_FALLBACK' AS NRR_SOURCE
FROM SEGMENT_FALLBACK AS F;

CREATE OR REPLACE VIEW VW_PADM_UNWIND_CURRENT AS
WITH MAPPED AS
(
    SELECT
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
        , SUM(H.BOARD_COUNT) AS BOARD_COUNT
        , SUM(H.UNWIND_COUNT) AS UNWIND_COUNT
    FROM DM_PADM_UNWIND_HISTORY_CELL AS H
    INNER JOIN DM_PADM_HISTORY_SEGMENT_MAP AS M
            ON H.HISTORY_SEGMENT_KEY_ID = M.HISTORY_SEGMENT_KEY_ID
           AND M.ACTIVE_FLAG = TRUE
           AND COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) >= M.VALID_FROM
           AND
           (
                M.VALID_TO IS NULL
             OR COALESCE(H.OBSERVATION_CAMPAIGN_DATE, CURRENT_DATE()) < M.VALID_TO
           )
    GROUP BY
          M.SEGMENT_ID
        , H.CAMPAIGN_TYPE
        , H.RESPONSE_MODEL_TIER
        , H.TIMES_MAILED_BUCKET
),
SEGMENT_FALLBACK AS
(
    SELECT
          SEGMENT_ID
        , CAMPAIGN_TYPE
        , SUM(BOARD_COUNT) AS BOARD_COUNT
        , SUM(UNWIND_COUNT) AS UNWIND_COUNT
    FROM MAPPED
    GROUP BY
          SEGMENT_ID
        , CAMPAIGN_TYPE
)
SELECT
      M.SEGMENT_ID
    , M.CAMPAIGN_TYPE
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.BOARD_COUNT
    , M.UNWIND_COUNT
    , M.UNWIND_COUNT / NULLIF(M.BOARD_COUNT, 0) AS HISTORICAL_UNWIND_RATE
    , 'EXACT_CELL' AS UNWIND_SOURCE
FROM MAPPED AS M

UNION ALL

SELECT
      F.SEGMENT_ID
    , F.CAMPAIGN_TYPE
    , NULL::NUMBER AS RESPONSE_MODEL_TIER
    , NULL::VARCHAR AS TIMES_MAILED_BUCKET
    , F.BOARD_COUNT
    , F.UNWIND_COUNT
    , F.UNWIND_COUNT / NULLIF(F.BOARD_COUNT, 0) AS HISTORICAL_UNWIND_RATE
    , 'SEGMENT_FALLBACK' AS UNWIND_SOURCE
FROM SEGMENT_FALLBACK AS F;

