    LEFT JOIN DM_PADM_SEGMENT_ASSUMPTION_VERSION AS P
           ON P.CAMPAIGN_ID = :P_CAMPAIGN_ID AND P.SEGMENT_ID = :P_SEGMENT_ID AND P.IS_CURRENT = TRUE;

