       AND SEGMENT_ID = :P_SEGMENT_ID
       AND (IS_CURRENT = TRUE OR VERSION_NUMBER = :V_NEXT_VERSION);

    COMMIT;
    RETURN 'Segment assumption version ' || :V_NEXT_VERSION || ' saved.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_SAVE_SELECTION_SET(
    P_CAMPAIGN_ID VARCHAR,
    P_SEGMENT_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_SET_ID VARCHAR;
    V_CHANGED_CELLS NUMBER(38,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;

    SELECT COUNT(*) INTO :V_CHANGED_CELLS
    FROM DM_PADM_SELECTION_WORKING
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_DIRTY = TRUE;
    IF (V_CHANGED_CELLS = 0) THEN RETURN 'ERROR: No unsaved selection changes for this segment.'; END IF;

    SELECT COALESCE(MAX(VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_SELECTION_SET WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;
    V_SET_ID := UUID_STRING();

    BEGIN TRANSACTION;

    UPDATE DM_PADM_SELECTION_SET SET IS_CURRENT = FALSE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE;

    INSERT INTO DM_PADM_SELECTION_SET
        (SELECTION_SET_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER, STATUS, IS_CURRENT, IS_FINAL, CHANGE_REASON)
    VALUES (:V_SET_ID, :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION, 'SAVED', TRUE, FALSE, :P_CHANGE_REASON);

    INSERT INTO DM_PADM_SELECTION_SET_CELL (SELECTION_SET_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET, SELECTION_PERCENTAGE)
    SELECT :V_SET_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET, SELECTION_PERCENTAGE
    FROM DM_PADM_SELECTION_WORKING WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    UPDATE DM_PADM_SELECTION_EVENT SET SELECTION_SET_ID = :V_SET_ID
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND SELECTION_SET_ID IS NULL;

    INSERT INTO DM_PADM_SELECTION_EVENT
        (SELECTION_EVENT_ID, CAMPAIGN_ID, SEGMENT_ID, SELECTION_SET_ID, ACTION_TYPE, CHANGED_CELL_COUNT, CHANGE_REASON)
    VALUES (UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_SET_ID, 'SAVE', :V_CHANGED_CELLS, :P_CHANGE_REASON);

    UPDATE DM_PADM_SELECTION_WORKING
       SET IS_DIRTY = FALSE, ROW_VERSION = ROW_VERSION + 1
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID;

    COMMIT;
    RETURN 'Selection set version ' || :V_NEXT_VERSION || ' saved (' || :V_CHANGED_CELLS || ' cells).';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CDE_VERSION
(
    P_CDE_LOAD_BATCH_ID VARCHAR,
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_CAMPAIGN_ID VARCHAR;
    V_SEGMENT_ID VARCHAR;
    V_VALIDATION_STATUS VARCHAR;
    V_STATUS VARCHAR;
BEGIN
    SELECT MAX(CAMPAIGN_ID), MAX(SEGMENT_ID), MAX(VALIDATION_STATUS)
      INTO :V_CAMPAIGN_ID, :V_SEGMENT_ID, :V_VALIDATION_STATUS
    FROM DM_PADM_CDE_LOAD_BATCH WHERE CDE_LOAD_BATCH_ID = :P_CDE_LOAD_BATCH_ID;

    IF (V_CAMPAIGN_ID IS NULL OR V_SEGMENT_ID IS NULL) THEN RETURN 'ERROR: CDE load batch was not found.'; END IF;
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :V_CAMPAIGN_ID;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (V_VALIDATION_STATUS <> 'VALID') THEN RETURN 'ERROR: Only a validated CDE version can be activated.'; END IF;
    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
    SELECT UUID_STRING(), :V_CAMPAIGN_ID, 'CDE_LOAD_BATCH', :P_CDE_LOAD_BATCH_ID, 'VERSION_ACTIVATED',
           (SELECT OBJECT_CONSTRUCT('CDE_LOAD_BATCH_ID', MAX(CDE_LOAD_BATCH_ID), 'VERSION_NUMBER', MAX(VERSION_NUMBER))
              FROM DM_PADM_CDE_LOAD_BATCH WHERE CAMPAIGN_ID = :V_CAMPAIGN_ID AND SEGMENT_ID = :V_SEGMENT_ID AND ACTIVE_FLAG = TRUE),
           OBJECT_CONSTRUCT('SEGMENT_ID', :V_SEGMENT_ID, 'CDE_LOAD_BATCH_ID', :P_CDE_LOAD_BATCH_ID),
           :P_CHANGE_REASON;

    UPDATE DM_PADM_CDE_LOAD_BATCH SET ACTIVE_FLAG = FALSE
    WHERE CAMPAIGN_ID = :V_CAMPAIGN_ID AND SEGMENT_ID = :V_SEGMENT_ID AND ACTIVE_FLAG = TRUE;

    UPDATE DM_PADM_CDE_LOAD_BATCH
       SET ACTIVE_FLAG = TRUE, ACTIVATED_BY = CURRENT_USER(), ACTIVATED_TS = CURRENT_TIMESTAMP()
     WHERE CDE_LOAD_BATCH_ID = :P_CDE_LOAD_BATCH_ID;

    COMMIT;
    RETURN 'CDE version activated.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_TRANSITION_CAMPAIGN_STATUS
(
    P_CAMPAIGN_ID VARCHAR,
    P_TO_STATUS VARCHAR,
    P_REASON VARCHAR,
    P_COMMENT VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_FROM VARCHAR;
    V_TO VARCHAR;
    V_VERSION NUMBER(10,0);
    V_SNAPSHOT_VERSION NUMBER(10,0);
BEGIN
    V_TO := UPPER(TRIM(P_TO_STATUS));
    SELECT MAX(STATUS), MAX(CURRENT_WORKING_VERSION_NUMBER) INTO :V_FROM, :V_VERSION
    FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_FROM IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_FROM = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (NULLIF(TRIM(P_REASON), '') IS NULL) THEN RETURN 'ERROR: Change Reason is required.'; END IF;
    IF (NOT (
            (V_FROM IN ('DRAFT', 'IN_PROGRESS') AND V_TO = 'IN_PROGRESS')
         OR (V_FROM = 'PENDING_APPROVAL' AND V_TO IN ('APPROVED', 'REJECTED'))
        )) THEN
        RETURN 'ERROR: Transition ' || V_FROM || ' -> ' || V_TO || ' is not allowed.';
    END IF;

    BEGIN TRANSACTION;

    IF (V_TO = 'IN_PROGRESS') THEN
        UPDATE DM_PADM_CAMPAIGN_1
           SET STATUS = 'IN_PROGRESS'
             , CURRENT_WORKING_VERSION_NUMBER = CURRENT_WORKING_VERSION_NUMBER + IFF(:V_FROM = 'IN_PROGRESS', 1, 0)
             , ROW_VERSION = ROW_VERSION + 1, UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
        INSERT INTO DM_PADM_WORKFLOW_EVENT (WORKFLOW_EVENT_ID, CAMPAIGN_ID, FROM_STATUS, TO_STATUS, EVENT_REASON, EVENT_COMMENT)
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_FROM, 'IN_PROGRESS', :P_REASON,
               COALESCE(:P_COMMENT || ' ', '') || '(working version v' || CURRENT_WORKING_VERSION_NUMBER || ')'
        FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    ELSEIF (V_TO = 'APPROVED') THEN
        SELECT MAX(SIGNATURE_VERSION_NUMBER) INTO :V_SNAPSHOT_VERSION
        FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
        IF (V_SNAPSHOT_VERSION IS NULL) THEN
            ROLLBACK;
            RETURN 'ERROR: Generate Signature Page 2 before approving.';
        END IF;
        UPDATE DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT SET SNAPSHOT_STATUS = 'APPROVED'
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SIGNATURE_VERSION_NUMBER = :V_SNAPSHOT_VERSION;
        UPDATE DM_PADM_SELECTION_SET SET IS_FINAL = TRUE, STATUS = 'APPROVED'
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE;
        UPDATE DM_PADM_CAMPAIGN_1
           SET STATUS = 'APPROVED', ROW_VERSION = ROW_VERSION + 1,
               UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
        INSERT INTO DM_PADM_WORKFLOW_EVENT (WORKFLOW_EVENT_ID, CAMPAIGN_ID, FROM_STATUS, TO_STATUS, EVENT_REASON, EVENT_COMMENT)
        VALUES (UUID_STRING(), :P_CAMPAIGN_ID, :V_FROM, 'APPROVED', :P_REASON, :P_COMMENT);
        INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'SIGNATURE_PAGE_2', :P_CAMPAIGN_ID, 'APPROVED',
               OBJECT_CONSTRUCT('STATUS', :V_FROM),
               OBJECT_CONSTRUCT('STATUS', 'APPROVED', 'SIGNATURE_VERSION_NUMBER', :V_SNAPSHOT_VERSION, 'WORKING_VERSION_NUMBER', :V_VERSION),
               :P_REASON;

    ELSE
        UPDATE DM_PADM_CAMPAIGN_1
           SET STATUS = 'DRAFT', ROW_VERSION = ROW_VERSION + 1,
               UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
        UPDATE DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT SET SNAPSHOT_STATUS = 'REJECTED'
         WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
           AND SIGNATURE_VERSION_NUMBER = (SELECT MAX(SIGNATURE_VERSION_NUMBER) FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID);
        INSERT INTO DM_PADM_WORKFLOW_EVENT (WORKFLOW_EVENT_ID, CAMPAIGN_ID, FROM_STATUS, TO_STATUS, EVENT_REASON, EVENT_COMMENT)
        VALUES (UUID_STRING(), :P_CAMPAIGN_ID, :V_FROM, 'REJECTED', :P_REASON, :P_COMMENT);
        INSERT INTO DM_PADM_WORKFLOW_EVENT (WORKFLOW_EVENT_ID, CAMPAIGN_ID, FROM_STATUS, TO_STATUS, EVENT_REASON, EVENT_COMMENT)
        VALUES (UUID_STRING(), :P_CAMPAIGN_ID, 'REJECTED', 'DRAFT', :P_REASON, 'Returned to draft after rejection');
    END IF;

    COMMIT;
    RETURN 'Campaign moved to ' || IFF(:V_TO = 'REJECTED', 'DRAFT (rejected)', :V_TO) || '.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_RUN_CALCULATION(P_CAMPAIGN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_RUN_ID VARCHAR;
    V_WORKING_VERSION NUMBER(10,0);
    V_ASSUMPTION_VERSION_ID VARCHAR;
    V_CELL_COUNT NUMBER(38,0);
    V_MISSING_CPP NUMBER(38,0);
    V_MISSING_NRR NUMBER(38,0);
BEGIN
    SELECT MAX(STATUS), MAX(CURRENT_WORKING_VERSION_NUMBER) INTO :V_STATUS, :V_WORKING_VERSION
    FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;

    SELECT COUNT(*), COUNT_IF(EFFECTIVE_CPP IS NULL), COUNT_IF(BASE_NRR IS NULL)
      INTO :V_CELL_COUNT, :V_MISSING_CPP, :V_MISSING_NRR
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_CELL_COUNT = 0) THEN RETURN 'ERROR: No CDE volume is active for any segment of this campaign.'; END IF;
    IF (V_MISSING_CPP > 0) THEN RETURN 'ERROR: Save CPP (Campaign Assumptions) before calculating Marketing Cost and CPA.'; END IF;
    IF (V_MISSING_NRR > 0) THEN RETURN 'ERROR: ' || V_MISSING_NRR || ' cell(s) have no NRR (no history and no NBR assumption). Save NBR first.'; END IF;

    SELECT MAX(CAMPAIGN_ASSUMPTION_VERSION_ID) INTO :V_ASSUMPTION_VERSION_ID
    FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE;
    V_RUN_ID := UUID_STRING();

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CALCULATION_RUN
        (CALCULATION_RUN_ID, CAMPAIGN_ID, CAMPAIGN_WORKING_VERSION_NUMBER, CAMPAIGN_ASSUMPTION_VERSION_ID,
         CALCULATION_STATUS, SOURCE_DATA_AS_OF_TS)
    VALUES (:V_RUN_ID, :P_CAMPAIGN_ID, :V_WORKING_VERSION, :V_ASSUMPTION_VERSION_ID, 'STARTED', CURRENT_TIMESTAMP());

    INSERT INTO DM_PADM_CALCULATION_CELL
    (
        CALCULATION_CELL_ID, CALCULATION_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED, BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED, POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    )
    SELECT
        UUID_STRING(), :V_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED, BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED, POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    UPDATE DM_PADM_CALCULATION_RUN
       SET CALCULATION_STATUS = 'COMPLETED', CALCULATION_COMPLETED_TS = CURRENT_TIMESTAMP()
     WHERE CALCULATION_RUN_ID = :V_RUN_ID;

    COMMIT;
    RETURN :V_RUN_ID || '|' || :V_CELL_COUNT;
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_GENERATE_SIGNATURE_PAGE_2(
    P_CAMPAIGN_ID VARCHAR,
    P_CALCULATION_RUN_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_LATEST_RUN VARCHAR;
    V_LATEST_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_ROW_COUNT NUMBER(38,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (V_STATUS NOT IN ('DRAFT', 'IN_PROGRESS', 'PENDING_APPROVAL')) THEN
        RETURN 'ERROR: Signature Page 2 can only be generated for DRAFT / IN_PROGRESS campaigns.';
    END IF;

    SELECT MAX_BY(CALCULATION_RUN_ID, CALCULATION_STARTED_TS), MAX_BY(CALCULATION_STATUS, CALCULATION_STARTED_TS)
      INTO :V_LATEST_RUN, :V_LATEST_STATUS
