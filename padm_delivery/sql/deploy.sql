           WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SEGMENT_ID = :P_SEGMENT_ID AND IS_CURRENT = TRUE)
        , OBJECT_CONSTRUCT('VERSION_NUMBER', :V_NEXT_VERSION, 'UNIT_COST', :P_UNIT_COST_OVERRIDE,
                            'NBR', :P_NBR_OVERRIDE, 'UNWIND_RATE', :P_UNWIND_RATE_OVERRIDE,
                            'RATE_ADJUSTMENT', :P_RATE_ADJUSTMENT_OVERRIDE,
                            'SEASONALITY_REDUCTION', :P_SEASONALITY_REDUCTION_OVERRIDE,
                            'UNWIND_RATE_ADJUSTMENT', :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE)
        , :P_CHANGE_REASON;

    INSERT INTO DM_PADM_SEGMENT_ASSUMPTION_VERSION
    (
        SEGMENT_ASSUMPTION_VERSION_ID, CAMPAIGN_ID, SEGMENT_ID, VERSION_NUMBER
      , CPP_OVERRIDE, UNIT_COST_OVERRIDE, NBR_OVERRIDE, UNWIND_RATE_OVERRIDE
      , RATE_ADJUSTMENT_OVERRIDE, SEASONALITY_REDUCTION_OVERRIDE, UNWIND_RATE_ADJUSTMENT_OVERRIDE
      , IS_CURRENT, CHANGE_REASON, ROW_VERSION, UPDATED_BY, UPDATED_TS
