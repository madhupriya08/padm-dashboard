(
    SELECT O.*, P.NETWORK AS PROGRAM_NETWORK,
           CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1), '/', TO_VARCHAR(P.ANNUAL_FEE_YR2)) AS PROGRAM_ANNUAL_FEE
