CREATE OR REPLACE VIEW VW_PADM_EFFECTIVE_ASSUMPTION AS
SELECT
      CS.CAMPAIGN_ID
    , CS.SEGMENT_ID
    , COALESCE(SA.CPP_OVERRIDE, CA.CPP) AS EFFECTIVE_CPP
    , COALESCE(SA.UNIT_COST_OVERRIDE, CA.UNIT_COST) AS EFFECTIVE_UNIT_COST
    , COALESCE(SA.NBR_OVERRIDE, CA.NBR) AS EFFECTIVE_NBR
    , COALESCE(SA.UNWIND_RATE_OVERRIDE, CA.UNWIND_RATE) AS EFFECTIVE_UNWIND_RATE
    , COALESCE(SA.RATE_ADJUSTMENT_OVERRIDE, 0) AS EFFECTIVE_RATE_ADJUSTMENT
    , COALESCE(SA.SEASONALITY_REDUCTION_OVERRIDE, 0) AS EFFECTIVE_SEASONALITY_REDUCTION
    , COALESCE(SA.UNWIND_RATE_ADJUSTMENT_OVERRIDE, 0) AS EFFECTIVE_UNWIND_RATE_ADJUSTMENT
FROM DM_PADM_CAMPAIGN_SEGMENT_1 AS CS
LEFT JOIN VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS CA
       ON CS.CAMPAIGN_ID = CA.CAMPAIGN_ID
LEFT JOIN VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS SA
       ON CS.CAMPAIGN_ID = SA.CAMPAIGN_ID
      AND CS.SEGMENT_ID = SA.SEGMENT_ID
WHERE CS.IS_CURRENT = TRUE;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_CALCULATION_CURRENT AS
WITH GRID AS
(
    SELECT
          C.CAMPAIGN_ID
        , C.CAMPAIGN_TYPE
        , G.SEGMENT_ID
        , G.RESPONSE_MODEL_TIER
        , G.TIMES_MAILED_BUCKET
        , G.CDE_VOLUME
        , COALESCE(E1.EMS_REDUCTION_RATE, E2.EMS_REDUCTION_RATE, E3.EMS_REDUCTION_RATE, 0.05) AS EMS_REDUCTION_RATE
        , CASE
              WHEN E1.EMS_REDUCTION_RATE IS NOT NULL THEN 'EXACT_CELL'
              WHEN E2.EMS_REDUCTION_RATE IS NOT NULL THEN 'SEGMENT_FALLBACK'
              WHEN E3.EMS_REDUCTION_RATE IS NOT NULL THEN 'CAMPAIGN_DEFAULT'
              ELSE 'POC_BLANKET_5_PCT'
          END AS EMS_SOURCE
        , S.SELECTION_PERCENTAGE
        , A.EFFECTIVE_CPP
        , A.EFFECTIVE_UNIT_COST
        , A.EFFECTIVE_NBR AS ASSUMED_NBR
        , A.EFFECTIVE_UNWIND_RATE AS ASSUMED_UNWIND_RATE
        , A.EFFECTIVE_RATE_ADJUSTMENT
        , A.EFFECTIVE_SEASONALITY_REDUCTION
        , A.EFFECTIVE_UNWIND_RATE_ADJUSTMENT
    FROM VW_PADM_CDE_GRID_CURRENT AS G
    INNER JOIN DM_PADM_CAMPAIGN_1 AS C
            ON G.CAMPAIGN_ID = C.CAMPAIGN_ID
    LEFT JOIN VW_PADM_SELECTION_CURRENT AS S
           ON G.CAMPAIGN_ID = S.CAMPAIGN_ID
          AND G.SEGMENT_ID = S.SEGMENT_ID
          AND G.RESPONSE_MODEL_TIER = S.RESPONSE_MODEL_TIER
          AND G.TIMES_MAILED_BUCKET = S.TIMES_MAILED_BUCKET
    LEFT JOIN VW_PADM_EFFECTIVE_ASSUMPTION AS A
           ON G.CAMPAIGN_ID = A.CAMPAIGN_ID
          AND G.SEGMENT_ID = A.SEGMENT_ID
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E1
           ON G.CAMPAIGN_ID = E1.CAMPAIGN_ID
          AND G.SEGMENT_ID = E1.SEGMENT_ID
          AND G.RESPONSE_MODEL_TIER = E1.RESPONSE_MODEL_TIER
          AND G.TIMES_MAILED_BUCKET = E1.TIMES_MAILED_BUCKET
          AND E1.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E2
           ON G.CAMPAIGN_ID = E2.CAMPAIGN_ID
          AND G.SEGMENT_ID = E2.SEGMENT_ID
          AND E2.RESPONSE_MODEL_TIER IS NULL
          AND E2.TIMES_MAILED_BUCKET IS NULL
          AND E2.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_EMS_RATE_VERSION AS E3
           ON G.CAMPAIGN_ID = E3.CAMPAIGN_ID
          AND E3.SEGMENT_ID IS NULL
          AND E3.RESPONSE_MODEL_TIER IS NULL
          AND E3.TIMES_MAILED_BUCKET IS NULL
          AND E3.IS_CURRENT = TRUE
),
HISTORY AS
(
    SELECT
          G.*
        , COALESCE(NE.BASE_NRR, NF.BASE_NRR, G.ASSUMED_NBR) AS BASE_NRR
        , CASE
              WHEN NE.BASE_NRR IS NOT NULL THEN 'EXACT_CELL'
              WHEN NF.BASE_NRR IS NOT NULL THEN 'SEGMENT_FALLBACK'
              WHEN G.ASSUMED_NBR IS NOT NULL THEN 'CAMPAIGN_DEFAULT'
          END AS NRR_SOURCE
        , COALESCE(UE.HISTORICAL_UNWIND_RATE, UF.HISTORICAL_UNWIND_RATE, G.ASSUMED_UNWIND_RATE) AS HISTORICAL_UNWIND_RATE
        , CASE
              WHEN UE.HISTORICAL_UNWIND_RATE IS NOT NULL THEN 'EXACT_CELL'
              WHEN UF.HISTORICAL_UNWIND_RATE IS NOT NULL THEN 'SEGMENT_FALLBACK'
              WHEN G.ASSUMED_UNWIND_RATE IS NOT NULL THEN 'CAMPAIGN_DEFAULT'
          END AS UNWIND_SOURCE
    FROM GRID AS G
    LEFT JOIN VW_PADM_NRR_CURRENT AS NE
           ON G.SEGMENT_ID = NE.SEGMENT_ID
          AND G.CAMPAIGN_TYPE = NE.CAMPAIGN_TYPE
          AND G.RESPONSE_MODEL_TIER = NE.RESPONSE_MODEL_TIER
          AND G.TIMES_MAILED_BUCKET = NE.TIMES_MAILED_BUCKET
          AND NE.NRR_SOURCE = 'EXACT_CELL'
    LEFT JOIN VW_PADM_NRR_CURRENT AS NF
           ON G.SEGMENT_ID = NF.SEGMENT_ID
          AND G.CAMPAIGN_TYPE = NF.CAMPAIGN_TYPE
          AND NF.NRR_SOURCE = 'SEGMENT_FALLBACK'
    LEFT JOIN VW_PADM_UNWIND_CURRENT AS UE
           ON G.SEGMENT_ID = UE.SEGMENT_ID
          AND G.CAMPAIGN_TYPE = UE.CAMPAIGN_TYPE
          AND G.RESPONSE_MODEL_TIER = UE.RESPONSE_MODEL_TIER
          AND G.TIMES_MAILED_BUCKET = UE.TIMES_MAILED_BUCKET
          AND UE.UNWIND_SOURCE = 'EXACT_CELL'
    LEFT JOIN VW_PADM_UNWIND_CURRENT AS UF
           ON G.SEGMENT_ID = UF.SEGMENT_ID
          AND G.CAMPAIGN_TYPE = UF.CAMPAIGN_TYPE
          AND UF.UNWIND_SOURCE = 'SEGMENT_FALLBACK'
),
MEASURES AS
(
    SELECT
          H.*
        , H.CDE_VOLUME * (1 - H.EMS_REDUCTION_RATE) AS POST_EMS_VOLUME
        , ROUND(H.CDE_VOLUME * (1 - H.EMS_REDUCTION_RATE) * COALESCE(H.SELECTION_PERCENTAGE, 0), 0) AS SELECTED_QUANTITY
        , H.BASE_NRR
          * (1 + COALESCE(H.EFFECTIVE_RATE_ADJUSTMENT, 0))
          * (1 - COALESCE(H.EFFECTIVE_SEASONALITY_REDUCTION, 0)) AS EFFECTIVE_NRR
        , H.HISTORICAL_UNWIND_RATE * (1 + COALESCE(H.EFFECTIVE_UNWIND_RATE_ADJUSTMENT, 0)) AS EFFECTIVE_UNWIND_RATE
    FROM HISTORY AS H
)
SELECT
      M.CAMPAIGN_ID
    , M.CAMPAIGN_TYPE
    , M.SEGMENT_ID
    , M.RESPONSE_MODEL_TIER
    , M.TIMES_MAILED_BUCKET
    , M.CDE_VOLUME
    , M.EMS_REDUCTION_RATE
    , M.POST_EMS_VOLUME
    , COALESCE(M.SELECTION_PERCENTAGE, 0) AS SELECTION_PERCENTAGE
    , M.SELECTED_QUANTITY
    , M.BASE_NRR
    , M.EFFECTIVE_RATE_ADJUSTMENT
    , M.EFFECTIVE_SEASONALITY_REDUCTION
    , M.EFFECTIVE_NRR
    , IFF(M.SELECTED_QUANTITY > 0, M.EFFECTIVE_NRR, NULL) AS SELECTED_NRR
    , M.HISTORICAL_UNWIND_RATE
    , M.EFFECTIVE_UNWIND_RATE_ADJUSTMENT
    , M.EFFECTIVE_UNWIND_RATE
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR AS BOOKED_PRE_UNWIND_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR AS BOOKED_PRE_UNWIND_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_CPP AS MARKETING_COST_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_CPP AS MARKETING_COST_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST AS BOOKING_COST_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST AS BOOKING_COST_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNWIND_RATE AS EXPECTED_UNWINDS_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNWIND_RATE AS EXPECTED_UNWINDS_SELECTED
    , M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE) AS BOOKED_POST_UNWIND_UNIVERSE
    , M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE) AS BOOKED_POST_UNWIND_SELECTED
    , (M.POST_EMS_VOLUME * M.EFFECTIVE_CPP) / NULLIF(M.POST_EMS_VOLUME * M.EFFECTIVE_NRR, 0) AS PRE_UNWIND_CPA_UNIVERSE
    , (M.SELECTED_QUANTITY * M.EFFECTIVE_CPP) / NULLIF(M.SELECTED_QUANTITY * M.EFFECTIVE_NRR, 0) AS PRE_UNWIND_CPA_SELECTED
    , ((M.POST_EMS_VOLUME * M.EFFECTIVE_CPP) + (M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST))
      / NULLIF(M.POST_EMS_VOLUME * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE), 0) AS POST_UNWIND_CPA_UNIVERSE
    , ((M.SELECTED_QUANTITY * M.EFFECTIVE_CPP) + (M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * M.EFFECTIVE_UNIT_COST))
      / NULLIF(M.SELECTED_QUANTITY * M.EFFECTIVE_NRR * (1 - M.EFFECTIVE_UNWIND_RATE), 0) AS POST_UNWIND_CPA_SELECTED
    , M.EFFECTIVE_CPP
    , M.EFFECTIVE_UNIT_COST
    , M.NRR_SOURCE
    , M.UNWIND_SOURCE
    , M.EMS_SOURCE
FROM MEASURES AS M;

CREATE OR REPLACE VIEW VW_PADM_SIGNATURE_PAGE_ALL AS
WITH SEGMENT_GROUP AS
(
    SELECT
          S.SEGMENT_ID
        , R.POPULATION_GROUP_LABEL
    FROM DM_PADM_SEGMENT_1 AS S
    INNER JOIN DM_PADM_POPULATION_GROUP_RULE AS R
            ON UPPER(R.SOURCE_NAME) = UPPER(S.SOURCE_NAME)
           AND (R.SCORE_TYPE IS NULL OR UPPER(R.SCORE_TYPE) = UPPER(S.SCORE_TYPE))
           AND (R.SCORE_MIN IS NULL OR S.SCORE_MIN >= R.SCORE_MIN)
           AND (R.SCORE_MAX IS NULL OR S.SCORE_MAX <= R.SCORE_MAX)
           AND (R.PROSPECT_SEGMENT_TYPE IS NULL OR UPPER(R.PROSPECT_SEGMENT_TYPE) = UPPER(S.PROSPECT_SEGMENT_TYPE))
           AND R.ACTIVE_FLAG = TRUE
           AND CURRENT_DATE() >= R.VALID_FROM
           AND (R.VALID_TO IS NULL OR CURRENT_DATE() < R.VALID_TO)
    QUALIFY ROW_NUMBER() OVER (PARTITION BY S.SEGMENT_ID ORDER BY R.DISPLAY_SEQUENCE NULLS LAST, R.POPULATION_GROUP_CODE) = 1
),
BASE AS
(
    SELECT
          O.CAMPAIGN_ID
        , O.CAMPAIGN_OFFER_ID
        , O.OFFER_RESERVATION_CODE
        , A.OFFER_SEGMENT_ALLOCATION_ID
        , A.SEGMENT_ID
        , S.SEGMENT_NAME
        , S.SCORE_TYPE
        , S.SCORE_MIN
        , S.SCORE_MAX
        , S.SOURCE_NAME
        , COALESCE(A.POPULATION_DESCRIPTION, SG.POPULATION_GROUP_LABEL) AS POPULATION_DESCRIPTION
        , COALESCE(ACM.CAMPAIGN_OFFER_DESCRIPTION, O.OFFER_DESCRIPTION) AS SEGMENT_DESCRIPTION
        , CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1), '/', TO_VARCHAR(P.ANNUAL_FEE_YR2)) AS ANNUAL_FEE
        , COALESCE(ACM.CAMPAIGN_OFFER_CONTROL_TEST_DESCRIPTION, O.TEST_TYPE) AS TEST_TYPE
        , P.NETWORK
        , COALESCE(ACM.PROSPECT_CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_MODEL) AS CREDIT_BUREAU_MODEL
        , COALESCE(ACM.PROSPECT_CREDIT_BUREAU_SCORE, O.CREDIT_BUREAU_SCORE) AS CREDIT_BUREAU_SCORE
        , ACM.PROSPECT_CRS_MODEL AS CRS_MODEL
        , COALESCE(ACM.PROSPECT_CRS_SCORE, O.CRS_SCORE) AS CRS_SCORE
        , ACM.NET_RESPONSE_MODEL_CODE AS NRM
        , COALESCE(ACM.COST_PER_PIECE::NUMBER(18,6), O.SOURCE_CPP) AS ACM_CPP
        , COALESCE(ACM.RESERVATION_CODE_RISK, O.PROMO_CODE) AS PROMO
        , COALESCE(ACM.CAMPAIGN_OFFER_APPROVAL_CODE, O.APPROVAL_CODE) AS IVR
        , NULL::VARCHAR AS UNDERWRITING_FLAG
        , COALESCE(PT.PROSPECT_TYPE, PTD.PROSPECT_TYPE) AS PROSPECT_TYPE
        , COALESCE(ACM.PRINT_VENDOR_ID, O.PRINT_VENDOR_ID) AS PRINT_VENDOR

        , YEAR(ACM.CAMPAIGN_GROUP_MAIL_DATE) AS CAMPAIGN_YEAR
        , MONTH(ACM.CAMPAIGN_GROUP_MAIL_DATE) AS CAMPAIGN_MONTH
        , C.CAMPAIGN_SEQUENCE AS CAMPAIGN_MONTH_SEQUENCE
        , C.CAMPAIGN_TYPE
        , COALESCE(ACM.CAMPAIGN_GROUP_MAIL_DATE::DATE, O.SOURCE_MAIL_DATE) AS MAIL_DATE
        , COALESCE(ACM.CAMPAIGN_OFFER_SEGMENT_NAME, O.OFFER_SEGMENT_NAME) AS ACM_SEGMENT
        , ACM.CAMPAIGN_OFFER_CONTROL_TEST_NAME AS TEST_PAIRINGS

        , COALESCE(PR.ACTUAL_MAIL_QUANTITY, PR.REPORT_105_VOLUME, PR.MKU_VOLUME) AS BASE_QUANTITY
        , PR.TIMES_MAILED_0_COUNT, PR.TIMES_MAILED_1_COUNT, PR.TIMES_MAILED_2_COUNT, PR.TIMES_MAILED_3_COUNT
        , PR.TIMES_MAILED_4_COUNT, PR.TIMES_MAILED_5_COUNT, PR.TIMES_MAILED_6_COUNT, PR.TIMES_MAILED_7_COUNT
        , PR.TIMES_MAILED_8_COUNT, PR.TIMES_MAILED_9_PLUS_COUNT
        , NULLIF(
              COALESCE(PR.TIMES_MAILED_0_COUNT, 0) + COALESCE(PR.TIMES_MAILED_1_COUNT, 0) + COALESCE(PR.TIMES_MAILED_2_COUNT, 0)
            + COALESCE(PR.TIMES_MAILED_3_COUNT, 0) + COALESCE(PR.TIMES_MAILED_4_COUNT, 0) + COALESCE(PR.TIMES_MAILED_5_COUNT, 0)
            + COALESCE(PR.TIMES_MAILED_6_COUNT, 0) + COALESCE(PR.TIMES_MAILED_7_COUNT, 0) + COALESCE(PR.TIMES_MAILED_8_COUNT, 0)
            + COALESCE(PR.TIMES_MAILED_9_PLUS_COUNT, 0), 0) AS TIMES_MAILED_TOTAL
        , ARRAY_MIN(PR.AVAILABLE_TIERS) AS PROFILE_MIN_TIER
        , ARRAY_MAX(PR.AVAILABLE_TIERS) AS PROFILE_MAX_TIER
    FROM VW_PADM_CAMPAIGN_OFFER_CURRENT AS O
    INNER JOIN DM_PADM_CAMPAIGN_OFFER AS CO
            ON O.CAMPAIGN_OFFER_ID = CO.CAMPAIGN_OFFER_ID
    INNER JOIN DM_PADM_CAMPAIGN_1 AS C
            ON O.CAMPAIGN_ID = C.CAMPAIGN_ID
    LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_CAMPAIGN_OFFERS AS ACM
           ON ACM.RCD_UUID = CO.SOURCE_RECORD_ID
    LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P
           ON O.PROGRAM_CODE = P.PROGRAM_CODE
          AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
    LEFT JOIN DM_PADM_OFFER_SEGMENT_ALLOCATION AS A
           ON O.CAMPAIGN_OFFER_ID = A.CAMPAIGN_OFFER_ID
          AND A.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_SEGMENT_1 AS S
           ON A.SEGMENT_ID = S.SEGMENT_ID
    LEFT JOIN SEGMENT_GROUP AS SG
           ON A.SEGMENT_ID = SG.SEGMENT_ID
    LEFT JOIN DM_PADM_CAMPAIGN_OFFER_PROFILE AS PR
           ON O.CAMPAIGN_OFFER_ID = PR.CAMPAIGN_OFFER_ID
          AND PR.IS_CURRENT = TRUE
    LEFT JOIN DM_PADM_PROSPECT_TYPE_RULE AS PT
           ON UPPER(TRIM(COALESCE(ACM.CAMPAIGN_OFFER_SEGMENT_NAME, O.OFFER_SEGMENT_NAME))) = UPPER(PT.ACM_SEGMENT_NAME)
          AND PT.ACTIVE_FLAG = TRUE
    LEFT JOIN DM_PADM_PROSPECT_TYPE_RULE AS PTD
           ON PTD.ACM_SEGMENT_NAME = '*'
          AND PTD.ACTIVE_FLAG = TRUE
),
SHARED AS
(
    SELECT
          B.*
        , IFF(
              B.SEGMENT_ID IS NULL, NULL,
              IFF(
                  SUM(COALESCE(B.BASE_QUANTITY, 0)) OVER (PARTITION BY B.CAMPAIGN_ID, B.SEGMENT_ID) > 0,
                  COALESCE(B.BASE_QUANTITY, 0) / SUM(COALESCE(B.BASE_QUANTITY, 0)) OVER (PARTITION BY B.CAMPAIGN_ID, B.SEGMENT_ID),
                  1 / COUNT(*) OVER (PARTITION BY B.CAMPAIGN_ID, B.SEGMENT_ID)
              )
          ) AS SEGMENT_SHARE
    FROM BASE AS B
),
CALC_SOURCE AS
(
    SELECT CAMPAIGN_ID, 'LIVE' AS CALC_SOURCE_ID FROM DM_PADM_CAMPAIGN_1
    UNION ALL
    SELECT CAMPAIGN_ID, CALCULATION_RUN_ID FROM DM_PADM_CALCULATION_RUN WHERE CALCULATION_STATUS = 'COMPLETED'
),
CALC_CELL AS
(
    SELECT 'LIVE' AS CALC_SOURCE_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, SELECTED_QUANTITY,
           BOOKED_PRE_UNWIND_SELECTED, MARKETING_COST_SELECTED, BOOKING_COST_SELECTED,
           EXPECTED_UNWINDS_SELECTED, BOOKED_POST_UNWIND_SELECTED
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
    UNION ALL
    SELECT CALCULATION_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, SELECTED_QUANTITY,
           BOOKED_PRE_UNWIND_SELECTED, MARKETING_COST_SELECTED, BOOKING_COST_SELECTED,
           EXPECTED_UNWINDS_SELECTED, BOOKED_POST_UNWIND_SELECTED
    FROM DM_PADM_CALCULATION_CELL
),
CALC_AGG AS
(
    SELECT
          CALC_SOURCE_ID
        , CAMPAIGN_ID
        , SEGMENT_ID
        , SUM(SELECTED_QUANTITY) AS SEL_QUANTITY
        , SUM(BOOKED_PRE_UNWIND_SELECTED) AS SEL_BOARDS
        , SUM(MARKETING_COST_SELECTED) AS SEL_MARKETING
        , SUM(BOOKING_COST_SELECTED) AS SEL_BOOKING
        , SUM(EXPECTED_UNWINDS_SELECTED) AS SEL_UNWINDS
        , SUM(BOOKED_POST_UNWIND_SELECTED) AS SEL_POST_BOARDS
        , MIN(IFF(SELECTED_QUANTITY > 0, RESPONSE_MODEL_TIER, NULL)) AS SEL_MIN_TIER
        , MAX(IFF(SELECTED_QUANTITY > 0, RESPONSE_MODEL_TIER, NULL)) AS SEL_MAX_TIER
    FROM CALC_CELL
    GROUP BY CALC_SOURCE_ID, CAMPAIGN_ID, SEGMENT_ID
),
ASSEMBLED AS
(
    SELECT
          CS.CALC_SOURCE_ID
        , SH.*
        , (CA.SEL_QUANTITY > 0) AS HAS_CALCULATION
        , CA.SEL_QUANTITY, CA.SEL_BOARDS, CA.SEL_MARKETING, CA.SEL_BOOKING, CA.SEL_UNWINDS, CA.SEL_POST_BOARDS
        , CA.SEL_MIN_TIER, CA.SEL_MAX_TIER
        , COALESCE(SA.NBR_OVERRIDE, CAS.NBR) AS ASSUMED_NBR
        , COALESCE(SA.UNWIND_RATE_OVERRIDE, CAS.UNWIND_RATE) AS ASSUMED_UNWIND_RATE
        , COALESCE(SA.CPP_OVERRIDE, CAS.CPP, SH.ACM_CPP) AS ASSUMED_CPP
        , COALESCE(SA.UNIT_COST_OVERRIDE, CAS.UNIT_COST) AS ASSUMED_UNIT_COST
    FROM SHARED AS SH
    INNER JOIN CALC_SOURCE AS CS
            ON SH.CAMPAIGN_ID = CS.CAMPAIGN_ID
    LEFT JOIN CALC_AGG AS CA
           ON CS.CALC_SOURCE_ID = CA.CALC_SOURCE_ID
          AND SH.CAMPAIGN_ID = CA.CAMPAIGN_ID
          AND SH.SEGMENT_ID = CA.SEGMENT_ID
    LEFT JOIN VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS CAS
           ON SH.CAMPAIGN_ID = CAS.CAMPAIGN_ID
    LEFT JOIN VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS SA
           ON SH.CAMPAIGN_ID = SA.CAMPAIGN_ID
          AND SH.SEGMENT_ID = SA.SEGMENT_ID
),
FIGURES AS
(
    SELECT
          X.*
        , IFF(X.HAS_CALCULATION, X.SEL_QUANTITY * X.SEGMENT_SHARE, X.BASE_QUANTITY) AS QUANTITY
        , IFF(X.HAS_CALCULATION, X.SEL_BOARDS / NULLIF(X.SEL_QUANTITY, 0), X.ASSUMED_NBR) AS NBR
        , X.ASSUMED_CPP AS CPP
        , X.ASSUMED_UNIT_COST AS UNIT_COST
        , IFF(X.HAS_CALCULATION, X.SEL_UNWINDS / NULLIF(X.SEL_BOARDS, 0), X.ASSUMED_UNWIND_RATE) AS UNWIND_RATE
    FROM ASSEMBLED AS X
),
FIGURES_2 AS
(
    SELECT
          F.*
        , IFF(F.HAS_CALCULATION, F.SEL_BOARDS * F.SEGMENT_SHARE, F.QUANTITY * F.NBR) AS BOARDS
        , IFF(F.HAS_CALCULATION, F.SEL_MARKETING * F.SEGMENT_SHARE, F.QUANTITY * F.CPP) AS MARKETING_EXPENSE
    FROM FIGURES AS F
),
FIGURES_3 AS
(
    SELECT
          F.*
        , IFF(F.HAS_CALCULATION, F.SEL_POST_BOARDS * F.SEGMENT_SHARE, F.BOARDS * (1 - F.UNWIND_RATE)) AS POST_UNWIND_BOARDS
        , IFF(F.HAS_CALCULATION, (F.SEL_MARKETING + F.SEL_BOOKING) * F.SEGMENT_SHARE,
              F.MARKETING_EXPENSE + F.BOARDS * F.UNIT_COST) AS MARKETING_PLUS_BOOKING_COSTS
    FROM FIGURES_2 AS F
)
SELECT
      F.*
    , IFF(F.HAS_CALCULATION, F.SEL_POST_BOARDS * F.SEGMENT_SHARE, F.BOARDS * (1 - F.UNWIND_RATE)) AS POST_UNWIND_BOARDS
    , IFF(F.HAS_CALCULATION, (F.SEL_MARKETING + F.SEL_BOOKING) * F.SEGMENT_SHARE,
          F.MARKETING_EXPENSE + F.BOARDS * F.UNIT_COST) AS MARKETING_PLUS_BOOKING_COSTS
    , IFF(BOARDS, MARKETING_EXPENSE / NULLIF(BOARDS, 0), 0) AS PRE_UNWIND_CPA
    , MARKETING_PLUS_BOOKING_COSTS / NULLIF(POST_UNWIND_BOARDS, 0) AS POST_UNWIND_CPA
    , UNDERWRITING_FLAG
    , PROSPECT_TYPE
    , IFF(HAS_CALCULATION, SEL_MIN_TIER || '-' || SEL_MAX_TIER, PROFILE_MIN_TIER || '-' || PROFILE_MAX_TIER) AS TIERS
    , TEST_PAIRINGS
    , ACM_SEGMENT
    , MAIL_DATE
    , CAMPAIGN_TYPE
    , CAMPAIGN_MONTH_SEQUENCE
    , CAMPAIGN_MONTH
    , CAMPAIGN_YEAR

    , IFF(TIMES_MAILED_TOTAL, TIMES_MAILED_0_COUNT / TIMES_MAILED_TOTAL, NULL) AS TIMES_MAILED_0_PERCENTAGE
    , TIMES_MAILED_1_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_1_PERCENTAGE
    , TIMES_MAILED_2_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_2_PERCENTAGE
    , TIMES_MAILED_3_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_3_PERCENTAGE
    , TIMES_MAILED_4_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_4_PERCENTAGE
    , TIMES_MAILED_5_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_5_PERCENTAGE
    , TIMES_MAILED_6_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_6_PERCENTAGE
    , TIMES_MAILED_7_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_7_PERCENTAGE
    , TIMES_MAILED_8_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_8_PERCENTAGE
    , TIMES_MAILED_9_PLUS_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_9_PLUS_PERCENTAGE
FROM FIGURES_3;

CREATE OR REPLACE VIEW VW_PADM_SIGNATURE_PAGE_LIVE AS
WITH TIMES_MAILED_0 AS (
    SELECT CAMPAIGN_OFFER_ID,
           TIMES_MAILED_0_COUNT / NULLIF(TIMES_MAILED_0_COUNT+TIMES_MAILED_1_COUNT+TIMES_MAILED_2_COUNT+TIMES_MAILED_3_COUNT
               +TIMES_MAILED_4_COUNT+TIMES_MAILED_5_COUNT+TIMES_MAILED_6_COUNT+TIMES_MAILED_7_COUNT+TIMES_MAILED_8_COUNT
               +TIMES_MAILED_9_PLUS_COUNT, 0) AS TIMES_MAILED_0_PERCENTAGE
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE WHERE IS_CURRENT = TRUE
)
SELECT
    O.CAMPAIGN_ID,
    O.CAMPAIGN_OFFER_ID,
    A.SEGMENT_ID,
    A.POPULATION_DESCRIPTION,
    O.OFFER_DESCRIPTION                                                          AS SEGMENT_DESCRIPTION,
    O.SOURCE_MAIL_DATE                                                           AS MAIL_DATE,
    O.OFFER_RESERVATION_CODE,
    O.OFFER_SEGMENT_NAME                                                        AS ACM_SEGMENT,
    O.TEST_TYPE,
    COALESCE(SRC.NETWORK, P.NETWORK)                                             AS NETWORK,
    O.CREDIT_BUREAU_MODEL,
    O.CREDIT_BUREAU_SCORE,
    SRC.CRS_MODEL,
    O.CRS_SCORE,
    SRC.NRM,
    CONCAT(TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1)), '/',
           TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2)))           AS ANNUAL_FEE,
    O.PROMO_CODE                                                                 AS PROMO,
    O.APPROVAL_CODE                                                              AS IVR,
    O.UNDERWRITING_FLAG,
    O.PROSPECT_TYPE,
    O.PRINT_VENDOR_ID                                                            AS PRINT_VENDOR,
    T0.TIMES_MAILED_0_PERCENTAGE,
    SUM(C.SELECTED_QUANTITY)                                                     AS QUANTITY,
    SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS NBR,
    SUM(C.BOOKED_PRE_UNWIND_SELECTED)                                            AS BOARDS,
    SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS CPP,
    SUM(C.MARKETING_COST_SELECTED)                                               AS MARKETING_EXPENSE,
    SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0) AS UNWIND_RATE,
    SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0) AS PRE_UNWIND_CPA,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0) AS POST_UNWIND_CPA,
    SUM(C.BOOKED_POST_UNWIND_SELECTED)                                           AS POST_UNWIND_BOARDS,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)                     AS MARKETING_PLUS_BOOKING_COSTS,
    LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ') WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER)) AS TIERS
FROM VW_PADM_CAMPAIGN_OFFER_CURRENT AS O
LEFT JOIN DM_PADM_OFFER_SEGMENT_ALLOCATION AS A ON O.CAMPAIGN_OFFER_ID = A.CAMPAIGN_OFFER_ID AND A.IS_CURRENT = TRUE
LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P ON O.PROGRAM_CODE = P.PROGRAM_CODE AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
LEFT JOIN VW_PADM_ACM_OFFER_SOURCE AS SRC ON O.OFFER_RESERVATION_CODE = SRC.OFFER_RESERVATION_CODE
LEFT JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C ON A.CAMPAIGN_ID = C.CAMPAIGN_ID AND A.SEGMENT_ID = C.SEGMENT_ID
LEFT JOIN TIMES_MAILED_0 AS T0 ON O.CAMPAIGN_OFFER_ID = T0.CAMPAIGN_OFFER_ID
GROUP BY O.CAMPAIGN_ID, O.CAMPAIGN_OFFER_ID, A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION,
         O.SOURCE_MAIL_DATE, O.OFFER_RESERVATION_CODE, O.OFFER_SEGMENT_NAME,
         O.TEST_TYPE, SRC.NETWORK, P.NETWORK, O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, SRC.CRS_MODEL, O.CRS_SCORE,
         SRC.NRM, SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1, SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2, O.PROMO_CODE,
         O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE, O.PRINT_VENDOR_ID, T0.TIMES_MAILED_0_PERCENTAGE;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_DROPDOWN_60D AS
