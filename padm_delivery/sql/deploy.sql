(
    SELECT 'LIVE' AS CALC_SOURCE_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, SELECTED_QUANTITY,
           BOOKED_PRE_UNWIND_SELECTED, MARKETING_COST_SELECTED, BOOKING_COST_SELECTED,
           EXPECTED_UNWINDS_SELECTED, BOOKED_POST_UNWIND_SELECTED
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT
    UNION ALL
    SELECT CALCULATION_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, SELECTED_QUANTITY,
           BOOKED_PRE_UNWIND_SELECTED, MARKETING_COST_SELECTED, BOOKING_COST_SELECTED,
           EXPECTED_UNWINDS_SELECTED, BOOKED_POST_UNWIND_SELECTED
    FROM DM_PADM_CALCULATION_CELL
),
CALC_AGG AS
(
    SELECT
          CALC_SOURCE_ID
        , CAMPAIGN_ID
        , SEGMENT_ID
        , SUM(SELECTED_QUANTITY) AS SEL_QUANTITY
        , SUM(BOOKED_PRE_UNWIND_SELECTED) AS SEL_BOARDS
        , SUM(MARKETING_COST_SELECTED) AS SEL_MARKETING
        , SUM(BOOKING_COST_SELECTED) AS SEL_BOOKING
        , SUM(EXPECTED_UNWINDS_SELECTED) AS SEL_UNWINDS
        , SUM(BOOKED_POST_UNWIND_SELECTED) AS SEL_POST_BOARDS
        , MIN(IFF(SELECTED_QUANTITY > 0, RESPONSE_MODEL_TIER, NULL)) AS SEL_MIN_TIER
        , MAX(IFF(SELECTED_QUANTITY > 0, RESPONSE_MODEL_TIER, NULL)) AS SEL_MAX_TIER
    FROM CALC_CELL
    GROUP BY CALC_SOURCE_ID, CAMPAIGN_ID, SEGMENT_ID
),
ASSEMBLED AS
(
    SELECT
          CS.CALC_SOURCE_ID
        , SH.*
        , (CA.SEL_QUANTITY > 0) AS HAS_CALCULATION
        , CA.SEL_QUANTITY, CA.SEL_BOARDS, CA.SEL_MARKETING, CA.SEL_BOOKING, CA.SEL_UNWINDS, CA.SEL_POST_BOARDS
        , CA.SEL_MIN_TIER, CA.SEL_MAX_TIER
        , COALESCE(SA.NBR_OVERRIDE, CAS.NBR) AS ASSUMED_NBR
        , COALESCE(SA.UNWIND_RATE_OVERRIDE, CAS.UNWIND_RATE) AS ASSUMED_UNWIND_RATE
        , COALESCE(SA.CPP_OVERRIDE, CAS.CPP, SH.ACM_CPP) AS ASSUMED_CPP
        , COALESCE(SA.UNIT_COST_OVERRIDE, CAS.UNIT_COST) AS ASSUMED_UNIT_COST
    FROM SHARED AS SH
    INNER JOIN CALC_SOURCE AS CS
            ON SH.CAMPAIGN_ID = CS.CAMPAIGN_ID
    LEFT JOIN CALC_AGG AS CA
           ON CS.CALC_SOURCE_ID = CA.CALC_SOURCE_ID
          AND SH.CAMPAIGN_ID = CA.CAMPAIGN_ID
          AND SH.SEGMENT_ID = CA.SEGMENT_ID
    LEFT JOIN VW_PADM_CAMPAIGN_ASSUMPTION_CURRENT AS CAS
           ON SH.CAMPAIGN_ID = CAS.CAMPAIGN_ID
    LEFT JOIN VW_PADM_SEGMENT_ASSUMPTION_CURRENT AS SA
           ON SH.CAMPAIGN_ID = SA.CAMPAIGN_ID
          AND SH.SEGMENT_ID = SA.SEGMENT_ID
),
FIGURES AS
(
    SELECT
          X.*
        , IFF(X.HAS_CALCULATION, X.SEL_QUANTITY * X.SEGMENT_SHARE, X.BASE_QUANTITY) AS QUANTITY
        , IFF(X.HAS_CALCULATION, X.SEL_BOARDS / NULLIF(X.SEL_QUANTITY, 0), X.ASSUMED_NBR) AS NBR
        , X.ASSUMED_CPP AS CPP
        , X.ASSUMED_UNIT_COST AS UNIT_COST
        , IFF(X.HAS_CALCULATION, X.SEL_UNWINDS / NULLIF(X.SEL_BOARDS, 0), X.ASSUMED_UNWIND_RATE) AS UNWIND_RATE
    FROM ASSEMBLED AS X
),
FIGURES_2 AS
(
    SELECT
          F.*
        , IFF(F.HAS_CALCULATION, F.SEL_BOARDS * F.SEGMENT_SHARE, F.QUANTITY * F.NBR) AS BOARDS
        , IFF(F.HAS_CALCULATION, F.SEL_MARKETING * F.SEGMENT_SHARE, F.QUANTITY * F.CPP) AS MARKETING_EXPENSE
    FROM FIGURES AS F
),
FIGURES_3 AS
(
    SELECT
          F.*
        , IFF(F.HAS_CALCULATION, F.SEL_POST_BOARDS * F.SEGMENT_SHARE, F.BOARDS * (1 - F.UNWIND_RATE)) AS POST_UNWIND_BOARDS
        , IFF(F.HAS_CALCULATION, (F.SEL_MARKETING + F.SEL_BOOKING) * F.SEGMENT_SHARE,
              F.MARKETING_EXPENSE + F.BOARDS * F.UNIT_COST) AS MARKETING_PLUS_BOOKING_COSTS
    FROM FIGURES_2 AS F
)
SELECT
      F.*
    , IFF(BOARDS <> 0, MARKETING_EXPENSE / NULLIF(BOARDS, 0), 0) AS PRE_UNWIND_CPA
    , MARKETING_PLUS_BOOKING_COSTS / NULLIF(POST_UNWIND_BOARDS, 0) AS POST_UNWIND_CPA
    , IFF(HAS_CALCULATION, SEL_MIN_TIER || '-' || SEL_MAX_TIER, PROFILE_MIN_TIER || '-' || PROFILE_MAX_TIER) AS TIERS
    , IFF(TIMES_MAILED_TOTAL <> 0, TIMES_MAILED_0_COUNT / TIMES_MAILED_TOTAL, NULL) AS TIMES_MAILED_0_PERCENTAGE
    , TIMES_MAILED_1_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_1_PERCENTAGE
    , TIMES_MAILED_2_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_2_PERCENTAGE
    , TIMES_MAILED_3_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_3_PERCENTAGE
    , TIMES_MAILED_4_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_4_PERCENTAGE
    , TIMES_MAILED_5_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_5_PERCENTAGE
    , TIMES_MAILED_6_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_6_PERCENTAGE
    , TIMES_MAILED_7_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_7_PERCENTAGE
    , TIMES_MAILED_8_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_8_PERCENTAGE
    , TIMES_MAILED_9_PLUS_COUNT / TIMES_MAILED_TOTAL AS TIMES_MAILED_9_PLUS_PERCENTAGE
FROM FIGURES_3 AS F;

CREATE OR REPLACE VIEW VW_PADM_SIGNATURE_PAGE_LIVE AS
WITH TIMES_MAILED_0 AS (
    SELECT CAMPAIGN_OFFER_ID,
           TIMES_MAILED_0_COUNT / NULLIF(TIMES_MAILED_0_COUNT+TIMES_MAILED_1_COUNT+TIMES_MAILED_2_COUNT+TIMES_MAILED_3_COUNT
               +TIMES_MAILED_4_COUNT+TIMES_MAILED_5_COUNT+TIMES_MAILED_6_COUNT+TIMES_MAILED_7_COUNT+TIMES_MAILED_8_COUNT
               +TIMES_MAILED_9_PLUS_COUNT, 0) AS TIMES_MAILED_0_PERCENTAGE
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE WHERE IS_CURRENT = TRUE
)
SELECT
    O.CAMPAIGN_ID,
    O.CAMPAIGN_OFFER_ID,
    A.SEGMENT_ID,
    A.POPULATION_DESCRIPTION,
    O.OFFER_DESCRIPTION                                                          AS SEGMENT_DESCRIPTION,
    O.SOURCE_MAIL_DATE                                                           AS MAIL_DATE,
    O.PROGRAM_CODE,
    O.OFFER_RESERVATION_CODE,
    O.OFFER_SEGMENT_NAME                                                        AS ACM_SEGMENT,
    O.TEST_TYPE,
    COALESCE(SRC.NETWORK, P.NETWORK)                                             AS NETWORK,
    O.CREDIT_BUREAU_MODEL,
    O.CREDIT_BUREAU_SCORE,
    SRC.CRS_MODEL,
    O.CRS_SCORE,
    SRC.NRM,
    CONCAT(TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1)), '/',
           TO_VARCHAR(COALESCE(SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2)))           AS ANNUAL_FEE,
    O.PROMO_CODE                                                                 AS PROMO,
    O.APPROVAL_CODE                                                              AS IVR,
    O.UNDERWRITING_FLAG,
    O.PROSPECT_TYPE,
    O.PRINT_VENDOR_ID                                                            AS PRINT_VENDOR,
    T0.TIMES_MAILED_0_PERCENTAGE,
    SUM(C.SELECTED_QUANTITY)                                                     AS QUANTITY,
    SUM(C.SELECTED_QUANTITY * C.SELECTED_NRR) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS NBR,
    SUM(C.BOOKED_PRE_UNWIND_SELECTED)                                            AS BOARDS,
    SUM(C.SELECTED_QUANTITY * C.EFFECTIVE_CPP) / NULLIF(SUM(C.SELECTED_QUANTITY), 0) AS CPP,
    SUM(C.MARKETING_COST_SELECTED)                                               AS MARKETING_EXPENSE,
    SUM(C.EXPECTED_UNWINDS_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0) AS UNWIND_RATE,
    SUM(C.MARKETING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_PRE_UNWIND_SELECTED), 0) AS PRE_UNWIND_CPA,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED) / NULLIF(SUM(C.BOOKED_POST_UNWIND_SELECTED), 0) AS POST_UNWIND_CPA,
    SUM(C.BOOKED_POST_UNWIND_SELECTED)                                           AS POST_UNWIND_BOARDS,
    SUM(C.MARKETING_COST_SELECTED + C.BOOKING_COST_SELECTED)                     AS MARKETING_PLUS_BOOKING_COSTS,
    LISTAGG(DISTINCT TO_VARCHAR(C.RESPONSE_MODEL_TIER), ', ') WITHIN GROUP (ORDER BY TO_VARCHAR(C.RESPONSE_MODEL_TIER)) AS TIERS
FROM VW_PADM_CAMPAIGN_OFFER_CURRENT AS O
LEFT JOIN DM_PADM_OFFER_SEGMENT_ALLOCATION AS A ON O.CAMPAIGN_OFFER_ID = A.CAMPAIGN_OFFER_ID AND A.IS_CURRENT = TRUE
LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P ON O.PROGRAM_CODE = P.PROGRAM_CODE AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
LEFT JOIN VW_PADM_ACM_OFFER_SOURCE AS SRC ON O.OFFER_RESERVATION_CODE = SRC.OFFER_RESERVATION_CODE
LEFT JOIN VW_PADM_SEGMENT_CALCULATION_CURRENT AS C ON A.CAMPAIGN_ID = C.CAMPAIGN_ID AND A.SEGMENT_ID = C.SEGMENT_ID
LEFT JOIN TIMES_MAILED_0 AS T0 ON O.CAMPAIGN_OFFER_ID = T0.CAMPAIGN_OFFER_ID
GROUP BY O.CAMPAIGN_ID, O.CAMPAIGN_OFFER_ID, A.SEGMENT_ID, A.POPULATION_DESCRIPTION, O.OFFER_DESCRIPTION,
         O.SOURCE_MAIL_DATE, O.PROGRAM_CODE, O.OFFER_RESERVATION_CODE, O.OFFER_SEGMENT_NAME,
         O.TEST_TYPE, SRC.NETWORK, P.NETWORK, O.CREDIT_BUREAU_MODEL, O.CREDIT_BUREAU_SCORE, SRC.CRS_MODEL, O.CRS_SCORE,
         SRC.NRM, SRC.ANNUAL_FEE_YR1, P.ANNUAL_FEE_YR1, SRC.ANNUAL_FEE_YR2, P.ANNUAL_FEE_YR2, O.PROMO_CODE,
         O.APPROVAL_CODE, O.UNDERWRITING_FLAG, O.PROSPECT_TYPE, O.PRINT_VENDOR_ID, T0.TIMES_MAILED_0_PERCENTAGE;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_DROPDOWN_60D AS
WITH RECENT AS
(
    SELECT O.*, P.NETWORK AS PROGRAM_NETWORK,
           CONCAT(TO_VARCHAR(P.ANNUAL_FEE_YR1), '/', TO_VARCHAR(P.ANNUAL_FEE_YR2)) AS PROGRAM_ANNUAL_FEE
    FROM CSTONE_BIZ.REFERENCE.T_ACM_CAMPAIGN_OFFERS AS O
    LEFT JOIN CSTONE_BIZ.REFERENCE.T_ACM_PROGRAMS AS P
           ON O.PROGRAM_CODE = P.PROGRAM_CODE
          AND O.PROGRAM_VERSION_NUMBER = P.PROGRAM_VERSION_NUMBER
    WHERE O.CAMPAIGN_GROUP_MAIL_DATE >= DATEADD(DAY, -60, CURRENT_DATE())
)
SELECT DISTINCT FIELD_NAME, FIELD_VALUE
FROM
(
    SELECT 'CREDIT_BUREAU_MODEL' AS FIELD_NAME, TO_VARCHAR(PROSPECT_CREDIT_BUREAU_MODEL) AS FIELD_VALUE FROM RECENT
    UNION ALL SELECT 'CREDIT_BUREAU_SCORE', TO_VARCHAR(PROSPECT_CREDIT_BUREAU_SCORE) FROM RECENT
    UNION ALL SELECT 'CRS_MODEL', TO_VARCHAR(PROSPECT_CRS_MODEL) FROM RECENT
    UNION ALL SELECT 'CRS_SCORE', TO_VARCHAR(PROSPECT_CRS_SCORE) FROM RECENT
    UNION ALL SELECT 'ANNUAL_FEE', PROGRAM_ANNUAL_FEE FROM RECENT
    UNION ALL SELECT 'NETWORK', PROGRAM_NETWORK FROM RECENT
    -- RESPONSE_MODEL_TYPE intentionally not added here: no raw ACM column backs it yet
    -- (Create Segment's Response Model Type dropdown is empty today) -- identify the real source
    -- column before adding a branch here.
) AS ALL_FIELDS;

CREATE OR REPLACE PROCEDURE SP_PADM_ACTIVATE_CAMPAIGN(P_CAMPAIGN_ID VARCHAR, P_CHANGE_REASON VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_REPORTING_MONTH DATE;
    V_CAMPAIGN_TYPE VARCHAR;
    V_SOURCE_VERSION_ID VARCHAR;
    V_LOAD_BATCH_ID VARCHAR;
    V_SOURCE_HASH VARCHAR;
    V_NEXT_SOURCE_VERSION NUMBER(10,0);
    V_CURRENT_VERSION_COUNT NUMBER DEFAULT 0;
    V_COMPONENT_COUNT NUMBER DEFAULT 0;
    V_OFFER_COUNT NUMBER DEFAULT 0;
    V_PROFILE_COUNT NUMBER DEFAULT 0;
    V_ELIGIBLE_COUNT NUMBER DEFAULT 0;
BEGIN
    SELECT MAX(STATUS), MAX(REPORTING_MONTH), MAX(CAMPAIGN_TYPE)
      INTO :V_STATUS, :V_REPORTING_MONTH, :V_CAMPAIGN_TYPE
    FROM DM_PADM_CAMPAIGN_1
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS IS NULL) THEN
        RETURN 'Campaign was not found.';
    END IF;

    IF (V_STATUS NOT IN ('NEW', 'DRAFT')) THEN
        RETURN 'Only NEW or incomplete DRAFT campaigns can be activated.';
    END IF;

    IF (NULLIF(TRIM(P_CHANGE_REASON), '') IS NULL) THEN
        RETURN 'Change Reason is required.';
    END IF;

    SELECT COUNT(*)
      INTO :V_CURRENT_VERSION_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_CURRENT_VERSION_COUNT > 0) THEN
        RETURN 'Campaign already has a current source version.';
    END IF;

    SELECT COALESCE(MAX(SOURCE_VERSION_NUMBER), 0) + 1
      INTO :V_NEXT_SOURCE_VERSION
    FROM DM_PADM_CAMPAIGN_SOURCE_VERSION
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    V_SOURCE_VERSION_ID := UUID_STRING();
    V_LOAD_BATCH_ID := UUID_STRING();

    SELECT COUNT(*), SHA2(
                COALESCE(TO_VARCHAR(:V_REPORTING_MONTH), '') || '|' ||
                COALESCE(:V_CAMPAIGN_TYPE, '') || '|' ||
                COALESCE(TO_VARCHAR(COUNT(*)), '') || '|' ||
                COALESCE(TO_VARCHAR(MIN(SOURCE_MAIL_DATE)), '') || '|' ||
                COALESCE(TO_VARCHAR(MAX(SOURCE_MAIL_DATE)), ''),
                256
           )
      INTO :V_ELIGIBLE_COUNT, :V_SOURCE_HASH
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    -- SHA2(...) above always returns a non-null hash even when COUNT(*) = 0 (every piece going
    -- into it is COALESCE'd to '' first), so the old "IF (V_SOURCE_HASH IS NULL)" check here could
    -- never actually fire -- a month/type with zero eligible ACM offers fell all the way through
    -- to the post-insert validation at the end instead, with the far less useful "Source snapshot
    -- validation failed" message. Check the real row count directly.
    IF (V_ELIGIBLE_COUNT = 0) THEN
        RETURN 'No eligible ACM offers were found for the campaign month and type.';
    END IF;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_VERSION
    (
        CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_VERSION_NUMBER
      , SOURCE_HASH
      , SOURCE_ROW_COUNT
      , SOURCE_MIN_MAIL_DATE
      , SOURCE_MAX_MAIL_DATE
      , LOAD_BATCH_ID
      , IS_CURRENT
      , CHANGE_SUMMARY
    )
    SELECT
        :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , :V_NEXT_SOURCE_VERSION
      , :V_SOURCE_HASH
      , COUNT(*)
      , MIN(SOURCE_MAIL_DATE)
      , MAX(SOURCE_MAIL_DATE)
      , :V_LOAD_BATCH_ID
      , TRUE
      , :P_CHANGE_REASON
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      );

    INSERT INTO DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    (
        CAMPAIGN_SOURCE_COMPONENT_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , SOURCE_OFFER_COUNT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE
      , COUNT(DISTINCT OFFER_RESERVATION_CODE)
    FROM VW_PADM_ACM_OFFER_SOURCE
    WHERE DATE_TRUNC('MONTH', SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    GROUP BY
        SOURCE_CAMPAIGN_IDENTIFICATION_CODE
      , SOURCE_CAMPAIGN_GROUP_CODE
      , SOURCE_CAMPAIGN_GROUP_DESCRIPTION
      , SOURCE_CAMPAIGN_TYPE_CODE
      , SOURCE_CAMPAIGN_TYPE_NAME
      , SOURCE_MAIL_DATE
      , SOURCE_GROUP_START_DATE
      , SOURCE_GROUP_END_DATE
      , SOURCE_GROUP_RETIRE_DATE
      , SOURCE_GROUP_EXPIRE_DATE
      , SOURCE_LETTER_EXPIRE_DATE;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER
    (
        CAMPAIGN_OFFER_ID
      , CAMPAIGN_SOURCE_VERSION_ID
      , CAMPAIGN_ID
      , CAMPAIGN_SOURCE_COMPONENT_ID
      , OFFER_RESERVATION_CODE
      , PROGRAM_CODE
      , PROGRAM_VERSION_NUMBER
      , PROGRAM_MATCH_STATUS
      , MATCHED_PROGRAM_VERSION_NUMBER
      , SOURCE_CAMPAIGN_CODE
      , SOURCE_CAMPAIGN_NAME
      , SOURCE_CAMPAIGN_DESCRIPTION
      , SOURCE_MAIL_DATE
      , OFFER_DESCRIPTION
      , OFFER_SEGMENT_NAME
      , TEST_TYPE
      , SOURCE_CPP
      , PROMO_CODE
      , APPROVAL_CODE
      , UNDERWRITING_FLAG
      , PROSPECT_TYPE
      , PRINT_VENDOR_ID
      , CRS_SCORE
      , CREDIT_BUREAU_MODEL
      , CREDIT_BUREAU_SCORE
      , OFFER_STATUS
      , SOURCE_RECORD_ID
      , SOURCE_ROW_HASH
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , :V_SOURCE_VERSION_ID
      , :P_CAMPAIGN_ID
      , C.CAMPAIGN_SOURCE_COMPONENT_ID
      , S.OFFER_RESERVATION_CODE
      , S.PROGRAM_CODE
      , S.PROGRAM_VERSION_NUMBER
      , S.PROGRAM_MATCH_STATUS
      , S.MATCHED_PROGRAM_VERSION_NUMBER
      , S.SOURCE_CAMPAIGN_CODE
      , S.SOURCE_CAMPAIGN_NAME
      , S.SOURCE_CAMPAIGN_DESCRIPTION
      , S.SOURCE_MAIL_DATE
      , S.OFFER_DESCRIPTION
      , S.ACM_SEGMENT_NAME
      , S.TEST_TYPE
      , S.SOURCE_CPP
      , S.PROMO
      , S.IVR
      , S.UNDERWRITING_FLAG
      , S.PROSPECT_TYPE
      , S.PRINT_VENDOR_ID
      , S.CRS_SCORE
      , S.CREDIT_BUREAU_MODEL
      , S.CREDIT_BUREAU_SCORE
      , S.SOURCE_OFFER_STATUS
      , S.SOURCE_RECORD_ID
      , SHA2(
            COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') || '|' ||
            COALESCE(S.OFFER_RESERVATION_CODE, '') || '|' ||
            COALESCE(S.PROGRAM_CODE, '') || '|' ||
            COALESCE(TO_VARCHAR(S.PROGRAM_VERSION_NUMBER), '') || '|' ||
            COALESCE(S.OFFER_DESCRIPTION, '') || '|' ||
            COALESCE(TO_VARCHAR(S.SOURCE_CPP), ''),
            256
        )
      , TRUE
    FROM VW_PADM_ACM_OFFER_SOURCE AS S
    INNER JOIN DM_PADM_CAMPAIGN_SOURCE_COMPONENT AS C
        ON C.CAMPAIGN_ID = :P_CAMPAIGN_ID
       AND C.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
       AND COALESCE(C.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_IDENTIFICATION_CODE, '')
       AND COALESCE(C.SOURCE_CAMPAIGN_GROUP_CODE, '') = COALESCE(S.SOURCE_CAMPAIGN_GROUP_CODE, '')
       AND C.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE DATE_TRUNC('MONTH', S.SOURCE_MAIL_DATE)::DATE = :V_REPORTING_MONTH
      AND
      (
            (:V_CAMPAIGN_TYPE = 'MAIN' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) = 'PADM')
         OR (:V_CAMPAIGN_TYPE = 'REMAIL' AND UPPER(TRIM(S.SOURCE_CAMPAIGN_GROUP_CODE)) IN ('MAP', 'PAREMAIL'))
      )
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.OFFER_RESERVATION_CODE
        ORDER BY S.SOURCE_MAIL_DATE DESC, S.SOURCE_RECORD_ID DESC
    ) = 1;

    INSERT INTO DM_PADM_CAMPAIGN_OFFER_PROFILE
    (
        CAMPAIGN_OFFER_PROFILE_ID
      , CAMPAIGN_ID
      , CAMPAIGN_OFFER_ID
      , PROFILE_VERSION_NUMBER
      , PROFILE_SOURCE_TYPE
      , ANNUAL_FEE
      , NETWORK
      , IS_CURRENT
    )
    SELECT
        UUID_STRING()
      , O.CAMPAIGN_ID
      , O.CAMPAIGN_OFFER_ID
      , 1
      , 'ACM_SOURCE'
      , S.ANNUAL_FEE
      , S.NETWORK
      , TRUE
    FROM DM_PADM_CAMPAIGN_OFFER AS O
    INNER JOIN VW_PADM_ACM_OFFER_SOURCE AS S
        ON O.OFFER_RESERVATION_CODE = S.OFFER_RESERVATION_CODE
       AND O.SOURCE_MAIL_DATE = S.SOURCE_MAIL_DATE
    WHERE O.CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND O.CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.CAMPAIGN_OFFER_ID
        ORDER BY S.SOURCE_RECORD_ID DESC
    ) = 1;

    UPDATE DM_PADM_CAMPAIGN_1
       SET STATUS = 'DRAFT'
         , ACTIVE_FLAG = TRUE
         , SOURCE_CHANGE_PENDING_FLAG = FALSE
         , CURRENT_SOURCE_VERSION_NUMBER = :V_NEXT_SOURCE_VERSION
         , ROW_VERSION = COALESCE(ROW_VERSION, 0) + 1
         , UPDATED_BY = CURRENT_USER()
         , UPDATED_TS = CURRENT_TIMESTAMP()
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS <> 'DRAFT') THEN
        INSERT INTO DM_PADM_WORKFLOW_EVENT
        (
            WORKFLOW_EVENT_ID
          , CAMPAIGN_ID
          , FROM_STATUS
          , TO_STATUS
          , EVENT_REASON
        )
        SELECT UUID_STRING(), :P_CAMPAIGN_ID, :V_STATUS, 'DRAFT', :P_CHANGE_REASON;
    END IF;

    INSERT INTO DM_PADM_CHANGE_EVENT
    (
        CHANGE_EVENT_ID
      , CAMPAIGN_ID
      , ENTITY_TYPE
      , ENTITY_ID
      , CHANGE_TYPE
      , BEFORE_VALUE
      , AFTER_VALUE
      , CHANGE_REASON
    )
    SELECT
        UUID_STRING()
      , :P_CAMPAIGN_ID
      , 'CAMPAIGN_SOURCE_VERSION'
      , :V_SOURCE_VERSION_ID
      , IFF(:V_STATUS = 'DRAFT', 'SOURCE_SNAPSHOT_REPAIRED', 'CAMPAIGN_ACTIVATED')
      , NULL
      , OBJECT_CONSTRUCT(
            'SOURCE_VERSION_NUMBER', :V_NEXT_SOURCE_VERSION,
            'REPORTING_MONTH', :V_REPORTING_MONTH,
            'CAMPAIGN_TYPE', :V_CAMPAIGN_TYPE
        )
      , :P_CHANGE_REASON;

    SELECT COUNT(*) INTO :V_COMPONENT_COUNT
    FROM DM_PADM_CAMPAIGN_SOURCE_COMPONENT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_OFFER_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND CAMPAIGN_SOURCE_VERSION_ID = :V_SOURCE_VERSION_ID;

    SELECT COUNT(*) INTO :V_PROFILE_COUNT
    FROM DM_PADM_CAMPAIGN_OFFER_PROFILE
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID
      AND IS_CURRENT = TRUE;

    IF (V_COMPONENT_COUNT = 0 OR V_OFFER_COUNT = 0 OR V_PROFILE_COUNT <> V_OFFER_COUNT) THEN
        ROLLBACK;
        RETURN 'Source snapshot validation failed. No changes were committed.';
    END IF;

    COMMIT;
    RETURN 'Campaign source snapshot completed. Components: '
        || TO_VARCHAR(V_COMPONENT_COUNT)
        || ', Offers: '
        || TO_VARCHAR(V_OFFER_COUNT)
        || ', Profiles: '
        || TO_VARCHAR(V_PROFILE_COUNT)
        || '.';
EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;

