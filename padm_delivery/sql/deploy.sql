    P_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_SEASONALITY_REDUCTION_OVERRIDE NUMBER(18,8),
    P_UNWIND_RATE_ADJUSTMENT_OVERRIDE NUMBER(18,8),
    P_EXPECTED_VERSION NUMBER(10,0),
    P_CHANGE_REASON VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_CURRENT_VERSION NUMBER(10,0);
    V_NEXT_VERSION NUMBER(10,0);
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
