    SELECT UUID_STRING(), :P_CAMPAIGN_ID, :P_SEGMENT_ID, :V_NEXT_VERSION
         , P.CPP_OVERRIDE, :P_UNIT_COST_OVERRIDE, :P_NBR_OVERRIDE, :P_UNWIND_RATE_OVERRIDE
         , :P_RATE_ADJUSTMENT_OVERRIDE, :P_SEASONALITY_REDUCTION_OVERRIDE, :P_UNWIND_RATE_ADJUSTMENT_OVERRIDE
