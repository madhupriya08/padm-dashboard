AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_RUN_ID VARCHAR;
    V_WORKING_VERSION NUMBER(10,0);
    V_ASSUMPTION_VERSION_ID VARCHAR;
    V_CELL_COUNT NUMBER(38,0);
    V_MISSING_CPP NUMBER(38,0);
    V_MISSING_NRR NUMBER(38,0);
BEGIN
    SELECT MAX(STATUS), MAX(CURRENT_WORKING_VERSION_NUMBER) INTO :V_STATUS, :V_WORKING_VERSION
    FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;

    SELECT COUNT(*), COUNT_IF(EFFECTIVE_CPP IS NULL), COUNT_IF(BASE_NRR IS NULL)
      INTO :V_CELL_COUNT, :V_MISSING_CPP, :V_MISSING_NRR
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_CELL_COUNT = 0) THEN RETURN 'ERROR: No CDE volume is active for any segment of this campaign.'; END IF;
    IF (V_MISSING_CPP > 0) THEN RETURN 'ERROR: Save CPP (Campaign Assumptions) before calculating Marketing Cost and CPA.'; END IF;
    IF (V_MISSING_NRR > 0) THEN RETURN 'ERROR: ' || V_MISSING_NRR || ' cell(s) have no NRR (no history and no NBR assumption). Save NBR first.'; END IF;

    SELECT MAX(CAMPAIGN_ASSUMPTION_VERSION_ID) INTO :V_ASSUMPTION_VERSION_ID
    FROM DM_PADM_CAMPAIGN_ASSUMPTION_VERSION WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND IS_CURRENT = TRUE;
    V_RUN_ID := UUID_STRING();

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_CALCULATION_RUN
        (CALCULATION_RUN_ID, CAMPAIGN_ID, CAMPAIGN_WORKING_VERSION_NUMBER, CAMPAIGN_ASSUMPTION_VERSION_ID,
         CALCULATION_STATUS, SOURCE_DATA_AS_OF_TS)
    VALUES (:V_RUN_ID, :P_CAMPAIGN_ID, :V_WORKING_VERSION, :V_ASSUMPTION_VERSION_ID, 'STARTED', CURRENT_TIMESTAMP());

    INSERT INTO DM_PADM_CALCULATION_CELL
    (
        CALCULATION_CELL_ID, CALCULATION_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED, BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED, POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    )
    SELECT
        UUID_STRING(), :V_RUN_ID, CAMPAIGN_ID, SEGMENT_ID, RESPONSE_MODEL_TIER, TIMES_MAILED_BUCKET,
        CDE_VOLUME, EMS_REDUCTION_RATE, POST_EMS_VOLUME, SELECTION_PERCENTAGE, SELECTED_QUANTITY,
        BASE_NRR, EFFECTIVE_NRR, SELECTED_NRR, HISTORICAL_UNWIND_RATE,
        BOOKED_PRE_UNWIND_UNIVERSE, BOOKED_PRE_UNWIND_SELECTED,
        MARKETING_COST_UNIVERSE, MARKETING_COST_SELECTED, BOOKING_COST_UNIVERSE, BOOKING_COST_SELECTED,
        EXPECTED_UNWINDS_UNIVERSE, EXPECTED_UNWINDS_SELECTED,
        BOOKED_POST_UNWIND_UNIVERSE, BOOKED_POST_UNWIND_SELECTED,
        PRE_UNWIND_CPA_UNIVERSE, PRE_UNWIND_CPA_SELECTED, POST_UNWIND_CPA_UNIVERSE, POST_UNWIND_CPA_SELECTED
    FROM VW_PADM_SEGMENT_CALCULATION_CURRENT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    UPDATE DM_PADM_CALCULATION_RUN
       SET CALCULATION_STATUS = 'COMPLETED', CALCULATION_COMPLETED_TS = CURRENT_TIMESTAMP()
     WHERE CALCULATION_RUN_ID = :V_RUN_ID;

    COMMIT;
    RETURN :V_RUN_ID || '|' || :V_CELL_COUNT;
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE SP_PADM_GENERATE_SIGNATURE_PAGE_2(
    P_CAMPAIGN_ID VARCHAR,
    P_CALCULATION_RUN_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_LATEST_RUN VARCHAR;
    V_LATEST_STATUS VARCHAR;
    V_NEXT_VERSION NUMBER(10,0);
    V_ROW_COUNT NUMBER(38,0);
    V_EVENT_ID VARCHAR;
BEGIN
    SELECT MAX(STATUS) INTO :V_STATUS FROM DM_PADM_CAMPAIGN_1 WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_STATUS IS NULL) THEN RETURN 'ERROR: Campaign was not found.'; END IF;
    IF (V_STATUS = 'APPROVED') THEN RETURN 'ERROR: Approved -- read only.'; END IF;
    IF (V_STATUS NOT IN ('DRAFT', 'IN_PROGRESS', 'PENDING_APPROVAL')) THEN
        RETURN 'ERROR: Signature Page 2 can only be generated for DRAFT / IN_PROGRESS campaigns.';
    END IF;

    SELECT MAX_BY(CALCULATION_RUN_ID, CALCULATION_STARTED_TS), MAX_BY(CALCULATION_STATUS, CALCULATION_STARTED_TS)
      INTO :V_LATEST_RUN, :V_LATEST_STATUS
    FROM DM_PADM_CALCULATION_RUN WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;
    IF (V_LATEST_RUN IS NULL OR V_LATEST_STATUS <> 'COMPLETED') THEN
        RETURN 'ERROR: The latest calculation run is not COMPLETED. Run Calculation first.';
    END IF;
    IF (P_CALCULATION_RUN_ID IS NOT NULL AND P_CALCULATION_RUN_ID <> V_LATEST_RUN) THEN
        RETURN 'ERROR: A newer calculation run exists. Reload and generate from the latest run.';
    END IF;

    SELECT COALESCE(MAX(SIGNATURE_VERSION_NUMBER), 0) + 1 INTO :V_NEXT_VERSION
    FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    BEGIN TRANSACTION;

    INSERT INTO DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT
    (
        SIGNATURE_PAGE_2_SNAPSHOT_ID, CAMPAIGN_ID, CALCULATION_RUN_ID, SIGNATURE_VERSION_NUMBER,
        CAMPAIGN_OFFER_ID, SEGMENT_ID, OFFER_RESERVATION_CODE, POPULATION_DESCRIPTION, POPULATION_GROUP_KEY,
        SEGMENT_DESCRIPTION, ANNUAL_FEE, TEST_TYPE, NETWORK, CREDIT_BUREAU_MODEL, CREDIT_BUREAU_SCORE,
        CRS_MODEL, CRS_SCORE, NRM, QUANTITY, NBR, BOARDS, CPP, MARKETING_EXPENSE, UNWIND_RATE,
        PRE_UNWIND_CPA, POST_UNWIND_CPA, PROMO, IVR, UNDERWRITING_FLAG, PROSPECT_TYPE,
        TIMES_MAILED_0_PERCENTAGE, TIERS, PRINT_VENDOR, POST_UNWIND_BOARDS, MARKETING_PLUS_BOOKING_COSTS,
        UNIT_COST, CAMPAIGN_YEAR, CAMPAIGN_MONTH, CAMPAIGN_MONTH_SEQUENCE, CAMPAIGN_TYPE, MAIL_DATE,
        ACM_SEGMENT, TEST_PAIRINGS, TIMES_MAILED_1_PERCENTAGE, TIMES_MAILED_2_PERCENTAGE,
        TIMES_MAILED_3_PERCENTAGE, TIMES_MAILED_4_PERCENTAGE, TIMES_MAILED_5_PERCENTAGE,
        TIMES_MAILED_6_PERCENTAGE, TIMES_MAILED_7_PERCENTAGE, TIMES_MAILED_8_PERCENTAGE,
        TIMES_MAILED_9_PLUS_PERCENTAGE, SNAPSHOT_STATUS
    )
    SELECT
        UUID_STRING(), CAMPAIGN_ID, CALC_SOURCE_ID, :V_NEXT_VERSION,
        CAMPAIGN_OFFER_ID, COALESCE(SEGMENT_ID, 'UNALLOCATED'), OFFER_RESERVATION_CODE, POPULATION_DESCRIPTION,
        POPULATION_GROUP_KEY, SEGMENT_DESCRIPTION, ANNUAL_FEE, TEST_TYPE, NETWORK, CREDIT_BUREAU_MODEL,
        CREDIT_BUREAU_SCORE, CRS_MODEL, CRS_SCORE, NRM, QUANTITY, NBR, BOARDS, CPP, MARKETING_EXPENSE, UNWIND_RATE,
        PRE_UNWIND_CPA, POST_UNWIND_CPA, PROMO, IVR, UNDERWRITING_FLAG, PROSPECT_TYPE,
        TIMES_MAILED_0_PERCENTAGE, TIERS, PRINT_VENDOR, POST_UNWIND_BOARDS, MARKETING_PLUS_BOOKING_COSTS,
        UNIT_COST, CAMPAIGN_YEAR, CAMPAIGN_MONTH, CAMPAIGN_MONTH_SEQUENCE, CAMPAIGN_TYPE, MAIL_DATE,
        ACM_SEGMENT, TEST_PAIRINGS, TIMES_MAILED_1_PERCENTAGE, TIMES_MAILED_2_PERCENTAGE,
        TIMES_MAILED_3_PERCENTAGE, TIMES_MAILED_4_PERCENTAGE, TIMES_MAILED_5_PERCENTAGE,
        TIMES_MAILED_6_PERCENTAGE, TIMES_MAILED_7_PERCENTAGE, TIMES_MAILED_8_PERCENTAGE,
        TIMES_MAILED_9_PLUS_PERCENTAGE, 'PENDING_APPROVAL'
    FROM VW_PADM_SIGNATURE_PAGE_ALL
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND CALC_SOURCE_ID = :V_LATEST_RUN;

    SELECT COUNT(*) INTO :V_ROW_COUNT FROM DM_PADM_SIGNATURE_PAGE_2_SNAPSHOT
    WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID AND SIGNATURE_VERSION_NUMBER = :V_NEXT_VERSION;

    UPDATE DM_PADM_CAMPAIGN_1
       SET STATUS = 'PENDING_APPROVAL', ROW_VERSION = ROW_VERSION + 1,
           UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
     WHERE CAMPAIGN_ID = :P_CAMPAIGN_ID;

    IF (V_STATUS <> 'PENDING_APPROVAL') THEN
        V_EVENT_ID := UUID_STRING();
        INSERT INTO DM_PADM_WORKFLOW_EVENT (WORKFLOW_EVENT_ID, CAMPAIGN_ID, FROM_STATUS, TO_STATUS, EVENT_REASON, EVENT_COMMENT)
        VALUES (:V_EVENT_ID, :P_CAMPAIGN_ID, :V_STATUS, 'PENDING_APPROVAL', 'Signature Page 2 v' || :V_NEXT_VERSION || ' generated', NULL);
    END IF;

    INSERT INTO DM_PADM_CHANGE_EVENT (CHANGE_EVENT_ID, CAMPAIGN_ID, ENTITY_TYPE, ENTITY_ID, CHANGE_TYPE, BEFORE_VALUE, AFTER_VALUE, CHANGE_REASON)
    SELECT UUID_STRING(), :P_CAMPAIGN_ID, 'SIGNATURE_PAGE_2', :V_LATEST_RUN, 'SNAPSHOT_CREATED',
           OBJECT_CONSTRUCT('STATUS', :V_STATUS),
           OBJECT_CONSTRUCT('SIGNATURE_VERSION_NUMBER', :V_NEXT_VERSION, 'ROW_COUNT', :V_ROW_COUNT),
           'Signature Page 2 v' || :V_NEXT_VERSION || ' generated';

    COMMIT;
    RETURN 'Signature Page 2 version ' || :V_NEXT_VERSION || ' created (' || :V_ROW_COUNT || ' rows). Status: PENDING_APPROVAL.';
EXCEPTION WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;

CREATE OR REPLACE VIEW VW_PADM_SEGMENT_SOURCE_CANDIDATE(
    SEGMENT_KEY,
    SUGGESTED_SEGMENT_NAME,
    SOURCE_SEGMENT_NAME,
    SOURCE,
    BUREAU_SCORE_TYPE,
    BUREAU_SCORE_RANGE,
    SCORE_MIN,
    SCORE_MAX,
    PROSPECT_SEGMENT_TYPE,
    ANNUAL_FEE,
    NETWORK,
    MLA_FLAG,
    RESPONSE_MODEL_TYPE,
    RISK_SCORE_TYPE,
    MAIL_REMAIL,
    SOURCE_RECORD_COUNT,
    FIRST_MAIL_DATE,
    LAST_MAIL_DATE
) AS
-- PROSPECT_TYPE/PROSPECT_SOURCE are NOT raw columns on the mailfile tables -- they're derived from
-- CAMPAIGN_SOURCE (a single letter/digit code), per the real classification script.
-- PROSPECT_SEGMENT_TYPE below reproduces that script's PROSPECTING/RETARGETING split; SOURCE_SEGMENT_NAME
-- carries the script's own finer-grained prospect_type label (e.g. 'PCO', 'Experian Vantage MLA') for
-- readability, informational only -- it isn't selected into the MERGE below. The former 'LIFT' leg is
-- dropped: LIFT_SCORE isn't a peer bureau score type (it buckets into RESPONSE_MODEL_TIER, per the same
-- script), so no DM_PADM_SCORE_RANGE_RULE_1 row should exist for it and that leg always matched 0 rows.
WITH RAW_SCORES AS
(
    SELECT 'EXPERIAN' AS SOURCE,
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END AS PROSPECT_SEGMENT_TYPE,
           CASE
               WHEN CAMPAIGN_SOURCE = 'V' AND UPPER(MLA_INDICATOR) = 'Y' THEN 'Experian Vantage MLA'
               WHEN CAMPAIGN_SOURCE = 'E' THEN 'Emerging Consumer'
               WHEN CAMPAIGN_SOURCE = 'V' THEN 'Experian Vantage'
               WHEN CAMPAIGN_SOURCE IN ('A','W') THEN 'ABDN'
               WHEN CAMPAIGN_SOURCE = 'C' THEN 'PCO'
               WHEN CAMPAIGN_SOURCE IN ('D','M') THEN 'PDCL'
               WHEN CAMPAIGN_SOURCE IN ('R','N') THEN 'PCL'
               WHEN CAMPAIGN_SOURCE = 'I' THEN 'Remails, Experian Vantage'
               WHEN CAMPAIGN_SOURCE = 'G' THEN 'Remails, Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE IN ('B','J') THEN 'Remails, Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'Q' THEN 'Remails, Prior Decline'
           END AS SOURCE_SEGMENT_NAME,
           UPPER(COALESCE(MLA_INDICATOR, 'N')) AS MLA_FLAG,
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE,
           'VS3' AS BUREAU_SCORE_TYPE, PRESCREEN_VANTAGE_V3 AS RAW_SCORE
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL

    UNION ALL
    SELECT 'EXPERIAN',
           CASE
               WHEN CAMPAIGN_SOURCE IN ('A','W','C','D','M','R','N','G','B','J','Q') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE IN ('V','E') THEN 'PROSPECTING'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE = 'V' AND UPPER(MLA_INDICATOR) = 'Y' THEN 'Experian Vantage MLA'
               WHEN CAMPAIGN_SOURCE = 'E' THEN 'Emerging Consumer'
               WHEN CAMPAIGN_SOURCE = 'V' THEN 'Experian Vantage'
               WHEN CAMPAIGN_SOURCE IN ('A','W') THEN 'ABDN'
               WHEN CAMPAIGN_SOURCE = 'C' THEN 'PCO'
               WHEN CAMPAIGN_SOURCE IN ('D','M') THEN 'PDCL'
               WHEN CAMPAIGN_SOURCE IN ('R','N') THEN 'PCL'
               WHEN CAMPAIGN_SOURCE = 'I' THEN 'Remails, Experian Vantage'
               WHEN CAMPAIGN_SOURCE = 'G' THEN 'Remails, Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE IN ('B','J') THEN 'Remails, Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'Q' THEN 'Remails, Prior Decline'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS4', PRESCREEN_VANTAGE_V4
    FROM CSTONE_BIZ.REFERENCE.T_EXPERIAN_MAILFILE
    WHERE PRESCREEN_VANTAGE_V4 IS NOT NULL

    UNION ALL
    SELECT 'TRANSUNION',
           CASE
               WHEN CAMPAIGN_SOURCE = 'U' THEN 'PROSPECTING'
               WHEN CAMPAIGN_SOURCE IN ('3','4','5','6','7','8','9','L','Z') THEN 'RETARGETING'
               WHEN CAMPAIGN_SOURCE = 'H' AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'RETARGETING'
           END,
           CASE
               WHEN CAMPAIGN_SOURCE = 'U' THEN 'TU'
               WHEN CAMPAIGN_SOURCE IN ('3','4') THEN 'TU Prior Decline'
               WHEN CAMPAIGN_SOURCE IN ('5','6') THEN 'TU Prior Closure'
               WHEN CAMPAIGN_SOURCE = '7' THEN 'TU Prior Charge-Off'
               WHEN CAMPAIGN_SOURCE = 'H' AND CAMPAIGN_SCORE_SEGMENT IN ('02','03','04','05') THEN 'Remails, TU'
               WHEN CAMPAIGN_SOURCE IN ('8','9') THEN 'Remails, TU Prior Closure'
               WHEN CAMPAIGN_SOURCE = 'L' THEN 'Remails, TU Prior Decline'
               WHEN CAMPAIGN_SOURCE = 'Z' THEN 'Remails, TU Charge-Off'
           END,
           UPPER(COALESCE(MLA_INDICATOR, 'N')),
           RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_DATE, 'VS3', PRESCREEN_VANTAGE_V3
    FROM CSTONE_BIZ.REFERENCE.T_TRANSUNION_MAILFILE
    WHERE PRESCREEN_VANTAGE_V3 IS NOT NULL

    -- T_MAP_MAILFILE: existing-customer "multiple account" offers (CAMPAIGN_SOURCE is always 'S'
    -- across the whole table). No RESPONSE_MODEL_TYPE/RISK_SCORE_TYPE column exists here, and
    -- PRESCREEN_VANTAGE_V3 is stored as VARCHAR -- TRY_CAST handles any blank/non-numeric values
    -- gracefully. Classified RETARGETING: this is a repeat-contact offer to a current customer,
    -- not new-prospect outreach.
    UNION ALL
    SELECT 'MAP', 'RETARGETING', 'MAP (existing-customer multiple account offer)',
           'N', NULL, NULL, MAIL_DATE, 'VS3', TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0))
    FROM CSTONE_BIZ.REFERENCE.T_MAP_MAILFILE
    WHERE TRY_CAST(PRESCREEN_VANTAGE_V3 AS NUMBER(10,0)) IS NOT NULL
)
SELECT
      SHA2(
          CONCAT_WS('|', M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, M.PROSPECT_SEGMENT_TYPE,
                     COALESCE(M.MLA_FLAG, ''), COALESCE(M.RESPONSE_MODEL_TYPE, ''), COALESCE(M.RISK_SCORE_TYPE, '')),
          256
      ) AS SEGMENT_KEY
    , M.BUREAU_SCORE_TYPE || ' ' || TO_VARCHAR(R.SCORE_MIN) || '-' || TO_VARCHAR(R.SCORE_MAX) || ' ' || M.SOURCE AS SUGGESTED_SEGMENT_NAME
    , M.SOURCE_SEGMENT_NAME
    , M.SOURCE
    , M.BUREAU_SCORE_TYPE
    , R.SCORE_RANGE_CODE AS BUREAU_SCORE_RANGE
    , R.SCORE_MIN
    , R.SCORE_MAX
    , M.PROSPECT_SEGMENT_TYPE
    , NULL AS ANNUAL_FEE
    , NULL AS NETWORK
    , M.MLA_FLAG
    , M.RESPONSE_MODEL_TYPE
    , M.RISK_SCORE_TYPE
    , NULL AS MAIL_REMAIL
    , COUNT(1) AS SOURCE_RECORD_COUNT
    , MIN(M.MAIL_DATE) AS FIRST_MAIL_DATE
    , MAX(M.MAIL_DATE) AS LAST_MAIL_DATE
FROM RAW_SCORES AS M
INNER JOIN DB_RISK.RISK_SBX.DM_PADM_SCORE_RANGE_RULE_1 AS R
        ON UPPER(M.BUREAU_SCORE_TYPE) = UPPER(R.SCORE_TYPE)
       AND M.RAW_SCORE BETWEEN R.SCORE_MIN AND R.SCORE_MAX
       AND R.ACTIVE_FLAG = TRUE
GROUP BY M.SOURCE, M.BUREAU_SCORE_TYPE, R.SCORE_RANGE_CODE, R.SCORE_MIN, R.SCORE_MAX,
         M.PROSPECT_SEGMENT_TYPE, M.SOURCE_SEGMENT_NAME, M.MLA_FLAG, M.RESPONSE_MODEL_TYPE, M.RISK_SCORE_TYPE;

SELECT SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX,
       COUNT(DISTINCT PROSPECT_SEGMENT_TYPE) AS DISTINCT_PROSPECT_TYPES, SUM(SOURCE_RECORD_COUNT) AS TOTAL_RECORDS
FROM VW_PADM_SEGMENT_SOURCE_CANDIDATE
GROUP BY SOURCE, BUREAU_SCORE_TYPE, BUREAU_SCORE_RANGE, SCORE_MIN, SCORE_MAX
ORDER BY SOURCE, BUREAU_SCORE_TYPE, SCORE_MIN;

UPDATE DM_PADM_ASSUMPTION_DEFINITION
SET ASSUMPTION_LEVEL = 'CAMPAIGN_SEGMENT', UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
WHERE ASSUMPTION_CODE = 'CPP';

MERGE INTO DM_PADM_SEGMENT_1 AS T
USING (
    SELECT SUGGESTED_SEGMENT_NAME AS SEGMENT_NAME, SOURCE AS SOURCE_NAME,
           BUREAU_SCORE_TYPE AS SCORE_TYPE, SCORE_MIN, SCORE_MAX,
           COALESCE(PROSPECT_SEGMENT_TYPE, 'ALL') AS PROSPECT_SEGMENT_TYPE,
           ANNUAL_FEE, NETWORK, MLA_FLAG, RESPONSE_MODEL_TYPE, RISK_SCORE_TYPE, MAIL_REMAIL
    FROM VW_PADM_SEGMENT_SOURCE_CANDIDATE
    WHERE SCORE_MIN IS NOT NULL AND SCORE_MAX IS NOT NULL AND SOURCE IS NOT NULL
      AND BUREAU_SCORE_TYPE IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SOURCE, BUREAU_SCORE_TYPE, SCORE_MIN, SCORE_MAX
        ORDER BY LAST_MAIL_DATE DESC, SOURCE_RECORD_COUNT DESC
    ) = 1
) AS S
ON UPPER(T.SOURCE_NAME) = UPPER(S.SOURCE_NAME) AND UPPER(T.SCORE_TYPE) = UPPER(S.SCORE_TYPE)
   AND T.SCORE_MIN = S.SCORE_MIN AND T.SCORE_MAX = S.SCORE_MAX
WHEN NOT MATCHED THEN INSERT (
    SEGMENT_ID, SEGMENT_NAME, SOURCE_NAME, SCORE_TYPE, SCORE_MIN, SCORE_MAX,
    PROSPECT_SEGMENT_TYPE, ANNUAL_FEE, NETWORK, MLA_FLAG, RESPONSE_MODEL_TYPE,
    RISK_SCORE_TYPE, MAIL_REMAIL, ACTIVE_FLAG, VALID_FROM, ROW_VERSION
) VALUES (
    UUID_STRING(), S.SEGMENT_NAME, S.SOURCE_NAME, S.SCORE_TYPE, S.SCORE_MIN, S.SCORE_MAX,
    S.PROSPECT_SEGMENT_TYPE, S.ANNUAL_FEE, S.NETWORK, S.MLA_FLAG, S.RESPONSE_MODEL_TYPE,
    S.RISK_SCORE_TYPE, S.MAIL_REMAIL, TRUE, CURRENT_DATE(), 1
);

SELECT COUNT(*) AS segment_master_rows FROM DM_PADM_SEGMENT_1 WHERE ACTIVE_FLAG = TRUE;

INSERT INTO DM_PADM_CAMPAIGN_SEGMENT_1
    (CAMPAIGN_SEGMENT_ID, CAMPAIGN_ID, SEGMENT_ID, WORKING_VERSION_NUMBER, SEGMENT_STATUS,
     INITIALIZATION_METHOD, IS_CURRENT, CHANGE_REASON, ROW_VERSION)
SELECT UUID_STRING(), C.CAMPAIGN_ID, S.SEGMENT_ID, C.CURRENT_WORKING_VERSION_NUMBER, 'ACTIVE',
       'SQL_SEED', TRUE, 'Seeded from governed segment pool for demo', 1
FROM DM_PADM_CAMPAIGN_1 C
CROSS JOIN DM_PADM_SEGMENT_1 S
WHERE S.ACTIVE_FLAG = TRUE
  AND NOT EXISTS (SELECT 1 FROM DM_PADM_CAMPAIGN_SEGMENT_1 CS
                  WHERE CS.CAMPAIGN_ID = C.CAMPAIGN_ID AND CS.SEGMENT_ID = S.SEGMENT_ID AND CS.IS_CURRENT = TRUE);

SELECT COUNT(*) AS campaign_segment_links FROM DM_PADM_CAMPAIGN_SEGMENT_1 WHERE IS_CURRENT = TRUE;

